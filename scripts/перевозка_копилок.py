#!/usr/bin/env python3
"""Разовая перевозка трёх markdown-копилок в полку `inbox`.

Живёт в репозитории, а не в плане этапа, по тому же правилу, что и замер
контекста: перевозка, которую нельзя повторить и проверить, — это не перенос,
а надежда на перенос. Скрипт идемпотентен по строке (вид + день + текст):
второй прогон ничего не задвоит.

**Три формата, три разбора, и это не лень.** Копилки писались разным кодом
в разное время, и общий разбор на них врал бы:

- `промахи-памяти.md` — раздел-день, внутри строки `- текст`. Проще некуда.
- `предложения-памяти.md` — то же, но со смысловыми подзаголовками
  («Со слов пользователя», «Выводы коуча») и вычеркнутыми строками `- ~~…~~ — итог`.
- `заявки.md` — блок `- **многострочный текст**` плюс `  Зачем: …`, а разобранная
  помечена не зачёркиванием, а абзацем `**РАЗОБРАНО …**` следом. Правило
  «разобранное вычёркивай» на заявках не соблюдалось ни разу — ровно то,
  ради чего затевался переезд.

Запуск (бот должен быть остановлен — писателей в мозг ноль):

    python3 scripts/перевозка_копилок.py --мозг /brain --база /archive/coach.db
    python3 scripts/перевозка_копилок.py --мозг /brain --база /archive/coach.db --проверить
"""

from __future__ import annotations

import argparse
import re
import sys
from dataclasses import dataclass, field
from datetime import date
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))

from src.inbox import ЗАЯВКА, ПРЕДЛОЖЕНИЕ, ПРОМАХ, СДЕЛАНА, Inbox  # noqa: E402

# Заголовок дня: «## 2026-07-31» и «## 2026-07-31 (перенос из фокус.md …)».
РАЗДЕЛ = re.compile(r"^##\s+(\d{4}-\d{2}-\d{2})")
# Вычеркнутая строка предложения: «- ~~что было~~ — чем кончилось».
ВЫЧЕРКНУТО = re.compile(r"^-\s*~~(?P<текст>.+?)~~\s*(?P<итог>.*)$")


@dataclass
class Запись:
    вид: str
    день: date
    текст: str
    зачем: str = ""
    итог: str = ""

    @property
    def закрыта(self) -> bool:
        return bool(self.итог)


@dataclass
class Разбор:
    записи: list[Запись] = field(default_factory=list)
    жалобы: list[str] = field(default_factory=list)


def _дни(текст: str):
    """Пары (день, строки этого дня). Всё до первого заголовка — шапка, не находки."""
    день: date | None = None
    накоплено: list[str] = []
    for строка in текст.splitlines():
        заголовок = РАЗДЕЛ.match(строка)
        if заголовок:
            if день is not None:
                yield день, накоплено
            день = date.fromisoformat(заголовок.group(1))
            накоплено = []
            continue
        if день is not None:
            накоплено.append(строка)
    if день is not None:
        yield день, накоплено


def разобрать_простую(текст: str, вид: str) -> Разбор:
    """Промахи и предложения: строка `- …` внутри дня — одна запись.

    Подзаголовки вроде «**Выводы коуча …**» пропускаются: они группируют
    строки по смыслу, но записью не являются. Смысл при переезде теряется
    осознанно — в базе то же различие несёт статус: вывод коуча приезжает
    как `новая` и записывается только после подтверждения человеком, ровно
    как и раньше.
    """
    разбор = Разбор()
    for день, строки in _дни(текст):
        for сырая in строки:
            голая = сырая.strip()
            if not голая.startswith("- "):
                continue
            вычеркнута = ВЫЧЕРКНУТО.match(голая)
            if вычеркнута:
                итог = вычеркнутый_итог(вычеркнута.group("итог"))
                разбор.записи.append(
                    Запись(вид, день, вычеркнута.group("текст").strip(), итог=итог)
                )
            else:
                разбор.записи.append(Запись(вид, день, голая[2:].strip()))
    return разбор


def вычеркнутый_итог(хвост: str) -> str:
    """Что приписано после зачёркивания. Пусто — значит «разобрано, итог не назван».

    Пустой итог всё равно закрывает запись: зачёркивание и было отметкой
    «разобрано». Но текст обязателен — полка не принимает закрытие без итога,
    и врать ей нельзя, поэтому говорим прямо, что итог не записали тогда.
    """
    хвост = хвост.lstrip(" —-–").strip()
    return хвост or "разобрано до переезда, итог тогда не записан"


def разобрать_заявки(текст: str) -> Разбор:
    """Заявки: блок `- **…**`, следом `  Зачем: …`, следом, может быть, «РАЗОБРАНО».

    Текст заявки бывает в тридцать строк — владелец надиктовывает целиком,
    вместе с разбором текущего устройства. Поэтому блок собирается до следующего
    маркера, а не до конца строки.
    """
    разбор = Разбор()
    for день, строки in _дни(текст):
        текущая: Запись | None = None
        куда: str | None = None   # «текст» | «зачем» | «итог»
        for сырая in строки:
            голая = сырая.strip()
            if голая.startswith("- **"):
                if текущая:
                    разбор.записи.append(текущая)
                текущая = Запись(ЗАЯВКА, день, голая[2:])
                куда = "текст"
                continue
            if текущая is None:
                continue
            if голая.startswith("Зачем:"):
                текущая.зачем = голая[len("Зачем:"):].strip()
                куда = "зачем"
                continue
            if "РАЗОБРАНО" in голая:
                текущая.итог = голая
                куда = "итог"
                continue
            if not голая:
                continue
            if куда == "текст":
                текущая.текст += "\n" + голая
            elif куда == "зачем":
                текущая.зачем += " " + голая
            elif куда == "итог":
                текущая.итог += " " + голая
        if текущая:
            разбор.записи.append(текущая)

    # Звёздочки жирного снимаем целиком, а не только по краям: заявка писалась
    # одним жирным блоком, поэтому `**` внутри — это шов, оставшийся от вёрстки,
    # а не выделение по смыслу.
    for запись in разбор.записи:
        запись.текст = запись.текст.replace("**", "").strip()
        запись.итог = запись.итог.replace("**", "").strip()
        if not запись.текст:
            разбор.жалобы.append(f"{запись.день}: заявка без текста")
    return разбор


ФАЙЛЫ = (
    ("предложения-памяти.md", ПРЕДЛОЖЕНИЕ),
    ("промахи-памяти.md", ПРОМАХ),
    ("заявки.md", ЗАЯВКА),
)


def прочитать(журнал: Path) -> Разбор:
    """Разобрать все три копилки. Файла нет — не ошибка, а пустая копилка."""
    всё = Разбор()
    for имя, вид in ФАЙЛЫ:
        путь = журнал / имя
        try:
            текст = путь.read_text(encoding="utf-8")
        except OSError:
            всё.жалобы.append(f"{имя}: не читается — пропускаю")
            continue
        разбор = разобрать_заявки(текст) if вид == ЗАЯВКА else разобрать_простую(текст, вид)
        всё.записи += разбор.записи
        всё.жалобы += разбор.жалобы
    return всё


def перевезти(полка: Inbox, разбор: Разбор) -> dict[str, int]:
    """Положить разобранное на полку. Возвращает счёт по видам плюс «закрытых».

    Идемпотентность по (вид, день, текст): прогон второй раз ничего не задвоит.
    Это не роскошь — перевозку почти наверняка придётся повторить после первой
    же найденной кривизны разбора.
    """
    счёт: dict[str, int] = {"всего": 0, "закрытых": 0}
    # Смотрим ВСЕ записи, включая закрытые: перевезённая и сразу закрытая строка
    # иначе приехала бы второй раз при повторном прогоне.
    db = полка._connect()
    try:
        существующие = {
            (вид, день, текст)
            for вид, день, текст in db.execute("SELECT вид, день, текст FROM inbox")
        }
    finally:
        db.close()

    for запись in разбор.записи:
        ключ = (запись.вид, запись.день.isoformat(), запись.текст)
        if ключ in существующие:
            continue
        id_ = полка.положить(запись.вид, запись.текст, зачем=запись.зачем, день=запись.день)
        if запись.закрыта:
            полка.закрыть(id_, СДЕЛАНА, запись.итог, день=запись.день)
            счёт["закрытых"] += 1
        счёт["всего"] += 1
        счёт[запись.вид] = счёт.get(запись.вид, 0) + 1
        существующие.add(ключ)
    return счёт


def main() -> int:
    разбор_доводов = argparse.ArgumentParser(description="Перевозка копилок в полку inbox")
    разбор_доводов.add_argument("--мозг", required=True, type=Path)
    разбор_доводов.add_argument("--база", required=True, type=Path)
    разбор_доводов.add_argument("--проверить", action="store_true",
                                help="только разобрать и показать счёт, в базу не писать")
    доводы = разбор_доводов.parse_args()

    журнал = доводы.мозг / "память" / "журнал"
    разбор = прочитать(журнал)
    по_видам: dict[str, int] = {}
    закрытых = 0
    for запись in разбор.записи:
        по_видам[запись.вид] = по_видам.get(запись.вид, 0) + 1
        закрытых += bool(запись.закрыта)

    print(f"Разобрано: {len(разбор.записи)} записей")
    for вид, число in sorted(по_видам.items()):
        print(f"  {вид}: {число}")
    print(f"  из них закрытых: {закрытых}")
    for жалоба in разбор.жалобы:
        print(f"  ! {жалоба}")

    if доводы.проверить:
        return 0

    счёт = перевезти(Inbox(доводы.база), разбор)
    print(f"\nПеревезено новых: {счёт['всего']} (закрытых {счёт['закрытых']})")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
