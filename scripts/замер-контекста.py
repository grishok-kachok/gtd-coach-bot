#!/usr/bin/env python3
"""Замер контекста зондами: во что обходится каждая строка рюкзака.

Зачем скрипт, если цена каждого хода и так пишется в базу. Журнал `context_cost`
отвечает на вопрос «сколько стоил разговор» — целиком. А чтобы понять, **из чего**
эта сумма складывается, нужен зонд: одинаковый пустой запрос с одной добавленной
строкой и вычитание. По отдельности эти строки в бою не видны никогда: служебный
промпт движка, описания встроенных инструментов, описания кнопок.

Числа получаются вычитанием, а не прикидкой, и потому проверяемы. Живёт скрипт
в репозитории, а не в плане этапа, ровно поэтому: замер, который нельзя
повторить, — это не число, а воспоминание о числе.

Запуск — в контейнере бота, где есть подписка и мост наружу:

    docker exec -w /app gtd-coach-bot python3 scripts/замер-контекста.py
    docker exec -w /app gtd-coach-bot python3 scripts/замер-контекста.py --режимы

Первая форма меряет строки (пол, инструменты, кнопки, конституция), вторая —
четыре режима целиком, как их собирает боевой код.

Осторожно: каждый зонд — настоящий запрос к модели. Их тут около десяти,
и в пустом виде они дёшевы, но бесплатными не являются.
"""

from __future__ import annotations

import argparse
import asyncio
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))

from claude_agent_sdk import ClaudeAgentOptions, ResultMessage, query  # noqa: E402

from src import modes as режимы_модуль  # noqa: E402
from src.context_cost import контекст, разобрать  # noqa: E402

# Реплика зонда одинаковая и нарочно бессмысленная: мы меряем РЮКЗАК, а не
# ответ. Чем короче и предсказуемее вопрос, тем меньше шума в разнице.
РЕПЛИКА = "Ответь одним словом: да."


async def зонд(что: str, **опции) -> int:
    """Сколько токенов уехало в модель при таких настройках."""
    цена = 0
    async for сообщение in query(prompt=РЕПЛИКА, options=ClaudeAgentOptions(**опции)):
        if isinstance(сообщение, ResultMessage):
            цена = контекст(разобрать(сообщение.usage))
    print(f"  {что:<52} {цена:>7} токенов")
    return цена


async def строки() -> None:
    """Разложить рюкзак по строкам вычитанием зондов."""
    print("\nСТРОКИ РЮКЗАКА (каждая — разница двух зондов)\n")

    пол = await зонд("голый движок без всего", system_prompt="", tools=[],
                     setting_sources=[], model=МОДЕЛЬ)
    с_инструментами = await зонд("он же + встроенные инструменты", system_prompt="",
                                 setting_sources=[], model=МОДЕЛЬ)
    с_правилами = await зонд("он же + правила памяти и навыки плагина",
                             system_prompt="", setting_sources=["project"],
                             cwd=str(МОЗГ), plugins=ПЛАГИН, model=МОДЕЛЬ)

    # Проверка, без которой рычаг «встроенные инструменты» опасен: гасит ли
    # `tools=[]` заодно и КНОПКИ. Работник комментариев живёт в фоновом режиме,
    # и без своих шести кнопок он не работник, а собеседник.
    from src.todoist import build_todoist_server
    with_mcp = await зонд(
        "пол + кнопки Todoist (проверка, что MCP выжил)", system_prompt="", tools=[],
        setting_sources=[], model=МОДЕЛЬ,
        mcp_servers={"todoist": build_todoist_server(
            __import__("os").environ["TODOIST_API_TOKEN"], {})},
        allowed_tools=["mcp__todoist"],
    )

    режимы = режимы_модуль.load()
    части: dict[str, int] = {}
    for часть in режимы_модуль.ЧАСТИ:
        текст = режимы_модуль.конституция((часть,))
        части[часть] = await зонд(f"он же + конституция: {часть}", system_prompt=текст,
                                  tools=[], setting_sources=[], model=МОДЕЛЬ) - пол

    print("\nРАЗНИЦЫ\n")
    print(f"  {'пол — движок без встроенных инструментов':<52} {пол:>7}")
    print(f"  {'встроенные инструменты (Read, Write, Bash…)':<52} "
          f"{с_инструментами - пол:>7}")
    # Вычитаем зонд С ИНСТРУМЕНТАМИ, а не пол: правила мерились поверх них.
    # Вычесть пол значило бы записать инструменты в цену правил — ровно та
    # ошибка, из-за которой служебный промпт движка когда-то насчитали
    # в 13 809 токенов и объявили несжимаемым.
    print(f"  {'правила памяти + навыки плагина':<52} "
          f"{с_правилами - с_инструментами:>7}")
    print(f"  {'кнопки Todoist поверх пола':<52} {with_mcp - пол:>7}"
          f"   {'← MCP выжил' if with_mcp > пол else '← MCP ПОГАШЕН ВМЕСТЕ СО ВСТРОЕННЫМИ!'}")
    for часть, цена in части.items():
        байт = len(режимы_модуль.конституция((часть,)).encode('utf-8'))
        курс = байт / цена if цена else 0
        print(f"  {'конституция: ' + часть:<52} {цена:>7}   "
              f"({байт} Б, {курс:.1f} Б/токен)")


async def режимы_целиком() -> None:
    """Померить четыре режима так, как их собирает боевой код."""
    режимы = режимы_модуль.load()
    print("\nРЕЖИМЫ ЦЕЛИКОМ (без окна выжимок — оно из живой базы)\n")
    for имя in режимы_модуль.РОДНЫЕ:
        режим = режимы[имя]
        цена = await зонд(
            f"{режим.значок} {имя}",
            system_prompt=режимы_модуль.конституция(режим.части),
            cwd=str(МОЗГ),
            model=МОДЕЛЬ,
            tools=None if режим.встроенные_инструменты else [],
            setting_sources=["project"] if режим.правила_памяти else [],
            plugins=ПЛАГИН if режим.правила_памяти else [],
        )
        файлы = len(режимы_модуль.файлы_стратегии(МОЗГ, режим.файлы).encode("utf-8"))
        print(f"     + файлы стратегии {файлы} Б ≈ {файлы // 4:>5} токенов "
              f"→ примерно {цена + файлы // 4} без выжимок")


МОДЕЛЬ = "claude-fable-5"
МОЗГ = Path("/brain")
ПЛАГИН = [{"type": "local", "path": "/plugin"}]


async def main() -> None:
    global МОДЕЛЬ, МОЗГ

    разбор = argparse.ArgumentParser(description=__doc__)
    разбор.add_argument("--режимы", action="store_true", help="мерить режимы целиком")
    разбор.add_argument("--модель", default=МОДЕЛЬ)
    разбор.add_argument("--мозг", default=str(МОЗГ))
    аргументы = разбор.parse_args()

    МОДЕЛЬ = аргументы.модель
    МОЗГ = Path(аргументы.мозг)

    if аргументы.режимы:
        await режимы_целиком()
    else:
        await строки()
    print("\nЧисла — из команды, а не с потолка. Записывай их в паспорт с датой.\n")


if __name__ == "__main__":
    asyncio.run(main())
