"""Ночная проверка памяти: не пора ли её обновить и где она за день подвела.

Зачем это вообще. Разбор сессии 31.07 нашёл протечку: коуч каждый день
пользовался наблюдением «ставка на кон заводит», а в модуле знаний его не было
вовсе — оно жило только в выжимках, то есть в окне, которое уезжает вперёд.
Причина не в лени модели, а в разнице механизмов: выжимку пишет код по
будильнику и она случается всегда, а запись в `знания/` держалась на просьбе
в тексте конституции — «увидел паттерн, допиши» — и случалась через раз.

Лекарство ровно одно: повесить проверку памяти на тот же будильник. Ночью,
сразу после выжимки, день перечитывается второй раз — но другими глазами:
не «что произошло», а «что из этого должно осесть в памяти и где память
сегодня не сработала».

Две вещи, которые здесь НЕ делаются намеренно:

1. **Ничего не пишется в `знания/` молча.** Граница из PROJECT.md: факт сказал
   человек — пишется сразу; вывод придумал бот — только после подтверждения.
   Ночью бот человека не спросит, поэтому ночь только предлагает. Записывает
   коуч в разговоре, когда пользователь подтвердил.
2. **Бот не оценивает сам себя.** Исходная идея была «пусть ночью оценивает,
   насколько адекватны критерии выжимки». Так не работает: оценивать нечем —
   он не знает, что выпало, потому что выпавшего у него уже нет. Поэтому мерим
   не самооценку, а **промахи** — наблюдаемые события: полез в архив за тем,
   что должно было быть в выжимке; переспросил то, что пользователь уже говорил.
   Через месяц это список улик, по которому критерии меняет человек
   правкой плагина, а не бот у себя в голове.
"""

from __future__ import annotations

import logging
import re
from datetime import date
from pathlib import Path


from .backrun import прогон
from .notes import append
from .prompts import load as load_prompt

log = logging.getLogger(__name__)

PROPOSALS = "предложения-памяти.md"
MISSES = "промахи-памяти.md"

# Норма копилки предложений: невычеркнутых строк старше двух недель нет.
# Две недели — это два пропущенных недельных обзора подряд, а копилку положено
# разбирать на каждом. Один пропуск — обычная жизнь, два — уже долг.
#
# Порог нужен именно потому, что сторож, кричащий каждый день, приучает себя
# не читать (решение 03.08 про строку паспорта без `bytes`). Свежая находка
# ждёт ближайшего обзора и отклонением не считается.
ЗАСТОЙ_ДНЕЙ = 14

# Раздел копилки — день, под заголовком которого лежат строки находок.
_РАЗДЕЛ = re.compile(r"^##\s+(\d{4}-\d{2}-\d{2})")


def застой(path: Path, сегодня: date, порог: int = ЗАСТОЙ_ДНЕЙ) -> tuple[int, str]:
    """Сколько строк копилки висят невычеркнутыми дольше нормы и с какого дня.

    Вычеркнутая строка начинается с `- ~~`. Другой отметки «разобрано» у копилки
    нет и заводить её не надо: зачёркивание видно человеку глазами и машине
    разбором, а лишнее поле в накопительном файле — второй дом одного факта.

    Строка принадлежит тому дню, под чьим заголовком лежит. Всё, что выше
    первого заголовка (шапка заметки, объяснение), не считается вовсе —
    там нет находок.

    Файла нет — застоя нет, а не ошибка: копилка заводится первой находкой.
    """
    try:
        текст = path.read_text(encoding="utf-8")
    except OSError:
        return 0, ""

    висит = 0
    самая_старая = ""
    день: date | None = None
    for строка in текст.splitlines():
        заголовок = _РАЗДЕЛ.match(строка)
        if заголовок:
            день = date.fromisoformat(заголовок.group(1))
            continue
        голая = строка.lstrip()
        if день is None or not голая.startswith("- ") or голая.startswith("- ~~"):
            continue
        if (сегодня - день).days < порог:
            continue
        висит += 1
        if not самая_старая or день.isoformat() < самая_старая:
            самая_старая = день.isoformat()
    return висит, самая_старая


class MemoryWatch:
    """Второй ночной вопрос к прожитому дню — про саму память."""

    def __init__(self, brain_dir: Path, model: str = "claude-fable-5",
                 mode=None, cost=None) -> None:
        self.brain_dir = brain_dir
        self.model = model
        # Фоновый режим. Проверка памяти ЧИТАЕТ знания, но читает их не сама —
        # текст подкладывается в промпт кодом, поэтому встроенные инструменты
        # ей не нужны, а правила записи не нужны тем более: она предлагает,
        # а записывает потом коуч в разговоре.
        self.mode = mode
        self.cost = cost
        self.journal = brain_dir / "память" / "журнал"

    async def _ask(self, prompt: str, system: str) -> str:
        return await прогон(
            mode=self.mode, prompt=prompt, system=system, model=self.model,
            effort="high",  # раз в сутки — экономить нечего
            cost=self.cost, channel="проверка памяти", что="проверка памяти",
        )

    def _knowledge(self) -> str:
        """Что коуч знает про пользователя сегодня — чтобы не предлагать записанное."""
        parts = []
        for folder in ("знания", "состояние"):
            for path in sorted((self.brain_dir / "память" / folder).glob("*.md")):
                parts.append(f"--- {folder}/{path.name} ---\n{path.read_text(encoding='utf-8')}")
        return "\n\n".join(parts)

    @staticmethod
    def _section(answer: str, name: str) -> list[str]:
        """Достать раздел ответа. Разбор нарочно тупой: модель отвечает по форме."""
        lines = []
        inside = False
        for line in answer.splitlines():
            head = line.strip().rstrip(":").upper()
            if head in ("ФАКТЫ", "ВЫВОДЫ", "ПРОМАХИ"):
                inside = head == name
                continue
            if inside and line.strip().startswith("-"):
                body = line.strip()[1:].strip()
                if body and body.lower() != "нет":
                    lines.append(body)
        return lines

    async def run(self, day: date, transcript: str) -> dict[str, int]:
        """Перечитать день глазами памяти. Возвращает, сколько чего нашлось."""
        if len(transcript) < 200:
            return {"факты": 0, "выводы": 0, "промахи": 0}

        prompt = load_prompt("проверка-памяти")
        answer = await self._ask(
            prompt.format(day=day.isoformat(), knowledge=self._knowledge(), transcript=transcript),
            prompt.system,
        )
        facts = self._section(answer, "ФАКТЫ")
        conclusions = self._section(answer, "ВЫВОДЫ")
        misses = self._section(answer, "ПРОМАХИ")

        if facts or conclusions:
            block = f"\n## {day.isoformat()}\n\n"
            if facts:
                block += "**Со слов пользователя — можно записывать сразу:**\n"
                block += "".join(f"- {item}\n" for item in facts) + "\n"
            if conclusions:
                block += "**Выводы коуча — сначала спросить пользователя:**\n"
                block += "".join(f"- {item}\n" for item in conclusions) + "\n"
            append(
                self.journal / PROPOSALS, day=day, block=block,
                title="предложения-памяти", heading="Что стоит записать в память",
                note="Собирает ночной прогон (`src/memory_watch.py`). Это ВХОДЯЩИЕ, а не память: "
                     "факты со слов пользователя коуч переносит в `знания/` сам, выводы — только "
                     "после того, как пользователь подтвердил. Разобрал — вычеркни строку и "
                     "припиши, чем кончилось: `- ~~строка~~ — куда уехало или почему отклонено`. "
                     "Отклонённое вычёркивается наравне с принятым: невычеркнутое значит "
                     "«ещё не разбирали». Норма — невычеркнутых строк старше двух недель нет.",
                ref="ночная проверка памяти, накопительный список",
                author="агент-коуч (ночная проверка памяти)", tags="проверка-памяти",
            )

        if misses:
            block = f"\n## {day.isoformat()}\n\n" + "".join(f"- {item}\n" for item in misses)
            append(
                self.journal / MISSES, day=day, block=block,
                title="промахи-памяти", heading="Копилка промахов памяти",
                note="Собирает ночной прогон (`src/memory_watch.py`). Промах — наблюдаемое событие: "
                     "коуч полез в архив за тем, что должно было быть в памяти, или переспросил "
                     "сказанное. Это улики для человека: по ним меняются критерии "
                     "выжимки. Бот свои критерии не меняет.",
                ref="ночная проверка памяти, накопительный список улик",
                author="агент-коуч (ночная проверка памяти)", tags="проверка-памяти",
            )

        found = {"факты": len(facts), "выводы": len(conclusions), "промахи": len(misses)}
        log.info("ночная проверка памяти за %s: %s", day, found)
        return found

    def залежалось(self, сегодня: date) -> tuple[int, str]:
        """Что висит в копилке предложений дольше нормы: сколько строк и с какого дня.

        Мерим **только предложения**. У промахов другая природа: это улики,
        которые копятся до тех пор, пока не сложится картина («три промаха
        про одно и то же — значит в памяти нет целого раздела»), и вычёркивает
        их человек сам, когда починил причину правкой кода. Копилка, которой
        положено накапливаться, отклонением быть не может.
        """
        висит, старая = застой(self.journal / PROPOSALS, сегодня)
        if висит:
            log.info("копилка предложений: %d строк не вычеркнуто, самая старая от %s",
                     висит, старая)
        return висит, старая
