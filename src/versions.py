"""Из чего собран GTD-коуч и что из этого уже устарело.

**GTD-коуч — это продукт целиком**, а не телеграм-часть. Он собран из пяти
частей, и каждая обновляется отдельно:

| Часть | Что это | Где живёт |
|---|---|---|
| бот | докер, телеграм, поллинг | образ, собранный из `gtd-coach-bot` |
| плагин | роль, навыки, методология, режимы | смонтированный клон `gtd-coach` |
| `todoist-mcp` | инструменты списка дел | смонтированный клон |
| `gcal-mcp` | инструменты календаря | смонтированный клон |
| движок | Claude Code, которым коуч думает | npm-пакет в образе |

Мозга здесь нет намеренно: он не часть поставки, а то, что в неё наливается —
приватный репозиторий у каждого свой, обновлять там нечего.

**Почему версия бота берётся из образа, а не из клона.** Код бота лежит внутри
образа, `.git` рядом с ним нет. Смотреть HEAD клона было бы враньём: «клон
подтянут, образ не пересобран» — штатное состояние, и 31.07.2026 выкатка ровно
на нём отрапортовала успех при живом контейнере со старым кодом. Поэтому у бота
два числа: что **работает** (вшито в образ) и что **лежит** (HEAD клона).

**Почему координаты репозитория берутся из `git remote`, а не зашиты.** Ученик
может форкнуть любую часть; зашитый в код `vefmvai/...` спрашивал бы у чужого
репозитория, свежая ли моя копия.

**Почему `-c safe.directory`.** Клоны на сервере принадлежат человеку (uid 1001),
а контейнер работает под 1000, и git отказывается читать чужой репозиторий:
`detected dubious ownership`. Проверено внутри живого контейнера 02.08.2026.
"""

from __future__ import annotations

import asyncio
import logging
import os
import re
import subprocess
from dataclasses import dataclass
from pathlib import Path

import httpx

log = logging.getLogger(__name__)

ПРОДУКТ = "GTD-коуч"

# npm-имя движка. Оно же стоит в Dockerfile — там его ставят, здесь спрашивают.
ДВИЖОК_ПАКЕТ = "@anthropic-ai/claude-code"
ДВИЖОК_РЕЕСТР = f"https://registry.npmjs.org/{ДВИЖОК_ПАКЕТ}/latest"

# Сколько ждём чужой сервис. Проверка версий — фоновая работа, торопиться ей
# некуда, но и висеть в ночном прогоне она не должна.
ТАЙМАУТ = 15.0


@dataclass(frozen=True)
class Часть:
    """Кусок продукта, у которого есть своя версия."""

    имя: str
    # Где лежит `.git` этой части. У плагина это его же смонтированный клон,
    # у остальных — отдельно смонтированная папка `.git` (см. docker-compose).
    git_dir: Path
    # У бота версия берётся из образа, а не из клона: см. заголовок модуля.
    из_образа: bool = False


def части() -> tuple[Часть, ...]:
    """Четыре части с git-версией. Пути переопределяются окружением — тем же

    приёмом, что и всё остальное в боте: в контейнере одно, в тестах другое.
    """
    корень = Path(os.environ.get("REPOS_DIR", "/repos"))
    плагин = Path(os.environ.get("PLUGIN_DIR", "/plugin"))
    return (
        Часть("бот", корень / "gtd-coach-bot.git", из_образа=True),
        Часть("плагин", плагин / ".git"),
        Часть("todoist-mcp", корень / "todoist-mcp.git"),
        Часть("gcal-mcp", корень / "gcal-mcp.git"),
    )


@dataclass
class Состояние:
    """Что с одной частью: что работает, что новее, что непонятно."""

    имя: str
    стоит: str = ""      # что работает прямо сейчас
    новее: str = ""      # что лежит в источнике, если оно другое
    отстал_на: int = 0   # на сколько коммитов, если удалось посчитать
    клон: str = ""       # HEAD клона на диске — с ним и сверяемся с GitHub
    лежит: str = ""      # подтянуто в клон, но ещё не собрано (только у бота)
    заметка: str = ""    # «не установлен», «сборка неизвестна», «не проверил»

    @property
    def устарело(self) -> bool:
        return bool(self.новее)


# ── местное: что стоит ────────────────────────────────────────────────────────

def _git(git_dir: Path, *args: str) -> str:
    """Спросить git про репозиторий по пути к его `.git`. Не вышло — пусто.

    Пусто здесь не «ошибка», а «этой части нет»: у ученика без календаря
    папки не существует, и это нормальное состояние, а не поломка.
    """
    try:
        готово = subprocess.run(
            ["git", "-c", f"safe.directory={git_dir}", f"--git-dir={git_dir}", *args],
            capture_output=True, text=True, timeout=10,
        )
    except (OSError, subprocess.SubprocessError) as сбой:
        log.debug("git %s в %s не вышел: %s", args, git_dir, сбой)
        return ""
    if готово.returncode != 0:
        log.debug("git %s в %s: %s", args, git_dir, готово.stderr.strip())
        return ""
    return готово.stdout.strip()


# Координаты на GitHub из адреса origin. Оба вида: ssh (`git@github.com:o/r.git`)
# и https (`https://github.com/o/r.git`). Чужой хост — не наш случай: спрашивать
# про версию мы умеем только у GitHub, и врать про это не надо.
#
# Хост сверяем по вхождению слова, а не по точному `github.com`. Куплено первым
# же прогоном на живом сервере 02.08.2026: там у каждого клона **свой ssh-алиас
# под свой deploy-ключ** — `git@github-gtd-coach-bot:vefmvai/gtd-coach-bot.git`.
# Точное совпадение не находило ни одной из четырёх частей, и ночь молчала бы
# про обновления навсегда — не сломавшись и ничего не сказав.
АДРЕС = re.compile(
    r"(?P<host>[\w.-]*github[\w.-]*)[:/](?P<owner>[^/:]+)/(?P<repo>[^/]+?)(?:\.git)?/?$"
)


def координаты(url: str) -> str:
    """`git@github.com:vefmvai/todoist-mcp.git` → `vefmvai/todoist-mcp`."""
    найдено = АДРЕС.search((url or "").strip())
    return f"{найдено['owner']}/{найдено['repo']}" if найдено else ""


def местное(часть: Часть) -> Состояние:
    """Что стоит у этой части прямо сейчас."""
    состояние = Состояние(имя=часть.имя)
    head = _git(часть.git_dir, "rev-parse", "HEAD")
    состояние.клон = head[:7]
    if часть.из_образа:
        вшито = (os.environ.get("GIT_SHA") or "").strip()
        состояние.стоит = вшито[:7]
        if not вшито:
            # Собирали не командой обновления — так выглядит первая установка
            # по README. Врать нечем: что в образе, снаружи не видно.
            #
            # Но сверяться с GitHub это не мешает и мешать не должно: сверяем
            # тогда клон, он на диске и он же поедет в следующую сборку.
            # Иначе у поставившего коуча впервые ночь молчала бы про бота
            # ровно до того дня, когда он первый раз запустит ./update.sh, —
            # то есть до дня, о котором он и должен был узнать от неё.
            состояние.заметка = "сборка неизвестна"
        elif head and not head.startswith(вшито[:7]):
            состояние.лежит = head[:7]
        if not head and not вшито:
            состояние.заметка = "не установлен"
        return состояние
    if not head:
        состояние.заметка = "не установлен"
        return состояние
    состояние.стоит = head[:7]
    return состояние


def адрес(часть: Часть) -> tuple[str, str]:
    """Координаты на GitHub и ветка, за которой следим."""
    коорд = координаты(_git(часть.git_dir, "remote", "get-url", "origin"))
    # Отделённая голова — не ошибка (так лежит клон, откаченный на коммит назад
    # ради проверки), но ветки у неё нет. Тогда main: за ним и следим.
    ветка = _git(часть.git_dir, "symbolic-ref", "--short", "HEAD") or "main"
    return коорд, ветка


def движок_местный() -> str:
    """Версия Claude Code, вшитая в образ. Ставит её Dockerfile, он же и говорит."""
    return (os.environ.get("CLAUDE_CODE_VERSION") or "").strip()


# ── удалённое: что новее ──────────────────────────────────────────────────────

def числа(версия: str) -> tuple[int, ...]:
    """`2.10.0` → `(2, 10, 0)`. Строкой такие версии сравнивать нельзя:

    «2.9.9» больше «2.10.0» по алфавиту и меньше по смыслу.
    """
    return tuple(int(кусок) for кусок in re.findall(r"\d+", версия))


def версия_новее(есть: str, вышла: str) -> bool:
    return bool(есть) and bool(вышла) and числа(вышла) > числа(есть)


async def _свежий_sha(клиент: httpx.AsyncClient, коорд: str, ветка: str) -> str:
    ответ = await клиент.get(
        f"https://api.github.com/repos/{коорд}/commits/{ветка}",
        headers={"Accept": "application/vnd.github+json"},
    )
    ответ.raise_for_status()
    return (ответ.json().get("sha") or "")[:7]


async def _отставание(клиент: httpx.AsyncClient, коорд: str, было: str, стало: str) -> int:
    """На сколько коммитов отстали. Не вышло — ноль: число тут украшение,

    а повод дёрнуть за рукав даёт сам факт расхождения.
    """
    try:
        ответ = await клиент.get(f"https://api.github.com/repos/{коорд}/compare/{было}...{стало}")
        ответ.raise_for_status()
        return int(ответ.json().get("ahead_by") or 0)
    except Exception as сбой:
        log.debug("не посчитал отставание %s: %s", коорд, сбой)
        return 0


async def _свежий_движок(клиент: httpx.AsyncClient) -> str:
    ответ = await клиент.get(ДВИЖОК_РЕЕСТР)
    ответ.raise_for_status()
    return (ответ.json().get("version") or "").strip()


# ── всё вместе ────────────────────────────────────────────────────────────────

async def проверить(таймаут: float = ТАЙМАУТ) -> list[Состояние]:
    """Пять строк: что стоит и что новее. Сеть отвалилась — говорим это вслух.

    Молчаливое «всё свежее» при мёртвой сети было бы худшим из ответов: сторож,
    который не может проверить, обязан сказать «не проверил», а не «всё хорошо».
    """
    отчёт: list[Состояние] = []
    # Прокси берётся из окружения (HTTPS_PROXY): GitHub и npm из РФ идут через
    # тот же мост, что и всё остальное. `trust_env` у httpx включён по умолчанию.
    async with httpx.AsyncClient(timeout=таймаут, follow_redirects=True) as клиент:
        for часть in части():
            состояние = await asyncio.to_thread(местное, часть)
            отчёт.append(состояние)
            if состояние.заметка == "не установлен":
                continue
            коорд, ветка = await asyncio.to_thread(адрес, часть)
            if not коорд:
                состояние.заметка = "не знаю, где смотреть обновления"
                continue
            # Сверяемся с тем, что ЛЕЖИТ в клоне, а не с тем, что собрано:
            # «есть новее на GitHub» — это про клон, его и надо тянуть. Иначе
            # после `git pull` без пересборки бот сообщал бы про новое дважды —
            # и как «есть новее», и как «лежит, не собрано».
            основание = состояние.клон or состояние.стоит
            try:
                свежий = await _свежий_sha(клиент, коорд, ветка)
            except Exception as сбой:
                log.warning("не спросил GitHub про %s: %s", коорд, сбой)
                состояние.заметка = "не проверил — GitHub не ответил"
                continue
            if свежий and основание and not свежий.startswith(основание[:7]):
                состояние.новее = свежий
                состояние.отстал_на = await _отставание(клиент, коорд, основание, свежий)

        движок = Состояние(имя="движок", стоит=движок_местный())
        if not движок.стоит:
            движок.заметка = "версия неизвестна"
        else:
            try:
                вышла = await _свежий_движок(клиент)
            except Exception as сбой:
                log.warning("не спросил npm про движок: %s", сбой)
                движок.заметка = "не проверил — npm не ответил"
            else:
                if версия_новее(движок.стоит, вышла):
                    движок.новее = вышла
        отчёт.append(движок)
    return отчёт


def устаревшие(отчёт: list[Состояние]) -> tuple[list[Состояние], Состояние | None]:
    """Разложить найденное по двум поводам: репозитории и движок.

    Поводы разные, потому что разные действия. Репозитории обновляются командой
    `./update.sh`; движок запинен намеренно (инцидент 30.07.2026, когда
    непиненная пересборка молча привезла другой мозг) и поднимается человеком
    отдельным осознанным коммитом. В одну задачу их мешать нельзя: задача
    обязана говорить, что делать руками.
    """
    репозитории = [с for с in отчёт if с.устарело and с.имя != "движок"]
    движок = next((с for с in отчёт if с.имя == "движок" and с.устарело), None)
    return репозитории, движок


# ── как это читается человеком ────────────────────────────────────────────────

# Значки читаются раньше слов, поэтому они и есть ответ на вопрос «всё ли
# в порядке». Три состояния, а не два: «свежий», «есть что делать» и «не знаю».
# Квадратик, стоявший здесь сначала, не говорил ничего — владелец посмотрел
# на живой ответ и сказал прямо: непонятно, актуальная версия или нет.
СВЕЖИЙ, ВНИМАНИЕ, НЕЯСНО = "✅", "🔸", "❓"


def строка(с: Состояние) -> str:
    """Одна часть одной строкой: значок, имя, версия и что с ней не так."""
    хвост = []
    if с.новее:
        сколько = f", +{с.отстал_на}" if с.отстал_на else ""
        хвост.append(f"есть новее: {с.новее}{сколько}")
    if с.лежит:
        хвост.append(f"подтянут {с.лежит}, но не собран")
    if с.заметка:
        хвост.append(с.заметка)
    if с.новее or с.лежит:
        значок = ВНИМАНИЕ          # есть что сделать руками
    elif с.заметка:
        значок = НЕЯСНО            # не установлен, не проверил, сборка неизвестна
    else:
        значок = СВЕЖИЙ
        хвост.append("свежий")     # словами тоже: значок могут не разглядеть
    стоит = с.стоит or с.клон or "—"
    return f"{значок} {с.имя} · {стоит}" + (f" — {'; '.join(хвост)}" if хвост else "")


def отчёт_текстом(отчёт: list[Состояние]) -> str:
    """Шапка «GTD-коуч», под ней пять частей.

    Шапка не украшение: без неё это читается как пять отдельных хозяйств,
    а обновляются они одной командой и являются одной вещью.
    """
    строки = "\n".join(строка(с) for с in отчёт)
    репозитории, движок = устаревшие(отчёт)
    низ = []
    if репозитории:
        низ.append("Обновиться: на сервере `./update.sh` в папке бота.")
    if движок:
        низ.append(
            f"Движок {движок.стоит} → {движок.новее} поднимается вручную: "
            "версия запинена в Dockerfile намеренно."
        )
    if not репозитории and not движок:
        низ.append("Всё свежее, делать нечего.")
    return f"{ПРОДУКТ}\n\n{строки}\n\n" + "\n".join(низ)
