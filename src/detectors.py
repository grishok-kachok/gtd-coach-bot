"""Сторож завалов: то, чего человек в своём списке дел не видит.

Коуч до сих пор смотрел на дела, только когда его спросили, и видел ровно то,
что видит человек: «сегодня» и «просрочено». А завал — это не задача, это
**отношение между задачами и временем**: на четверг набито вшестеро больше,
чем в него влезает; вот это дело переехало пятый раз; четыре задачи лежат
без даты и потому не всплывут никогда.

Три правила, по которым это устроено.

**Считает код, говорит коуч.** Здесь нет ни одного вызова модели: детекторы —
чистая арифметика над Todoist, календарём и снимками. Свод подкладывается
в утренний чек-ин, а что назвать главным и как сказать — суждение, и оно
остаётся коучу. Правило проекта: обязательное делает код, суждение — модель.

**У прибора есть исправное состояние.** Список без нормы — это просто список,
по нему нельзя сказать «в порядке». Нормы объявлены здесь один раз и отсюда же
берутся дашбордом: до 01.08 они жили в `dashboard.py`, и второй потребитель
завёл бы им второй дом — ровно то, что этап 14 лечил у списка инструментов.

**Молчание — это ответ.** Всё в норме — свод пуст, и коуч про проверку молчит.
Отчёт о пустой проверке приучает не читать отчёты.
"""

from __future__ import annotations

import logging
import os
import sqlite3
from collections import Counter
from dataclasses import dataclass, field
from datetime import date, datetime, timedelta
from pathlib import Path
from zoneinfo import ZoneInfo

from todoist_mcp.client import TodoistClient, TodoistError

log = logging.getLogger(__name__)

# Вес задачи — время, а не штука. Метки заведены владельцем (этап 03),
# от тарифа не зависят, в отличие от платного поля `duration`.
МИНУТЫ = {"⏱️S": 20, "⏱️M": 120, "⏱️L": 240}

# Приборы панели: у каждого свой вопрос и своё исправное состояние.
# Порог «В игре» намеренно не назначен — считается по данным через год.
GAUGES = (
    ("Потеряшки", "@актив & no date", "пусто"),
    ("Ждёт ответа", "@ждёт & (overdue | no date)", "пусто"),
    ("Inbox", "#Inbox", "0"),
    ("Просрочено", "overdue", "пусто"),
    ("В игре", "@актив & !no date", "—"),
)

# Сколько переносов подряд считаем хроникой. Три, а не два: один перенос —
# жизнь, второй — совпадение, третий — уже свойство задачи. Число здесь,
# а не в тексте промпта, потому что его положено менять по прожитому.
ХРОНИКА = 3

# Окно, в котором ищем переносы. Месяц: короче — не наберётся статистики,
# длиннее — вспомним то, что человек уже разрулил.
ОКНО_ПЕРЕНОСОВ = 30

# Рабочий день, когда календарь недоступен. Не 24 часа: спать и жить тоже надо,
# а перегруз, посчитанный от суток, не сработает никогда.
ДЕНЬ_ЧАСОВ = 8.0


@dataclass(frozen=True)
class Отклонение:
    """Прибор вне нормы. `строка` — то, что увидит коуч; остальное для порядка."""

    класс: str      # чем это лечится: «завал», «прибор», «мелочь»
    имя: str
    строка: str


@dataclass
class Свод:
    """Что сторож увидел за один обход."""

    отклонения: list[Отклонение] = field(default_factory=list)
    в_норме: list[str] = field(default_factory=list)
    жалобы: list[str] = field(default_factory=list)  # чего не удалось посмотреть

    def пусто(self) -> bool:
        return not self.отклонения

    def текст(self) -> str:
        """Свод для подстановки в чек-ин. Пусто — пустая строка, и это ответ."""
        if self.пусто() and not self.жалобы:
            return ""
        куски = [f"- {о.строка}" for о in self.отклонения]
        if self.в_норме:
            куски.append(f"- В норме: {', '.join(self.в_норме)}.")
        куски += [f"- Не посмотрел: {ж}" for ж in self.жалобы]
        return "Ночной обход дел (посчитано кодом, не пересказ):\n" + "\n".join(куски)


# ── время ────────────────────────────────────────────────────────────────────

def _зона() -> ZoneInfo:
    return ZoneInfo(os.environ.get("COACH_TZ") or "Europe/Moscow")


def _сегодня() -> date:
    return datetime.now(_зона()).date()


def _срок(задача: dict) -> date | None:
    сырое = (задача.get("due") or {}).get("date") or ""
    try:
        return date.fromisoformat(сырое[:10])
    except ValueError:
        return None


def _часы(задачи: list[dict]) -> float:
    минут = sum(МИНУТЫ.get(м, 0) for з in задачи for м in з.get("labels") or [])
    return round(минут / 60, 1)


# ── чтение Todoist ───────────────────────────────────────────────────────────

async def по_фильтру(client: TodoistClient, запрос: str, limit: int = 100) -> list[dict]:
    """Задачи по запросу Todoist. Не ответил — пусто и жалоба в лог."""
    try:
        data = await client.get("/tasks/filter", params={"query": запрос, "limit": limit})
    except TodoistError as err:
        log.warning("прибор «%s» не снялся: %s", запрос, err)
        return []
    return data.get("results", []) if isinstance(data, dict) else (data or [])


async def цели(client: TodoistClient) -> list[dict]:
    """Работа по каждой цели: сколько дел, сколько с датой, ближайший шаг.

    **Работа по цели — это карточка ПЛЮС всё, что под ней.** Метка на подзадачи
    не наследуется, а карточка-замысел по методологии без даты: сроки живут
    у подзадач. Считать только помеченное — значит объявить спящей цель «Бали»
    с тридцатью задачами и датами (поймано на живом аккаунте 31.07).

    Помеченное вне карточки тоже считается: метка на то и заведена, чтобы
    собирать работу по цели, где бы та ни лежала.
    """
    try:
        все = await client.get_paginated("/tasks", params={"limit": 200}, cap=1000)
    except TodoistError as err:
        log.warning("задачи для целей не забрались: %s", err)
        return []
    return цели_из(все)


def цели_из(все: list[dict]) -> list[dict]:
    """То же, но по уже собранному списку задач: лишний раз Todoist не дёргаем."""
    дети: dict[str, list[dict]] = {}
    for задача in все:
        if задача.get("parent_id"):
            дети.setdefault(задача["parent_id"], []).append(задача)

    def потомки(корни: list[dict]) -> list[dict]:
        собрано, очередь = [], list(корни)
        while очередь:
            узел = очередь.pop()
            собрано.append(узел)
            очередь.extend(дети.get(узел["id"], []))
        return собрано

    имена = sorted({
        метка for задача in все for метка in (задача.get("labels") or [])
        if метка.startswith("цель-")
    })

    собранные = []
    for имя in имена:
        помеченные = [з for з in все if имя in (з.get("labels") or [])]
        работа = {з["id"]: з for з in потомки(помеченные)}
        сроки = sorted(
            (з.get("due") or {}).get("date", "")[:10]
            for з in работа.values() if (з.get("due") or {}).get("date")
        )
        собранные.append({
            "имя": имя.removeprefix("цель-"),
            "всего": len(работа),
            "с_датой": len(сроки),
            "ближайший": сроки[0] if сроки else "",
        })
    return собранные


# ── детекторы ────────────────────────────────────────────────────────────────

def перегруз(задачи: list[dict], свободно: dict[str, float],
             дней: int = 7) -> list[Отклонение]:
    """Дни, куда набито больше, чем в них влезает.

    Свободные часы берутся из календаря: сутки — не мера, потому что три
    встречи по два часа съедают день, а список дел об этом не знает.
    Календарь молчит — считаем от рабочего дня и говорим, что считали так.
    """
    начало = _сегодня()
    по_дням: dict[date, list[dict]] = {}
    for задача in задачи:
        когда = _срок(задача)
        if когда and начало <= когда < начало + timedelta(days=дней):
            по_дням.setdefault(когда, []).append(задача)

    найдено = []
    for когда in sorted(по_дням):
        часов = _часы(по_дням[когда])
        если_бы = свободно.get(когда.isoformat())
        вместимость = если_бы if если_бы is not None else ДЕНЬ_ЧАСОВ
        if часов <= вместимость or not часов:
            continue
        откуда = "по календарю" if если_бы is not None else "рабочий день без календаря"
        найдено.append(Отклонение(
            "завал", "Перегруз дня",
            f"{когда.strftime('%d.%m')}: дел на {часов} ч, свободно {вместимость} ч "
            f"({откуда}), задач {len(по_дням[когда])}.",
        ))
    return найдено[:2]  # две худшие даты; остальное коуч спросит инструментом


def баланс_недели(задачи: list[dict], дней: int = 7) -> list[Отклонение]:
    """Всё свалено в один день при пустых соседних.

    Это не то же самое, что перегруз: день может влезать в норму и всё равно
    быть горкой рядом с двумя пустыми — и тогда лечится не отказом, а сдвигом.
    """
    начало = _сегодня()
    часы: dict[date, float] = {}
    for сдвиг in range(дней):
        когда = начало + timedelta(days=сдвиг)
        часы[когда] = _часы([з for з in задачи if _срок(з) == когда])
    if not any(часы.values()):
        return []
    горка = max(часы, key=lambda d: часы[d])
    ямы = [d for d, ч in часы.items() if ч == 0]
    if часы[горка] < 3 or len(ямы) < 2:
        return []
    return [Отклонение(
        "завал", "Баланс недели",
        f"Неделя перекошена: {горка.strftime('%d.%m')} — {часы[горка]} ч, "
        f"а {', '.join(d.strftime('%d.%m') for d in ямы[:3])} пусты.",
    )]


def мелочь(задачи: list[dict], сколько: int = 3) -> list[Отклонение]:
    """Дела на двадцать минут, которые можно закрыть заодно.

    Берём короткие без даты и просроченные короткие: они не всплывут сами,
    а закрываются между делом. Это единственный детектор, который не ругается,
    а предлагает лёгкое — он про то, чтобы день начался с движения.
    """
    сегодня = _сегодня()
    короткие = [
        з for з in задачи
        if "⏱️S" in (з.get("labels") or [])
        and (_срок(з) is None or _срок(з) < сегодня)
        and not з.get("parent_id")
    ]
    if not короткие:
        return []
    имена = ", ".join(f"«{з.get('content', '')}»" for з in короткие[:сколько])
    return [Отклонение(
        "мелочь", "Мелочь дня",
        f"На 20 минут, можно закрыть заодно ({len(короткие)} шт.): {имена}.",
    )]


def хронические_переносы(db_path: Path, окно: int = ОКНО_ПЕРЕНОСОВ,
                         порог: int = ХРОНИКА) -> list[Отклонение]:
    """Задачи, которые переезжают снова и снова.

    Перенос — не лень, а признак: задача либо великовата, либо страшновата,
    либо не своя. Лечится дроблением или отказом, но сначала её надо увидеть.
    Данные берём из своих снимков: на бесплатном тарифе журнал Todoist живёт
    около недели, а снимок помнит всё.
    """
    if not db_path.exists():
        return []
    порог_дня = (_сегодня() - timedelta(days=окно)).isoformat()
    try:
        with sqlite3.connect(db_path) as db:
            строки = db.execute(
                "SELECT task_id, content FROM todoist_diff"
                " WHERE kind = 'перенесена' AND day >= ?", (порог_дня,),
            ).fetchall()
    except sqlite3.Error as err:
        log.warning("переносы не читаются: %s", err)
        return []

    счёт = Counter(task_id for task_id, _ in строки)
    имена = {task_id: content for task_id, content in строки}
    хроники = [(имена.get(t, ""), n) for t, n in счёт.most_common() if n >= порог]
    if not хроники:
        return []
    перечень = ", ".join(f"«{имя}» — {n} раз" for имя, n in хроники[:3])
    return [Отклонение(
        "завал", "Хронические переносы",
        f"Переезжает не первый раз ({len(хроники)} шт. за {окно} дней): {перечень}. "
        f"Обычно это значит «великовато» или «не своё».",
    )]


def без_размера(задачи: list[dict]) -> list[Отклонение]:
    """Активные задачи без метки размера.

    Правило «оценивай время каждой задаче» действует с 20.07 и на 01.08 живо
    на 42 % (59 задач из 140). Правило без прибора не выполняется, сколько бы
    раз его ни записали, — поэтому у него появился прибор.
    """
    активные = [з for з in задачи if "актив" in (з.get("labels") or [])]
    без = [з for з in активные if not any(м in МИНУТЫ for м in з.get("labels") or [])]
    if not без or not активные:
        return []
    доля = round(100 * len(без) / len(активные))
    return [Отклонение(
        "прибор", "Без размера",
        f"Без метки размера {len(без)} активных задач из {len(активные)} ({доля} %). "
        f"Без размера не посчитать, влезет ли день.",
    )]


def спящие_цели(собранные: list[dict]) -> list[Отклонение]:
    """Цель, под которой нет ни одной задачи с датой, — это надпись, а не работа."""
    спящие = [ц["имя"] for ц in собранные if ц["с_датой"] == 0]
    if not спящие:
        return []
    return [Отклонение(
        "прибор", "Спящие цели",
        f"Спят {len(спящие)} из {len(собранные)} целей — под ними нет ни одного дела "
        f"с датой: {', '.join(спящие)}.",
    )]


# ── память сторожа: что держится дольше нормы ────────────────────────────────

# Сколько суток подряд прибор должен быть не в норме, чтобы это перестало быть
# жизнью и стало долгом. Три: один день — обычное дело, два — совпадение,
# три — уже свойство. Число здесь, а не в промпте: его меняют по прожитому.
ДЕРЖИТСЯ_ДНЕЙ = 3

ПАМЯТЬ = """
CREATE TABLE IF NOT EXISTS detector_streak (
    имя       TEXT PRIMARY KEY,
    впервые   TEXT NOT NULL,
    последний TEXT NOT NULL,
    поднято   TEXT NOT NULL DEFAULT ''
);
"""


def запомнить(db_path: Path, свод: Свод, день: date | None = None,
              порог: int = ДЕРЖИТСЯ_ДНЕЙ) -> list[Отклонение]:
    """Отметить сегодняшние отклонения и вернуть те, что держатся дольше нормы.

    Зачем помнить. Прибор без реакции — декорация (решение 31.07). Но дёргать
    задачей на каждое отклонение значит засорить Todoist собственным шумом:
    просроченная задача в четверг — обычная жизнь. Дёргаем, когда лампочка
    горит третьи сутки подряд, и ровно один раз за приступ: восстановилась
    норма — счёт обнуляется, загорелась снова — начинается заново.

    «Мелочь дня» сюда не попадает никогда: это предложение лёгкого, а не долг.
    """
    день = день or _сегодня()
    сегодня = день.isoformat()
    живые = {о.имя: о for о in свод.отклонения if о.класс != "мелочь"}

    db_path.parent.mkdir(parents=True, exist_ok=True)
    with sqlite3.connect(db_path, timeout=30) as db:
        db.executescript(ПАМЯТЬ)
        было = {
            имя: (впервые, поднято)
            for имя, впервые, поднято in db.execute(
                "SELECT имя, впервые, поднято FROM detector_streak"
            )
        }
        # Норма восстановилась — забываем приступ целиком, вместе с отметкой.
        for имя in set(было) - set(живые):
            db.execute("DELETE FROM detector_streak WHERE имя = ?", (имя,))

        созревшие: list[Отклонение] = []
        for имя, отклонение in живые.items():
            впервые, поднято = было.get(имя, (сегодня, ""))
            db.execute(
                "INSERT INTO detector_streak(имя, впервые, последний, поднято)"
                " VALUES(?,?,?,?) ON CONFLICT(имя) DO UPDATE SET последний = excluded.последний",
                (имя, впервые, сегодня, поднято),
            )
            держится = (день - date.fromisoformat(впервые)).days + 1
            if держится >= порог and not поднято:
                db.execute("UPDATE detector_streak SET поднято = ? WHERE имя = ?",
                           (сегодня, имя))
                созревшие.append(отклонение)
    return созревшие


# ── обход целиком ────────────────────────────────────────────────────────────

async def свободные_часы(calendar: dict | None, дней: int = 7) -> tuple[dict[str, float], str]:
    """Сколько часов реально свободно в ближайшие дни. Возвращает (часы, жалоба)."""
    if not calendar:
        return {}, "календарь не подключён — перегруз считаю от рабочего дня"
    try:
        from gcal_mcp.client import CalendarClient, CalendarError
        from gcal_mcp.core import free_windows
    except ImportError as err:  # пакета нет — не повод ронять обход
        return {}, f"календарь недоступен ({err})"

    client = CalendarClient(**calendar)
    try:
        _, окна = await free_windows(
            client, date_from=_сегодня().isoformat(),
            date_to=(_сегодня() + timedelta(days=дней)).isoformat(), min_minutes=30,
        )
    except (CalendarError, OSError) as err:
        log.warning("свободные окна не забрались: %s", err)
        return {}, "календарь не ответил — перегруз считаю от рабочего дня"
    finally:
        await client.aclose()

    часы = {
        день: round(sum((к - н).total_seconds() for н, к in окна) / 3600, 1)
        for день, окна in окна.items()
    }
    return часы, ""


async def обойти(token: str, db_path: Path, calendar: dict | None = None) -> Свод:
    """Один обход: живой Todoist + снимки + календарь. Ноль токенов.

    Todoist не ответил — возвращаем то, что успели, и говорим об этом.
    Молча отдавать пустой свод нельзя: пустой свод означает «всё в порядке».
    """
    свод = Свод()
    свободно, жалоба = await свободные_часы(calendar)
    if жалоба:
        свод.жалобы.append(жалоба)

    try:
        async with TodoistClient(token) as client:
            все = await client.get_paginated("/tasks", params={"limit": 200}, cap=1000)
            показания = [
                (имя, len(await по_фильтру(client, запрос)), норма)
                for имя, запрос, норма in GAUGES
            ]
    except (TodoistError, OSError) as err:
        log.error("обход завалов не состоялся: %s", err)
        свод.жалобы.append(f"Todoist не ответил ({err})")
        return свод

    свод.отклонения += перегруз(все, свободно)
    свод.отклонения += баланс_недели(все)
    свод.отклонения += хронические_переносы(db_path)
    свод.отклонения += без_размера(все)
    свод.отклонения += спящие_цели(цели_из(все))
    свод.отклонения += мелочь(все)

    for имя, факт, норма in показания:
        исправен = норма == "—" or (норма in ("пусто", "0") and факт == 0)
        if исправен:
            свод.в_норме.append(f"{имя.lower()} {факт}" if норма == "—" else имя.lower())
        else:
            свод.отклонения.append(Отклонение(
                "прибор", имя, f"{имя}: {факт} при норме «{норма}».",
            ))
    return свод
