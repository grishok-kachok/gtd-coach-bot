"""Цели из `состояние/горизонты.md`: имя цели и имя её карточки в Todoist.

**Почему связка по имени, а не по адресу.** Адрес — id или «секция такая-то» —
ломается молча. Замер 07.08.2026: в горизонтах было записано «→ секция
💰 Автопродукт (осень)» и «→ секция Сделать перед Бали», а в живом Todoist
обеих секций уже не существовало, и не знал об этом никто. Имя ломается
видимо, и расхождение ловит код.

Цена решения названа и принята: у цели появляется строка, которую читает
машина. Тот же приём уже работает в `колесо-баланса.md` и `ритмы.md` — формат
выбирается по читателю, а читает здесь код.

Строгая строка одна и выглядит так:

    карточка: 💰 Автопродукт — автовебинар + продукт 5–10 тыс.
    карточка: нет — до сентября в работу не берём, заведём, когда начнётся

Слово «нет» — полноправный ответ, а не пропуск: решением 06.08.2026 цель может
жить в горизонтах без карточки в Todoist. Важно, чтобы рядом стояло почему,
иначе через месяц кто-нибудь заведёт карточку заново.
"""

from __future__ import annotations

import re
from dataclasses import dataclass
from pathlib import Path

# Заголовок цели: «**3. Автопродукт: …**» — жирная строка, начинающаяся с числа.
ЗАГОЛОВОК = re.compile(r"^\*\*(\d+)\.\s*(.+?)\*\*\s*$")
КАРТОЧКА = re.compile(r"^карточка:\s*(.+?)\s*$", re.I)


@dataclass(frozen=True)
class Цель:
    имя: str            # заголовок цели, как он написан в горизонтах
    карточка: str       # имя карточки в Todoist либо пусто
    почему_нет: str     # причина отсутствия карточки; пусто, если карточка есть

    @property
    def без_карточки(self) -> bool:
        return not self.карточка


def читать(path: Path) -> list[Цель]:
    """Цели года из файла горизонтов. Файла нет или он пуст — пустой список.

    Молчать при отсутствии файла правильно: обход обязан работать и там,
    где мозг ещё не наполнен, — у ученика на первом запуске целей нет вовсе.
    """
    if not path.exists():
        return []
    цели: list[Цель] = []
    текущая = ""
    for строка in path.read_text(encoding="utf-8").splitlines():
        голый = строка.strip()
        if (з := ЗАГОЛОВОК.match(голый)):
            текущая = з.group(2).strip()
            continue
        if (к := КАРТОЧКА.match(голый)) and текущая:
            значение = к.group(1).strip()
            низ = значение.lower()
            if низ == "нет" or низ.startswith("нет —") or низ.startswith("нет -"):
                причина = значение[3:].lstrip(" —-").strip()
                цели.append(Цель(текущая, "", причина))
            else:
                цели.append(Цель(текущая, значение, ""))
            текущая = ""
    return цели


def имена_карточек(path: Path) -> list[str]:
    """Только те имена, которые обязаны найтись в Todoist."""
    return [ц.карточка for ц in читать(path) if ц.карточка]
