"""Две кнопки коучу: показать предложения памяти и закрыть разобранное.

**Почему только предложения, а не вся полка.** Решение владельца 05.08: из
четырёх видов входящих коуч умеет сделать сам ровно один. Заявку, промах
и поломку чинит правкой кода человек — коуч может лишь зачитать их вслух,
а обзор, на котором восемнадцать заявок подряд получают ответ «это не ко мне»,
вытесняет то, ради чего обзор собирался. Предложения остаются, и это не
исключение, а признак: ответить на «ставки тебе в кайф или ты терпишь?» может
только человек и только словами, а записать ответ умеет сам коуч.

**Почему кнопки, а не просьба в конституции.** Ровно та разница, из-за которой
протекло знание: просьба «загляни в копилку» срабатывает, если модель не
отвлеклась; вызов инструмента либо случился, либо нет. Это уже покупали
четырежды — см. `recall.py`.

Имена кнопок и полей — латиницей. Кириллическое имя поля движок принимает молча
и потом ошибается на КАЖДОМ ходу, то есть коуч немеет целиком (зонд 02.08.2026).
Русский остаётся там, где его читает модель, — в описаниях.
"""

from __future__ import annotations

import asyncio
import logging
import sqlite3
from typing import Any

from claude_agent_sdk import create_sdk_mcp_server, tool

from .inbox import (
    ОТКЛОНЕНА,
    ОТЛОЖЕНА,
    ПРЕДЛОЖЕНИЕ,
    СДЕЛАНА,
    Inbox,
)

log = logging.getLogger(__name__)

ПОКАЗАТЬ = (
    "Показать предложения памяти — что ночная проверка предложила записать про "
    "пользователя. Зови на недельном обзоре и месячном итоге (это обязательный шаг "
    "ритуала), а также когда пользователь сам просит: «что там ночь предложила», "
    "«разберём предложения». Возвращает записи с номерами — номер нужен, чтобы "
    "потом закрыть разобранное кнопкой close_memory_proposal.\n"
    "У каждой записи сказано, откуда она: «со слов пользователя» можно записывать "
    "в память сразу, «вывод коуча» — только после того, как пользователь подтвердил. "
    "Эту границу не нарушай: вывод, записанный без подтверждения, через полгода "
    "станет портретом, который человек не утверждал."
)

ЗАКРЫТЬ = (
    "Закрыть разобранное предложение памяти с итогом. Зови СРАЗУ после того, как "
    "разобрал запись с пользователем, — незакрытая запись означает «ещё не разбирали» "
    "и вернётся задачей.\n"
    "Поля: item_id — номер записи из show_memory_proposals; outcome — что вышло: "
    "«сделана» (записал в память), «отклонена» (пользователь отказался) или "
    "«отложена» (вернуться позже); result — чем кончилось, одной строкой и обязательно, "
    "даже у отклонённой: без причины через месяц предложат ровно то же самое; "
    "return_on — дата возврата вида 2026-09-20, обязательна ТОЛЬКО у «отложена», "
    "потому что «потом» без числа означает «никогда».\n"
    "Отклонённое закрывай наравне с принятым: отказ — это тоже разбор."
)

ИСХОДЫ = {
    "сделана": СДЕЛАНА,
    "отклонена": ОТКЛОНЕНА,
    "отложена": ОТЛОЖЕНА,
}


def _строки(записи: list[dict]) -> str:
    куски = []
    for з in записи:
        откуда = f" [{з['зачем']}]" if з["зачем"] else ""
        куски.append(f"#{з['id']} от {з['день']}{откуда}\n{з['текст']}")
    return "\n\n".join(куски)


def build_inbox_server(inbox: Inbox):
    @tool("show_memory_proposals", ПОКАЗАТЬ, {
        "type": "object",
        "properties": {
            "limit": {"type": "integer",
                      "description": "Сколько показать, по умолчанию 20"},
        },
    })
    async def показать(args: dict[str, Any]) -> dict[str, Any]:
        сколько = int(args.get("limit") or 20)
        try:
            записи = await asyncio.to_thread(inbox.открытые, ПРЕДЛОЖЕНИЕ, сколько)
        except sqlite3.Error as err:
            log.exception("полка входящих не читается")
            return {"content": [{"type": "text", "text": (
                f"Полка входящих не отвечает: {err}. Скажи об этом вслух, а не молчи."
            )}]}

        if not записи:
            return {"content": [{"type": "text", "text": (
                "Неразобранных предложений памяти нет. Так и скажи — и не выдумывай "
                "их из головы: пустая копилка это ответ, а не повод что-то придумать."
            )}]}
        return {"content": [{"type": "text", "text": (
            f"Неразобранных предложений: {len(записи)}.\n\n{_строки(записи)}\n\n"
            "Разобрал запись — закрой её кнопкой close_memory_proposal с итогом. "
            "Незакрытая означает «ещё не разбирали»."
        )}]}

    @tool("close_memory_proposal", ЗАКРЫТЬ, {
        "type": "object",
        "properties": {
            "item_id": {"type": "integer", "description": "Номер записи из show_memory_proposals"},
            "outcome": {"type": "string", "description": "сделана | отклонена | отложена"},
            "result": {"type": "string", "description": "Чем кончилось, одной строкой"},
            "return_on": {"type": "string",
                          "description": "Дата возврата 2026-09-20 — только для «отложена»"},
        },
        "required": ["item_id", "outcome", "result"],
    })
    async def закрыть(args: dict[str, Any]) -> dict[str, Any]:
        исход = ИСХОДЫ.get((args.get("outcome") or "").strip().lower())
        if исход is None:
            return {"content": [{"type": "text", "text": (
                "Не понял исход. Можно только «сделана», «отклонена» или «отложена»."
            )}]}
        try:
            нашлась = await asyncio.to_thread(
                inbox.закрыть, int(args.get("item_id") or 0), исход,
                (args.get("result") or ""), вернуться=(args.get("return_on") or ""),
            )
        except ValueError as err:
            # Полка отказала осмысленно — пустой итог, отложенная без даты.
            # Отдаём словами, чтобы модель поправилась, а не потеряла действие.
            return {"content": [{"type": "text", "text": f"Не закрыл: {err}"}]}
        except sqlite3.Error as err:
            log.exception("не смог закрыть запись полки")
            return {"content": [{"type": "text", "text": (
                f"Полка входящих не отвечает: {err}. Скажи об этом вслух."
            )}]}

        if not нашлась:
            return {"content": [{"type": "text", "text": (
                "Записи с таким номером нет. Посмотри список заново — "
                "номер мог устареть."
            )}]}
        log.info("запись полки #%s закрыта как «%s»", args.get("item_id"), исход)
        return {"content": [{"type": "text", "text": (
            f"Запись #{args.get('item_id')} закрыта: {исход}. "
            f"Скажи пользователю, что записал итог."
        )}]}

    return create_sdk_mcp_server(name="inbox", version="1.0.0",
                                 tools=[показать, закрыть])
