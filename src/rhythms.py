"""Ритмы коуча: во сколько он пишет. Дом — мозг, а не `.env` на сервере.

Раньше расписание лежало в переменных окружения и читалось один раз на старте.
Значит поменять его мог только тот, у кого есть ssh, и только с перезапуском —
то есть пользователь не мог никак. А ритм — это настройка про человека, а не про
инфраструктуру: «пиши мне три раза в день» должно работать как фраза в телеграме.

Формат — строгий YAML со схемой, и это не вкусовщина (решение из PROJECT.md
от 31.07): файл читает КОД. Опечатка в прозе — бот молча перестал писать
по утрам, и это всплывёт через три дня. Опечатка в YAML со схемой — жалоба
сразу и вслух, а расписание остаётся прежним, пока файл не починят.

Ключи по-русски намеренно: файл правят пользователь и коуч, а не программист.
"""

from __future__ import annotations

import logging
import re
from pathlib import Path

import yaml

log = logging.getLogger(__name__)

RHYTHMS_FILE = "ритмы.md"

# Умолчания = то, что стояло в .env до переезда. Нужны, когда файла ещё нет,
# когда он сломан и когда в нём просто нет такой строки: без расписания бот
# не должен онеметь.
#
# **Недостающая строка — не поломка, а умолчание.** Раньше код требовал все ключи
# разом, и это была ловушка совместимости: стоило завести новый ключ — и файл
# ритмов ломался у каждого, кто про этот ключ не знает, все настройки разом
# откатывались на умолчания, а человек получал жалобу на ровном месте. Ругаемся
# только на то, что человек написал сам и написал неверно.
DEFAULTS = {
    "утро": "10:00",
    "день": "14:30",
    "вечер": "20:00",
    "ночная_выжимка": "03:00",
    "дожим_минут": 30,
    # Сколько раз достучаться, если человек не отозвался. Умолчание 2 — ровно
    # столько попыток было зашито в плагин числом файлов `дожим-N.md`, поэтому
    # у того, кто ничего не менял, поведение не изменилось.
    #
    # Ноль — законное значение, а не поломка: «мне дожимы не нужны» настраивается
    # строкой в этом файле, а не удалением текстов из общего плагина. Плагин
    # публичный, и выпиливание отняло бы механизм у тех, кто о нём не просил.
    "дожим_раз": 2,
    "тихий_час": 23,
}

# Больше пяти попыток — это уже не «достучаться», а долбёжка; верхняя граница
# стоит затем же, зачем она у `дожим_минут`: поймать опечатку вроде 20 вместо 2.
ДОЖИМОВ_МАКСИМУМ = 5

TIME = re.compile(r"^([01]\d|2[0-3]):([0-5]\d)$")

# Слово вместо времени: «этот чек-ин мне не нужен». Выключить можно только день
# и вечер. Утро держит обещание дня, а ночная выжимка — вообще не сообщение
# человеку, а уборка внутри: свернуть прожитый день и проверить память. Выключить
# её значило бы сломать память, а не сделать тише.
ВЫКЛЮЧЕНО = "нет"
ВЫКЛЮЧАЕМЫЕ = ("день", "вечер")
YAML_BLOCK = re.compile(r"```yaml\s*\n(.*?)\n```", re.DOTALL)


def _complaints(data: dict) -> list[str]:
    """Претензии к файлу человеческим языком. Пусто — значит расписание годное."""
    problems = []
    for key in ("утро", "день", "вечер", "ночная_выжимка"):
        if key not in data:
            continue
        value = data[key]
        if isinstance(value, str) and TIME.match(value):
            continue
        if value == ВЫКЛЮЧЕНО and key in ВЫКЛЮЧАЕМЫЕ:
            continue
        if value == ВЫКЛЮЧЕНО:
            problems.append(
                f"«{key}: {ВЫКЛЮЧЕНО}» — выключить можно только "
                + " и ".join(ВЫКЛЮЧАЕМЫЕ)
            )
        elif key in ВЫКЛЮЧАЕМЫЕ:
            problems.append(
                f"«{key}: {value}» — нужно время вида ЧЧ:ММ в кавычках "
                f"или слово «{ВЫКЛЮЧЕНО}»"
            )
        else:
            problems.append(f"«{key}: {value}» — нужно время вида ЧЧ:ММ в кавычках")
    minutes = data.get("дожим_минут")
    if "дожим_минут" in data and not (isinstance(minutes, int) and 5 <= minutes <= 180):
        problems.append(f"«дожим_минут: {minutes}» — нужно целое число от 5 до 180")
    раз = data.get("дожим_раз")
    if "дожим_раз" in data and not (
        isinstance(раз, int) and not isinstance(раз, bool) and 0 <= раз <= ДОЖИМОВ_МАКСИМУМ
    ):
        problems.append(
            f"«дожим_раз: {раз}» — нужно целое число от 0 до {ДОЖИМОВ_МАКСИМУМ}, "
            "ноль значит «не дожимать вовсе»"
        )
    hour = data.get("тихий_час")
    if "тихий_час" in data and not (isinstance(hour, int) and 12 <= hour <= 23):
        problems.append(f"«тихий_час: {hour}» — нужно целое число от 12 до 23")
    unknown = set(data) - set(DEFAULTS)
    if unknown:
        problems.append("лишние строки, которых код не знает: " + ", ".join(sorted(unknown)))
    return problems


def path_in(brain_dir: Path) -> Path:
    return brain_dir / "память" / "состояние" / RHYTHMS_FILE


def read(brain_dir: Path) -> tuple[dict, list[str]]:
    """Расписание и претензии к файлу.

    Претензии есть — отдаём УМОЛЧАНИЯ целиком, а не половину файла: расписание,
    собранное из годных строк и подставленных умолчаний, выглядит рабочим и врёт
    про то, когда придёт пинг.

    Претензий нет — недостающие строки берутся из умолчаний молча. Это не то же
    самое: там человек написал неверно и должен об этом узнать, здесь он просто
    ничего не писал.
    """
    path = path_in(brain_dir)
    if not path.exists():
        return dict(DEFAULTS), []

    block = YAML_BLOCK.search(path.read_text(encoding="utf-8"))
    if not block:
        return dict(DEFAULTS), ["в файле нет блока ```yaml — расписание читать неоткуда"]
    try:
        data = yaml.safe_load(block.group(1))
    except yaml.YAMLError as err:
        return dict(DEFAULTS), [f"YAML не разбирается: {err}"]
    if not isinstance(data, dict):
        return dict(DEFAULTS), ["в блоке ```yaml должен быть список строк «ключ: значение»"]

    problems = _complaints(data)
    if problems:
        return dict(DEFAULTS), problems

    result = dict(DEFAULTS)
    for key in DEFAULTS:
        if key in data and data[key] is not None:
            result[key] = data[key]
    return result, []


def выключен(rhythms: dict, key: str) -> bool:
    """Человек отказался от этого чек-ина — будильник не вешаем."""
    return rhythms.get(key) == ВЫКЛЮЧЕНО


def describe(rhythms: dict, previous: dict | None = None) -> str:
    """Человеческая строка про расписание — её коуч показывает пользователю."""
    names = {
        "утро": "утренний чек-ин",
        "день": "дневной",
        "вечер": "вечерний",
        "ночная_выжимка": "ночная выжимка",
        "дожим_минут": "дожим через, мин",
        "дожим_раз": "сколько раз дожимать",
        "тихий_час": "после этого часа не дожимаю",
    }
    if previous is None:
        return ", ".join(f"{names[k]} {rhythms[k]}" for k in DEFAULTS)
    changed = [k for k in DEFAULTS if rhythms[k] != previous[k]]
    return ", ".join(f"{names[k]}: {previous[k]} → {rhythms[k]}" for k in changed)
