"""Инструмент «вспомнить»: догрузка прошлого по смыслу, в два шага.

Окно памяти — пятнадцать кусков, и это осознанное решение: постоянное
количество делает размер рюкзака умножением, известным заранее. Но за окном
остаётся всё остальное, и вопрос «мы это где-то в конце июля обсуждали, найди»
без догрузки не решается никак.

**Почему инструмент, а не кнопка в телеграме.** Кнопкой «поискать в прошлом»
не воспользуется никто: человек не помнит, что у него есть такая кнопка, и не
обязан помнить. Понимать по смыслу, что пора лезть в прошлое, — работа модели.

**Почему «когда звать» написано здесь, а не в конституции.** Описание инструмента
модель видит в каждом ходу; просьбу внутри конституции — через раз. Это уже
покупали четырежды: протечка знаний, сводка дел, ночная проверка памяти
и стратегия, которую велено было читать и которую прочли в одной сессии
из десяти. Поэтому раздел «Вспоминание» переехал из конституции сюда.

**Почему два шага, а не векторный поиск.** Смысловой слой у нас уже есть
и называется выжимками: они написаны смыслом, а не дословно, и потому дают
попадание там, где дословный поиск промахивается. Шаг 1 — найти ДЕНЬ по
выжимкам, шаг 2 — достать дословное из архива за этот день. Векторы потребовали
бы платной модели эмбеддингов, недоступной из РФ, и отдельной базы — ради
брошюры: архив 505 КБ, поиск `LIKE` по всему занимает 4,5 мс (замер 01.08.2026).

**Признак, по которому пора заводить полнотекстовый указатель (FTS5):**
поиск дольше секунды **или** промахи мимо очевидного. За год архив вырастет
до ~14 МБ, и это всё ещё немного. Механизм впрок не строим — записываем
признак. Время каждого поиска пишется в лог, чтобы признак был проверяемым,
а не на глаз.
"""

from __future__ import annotations

import asyncio
import logging
import sqlite3
import time
from pathlib import Path
from typing import Any

from claude_agent_sdk import create_sdk_mcp_server, tool

log = logging.getLogger(__name__)

# Сколько дней-кандидатов показывать на первом шаге и сколько реплик на втором.
# Числа не от балды: больше пяти дней человек уже не различает, а сорок реплик —
# это примерно один плотный вечер целиком.
ДНЕЙ = 5
РЕПЛИК = 40
ОБРЕЗКА = 600      # символов на реплику в выдаче — цитата, а не пересказ дня
МЕДЛЕННО = 1.0     # секунд: дольше — значит пора заводить указатель

ОПИСАНИЕ = (
    "Вспомнить, что было в прошлом разговоре или в прошлом дне. "
    "Зови ВСЕГДА, когда пользователь отсылает к прошлому, которого нет перед тобой: "
    "«мы это обсуждали на прошлой неделе», «что там было с переездом в июле», "
    "«я тебе говорил про эквайринг», «когда мы решили про автопродукт». "
    "Свежая память (последние дни, недели и месяцы) приходит к тебе сама в начале "
    "разговора — за ней сюда ходить не надо. Сюда ходят за тем, чего в ней нет. "
    "Работает в два шага и сам их делает: сперва ищет ДЕНЬ по выжимкам (они написаны "
    "смыслом, поэтому попадают там, где дословный поиск мимо), потом достаёт "
    "дословные реплики того дня. Не выдумывай «по мотивам»: чего нет в архиве, "
    "того не было — так и скажи.\n"
    "Поля: query — слово или имя, которое точно звучало (не пересказ, а слово); "
    "day — день в виде 2026-07-14, если он уже известен, иначе не заполняй."
)


def _искать(path: Path, слово: str, day: str = "") -> dict[str, Any]:
    слово = слово.strip()
    if not слово:
        return {"дни": [], "реплики": [], "мс": 0.0}
    начало = time.perf_counter()
    шаблон = f"%{слово}%"
    with sqlite3.connect(f"file:{path}?mode=ro", uri=True, timeout=30) as db:
        # Шаг 1: где вообще про это говорили. Ищем по выжимкам — они смысловые.
        дни = db.execute(
            "SELECT period, period_key, text FROM digests WHERE text LIKE ? "
            "ORDER BY period_key DESC LIMIT ?",
            (шаблон, ДНЕЙ),
        ).fetchall()
        # Если день назван — берём его; иначе самый свежий из найденных дневных.
        цель = day
        if not цель:
            for период, ключ, _ in дни:
                if период == "day":
                    цель = ключ
                    break
        if цель:
            реплики = db.execute(
                "SELECT created_at, role, text FROM messages WHERE day=? "
                "ORDER BY created_at, id LIMIT ?",
                (цель, РЕПЛИК),
            ).fetchall()
        else:
            # Дня не нашлось — ищем дословно по всему архиву. 4,5 мс на 505 КБ.
            реплики = db.execute(
                "SELECT created_at, role, text FROM messages WHERE text LIKE ? "
                "ORDER BY created_at DESC LIMIT ?",
                (шаблон, РЕПЛИК),
            ).fetchall()
    мс = (time.perf_counter() - начало) * 1000
    return {"дни": дни, "реплики": реплики, "цель": цель, "мс": мс}


def _собрать(слово: str, найдено: dict[str, Any]) -> str:
    дни = найдено["дни"]
    реплики = найдено["реплики"]
    if not дни and not реплики:
        return (f"По слову «{слово}» в архиве ничего нет. Так и скажи пользователю: "
                "не выдумывай «по мотивам» — чего нет в архиве, того не было.")

    куски: list[str] = []
    if дни:
        строки = [f"- {ключ} ({период}): {текст.strip()[:300]}" for период, ключ, текст in дни]
        куски.append("Где про это говорили (по выжимкам):\n" + "\n".join(строки))
    if реплики:
        подпись = f"Дословно за {найдено['цель']}" if найдено.get("цель") else "Дословно по всему архиву"
        строки = [
            f"[{когда}] {'человек' if роль == 'user' else 'коуч'}: {текст.strip()[:ОБРЕЗКА]}"
            for когда, роль, текст in реплики
        ]
        куски.append(f"{подпись}:\n" + "\n".join(строки))
    куски.append("Цитируй точно и с датой. Чего здесь нет — того не было.")
    return "\n\n".join(куски)


def build_recall_server(db_path: Path):
    # Имя кнопки и имена полей — ЛАТИНИЦЕЙ, и это не вкус.
    #
    # Кириллическое имя кнопки движок принимает с предупреждением про SEP-986.
    # А кириллические имена полей схемы он принимает молча — и потом возвращает
    # ошибочный результат на КАЖДЫЙ ход, то есть коуч немеет целиком. Поймано
    # зондом 02.08.2026: латинское имя с полем `слово` падает, оно же с полем
    # `word` работает. До живого круга дело не дошло, но дошло бы.
    #
    # Русский здесь остаётся там, где его читает модель, — в ОПИСАНИИ. Схему
    # читает движок, а он к языку не готов. Ровно то же правило, по которому
    # питон в этом проекте по-русски, а имена MCP-кнопок — нет.
    # Короткая запись схемы сделала бы обязательным и `day`: движок ставит
    # `required` по всем ключам сразу. Поиск без дня — обычный случай, и отбивать
    # его валидацией нельзя (тот же разбор 13.08.2026, что и у заявки).
    @tool("recall", ОПИСАНИЕ, {
        "type": "object",
        "properties": {
            "query": {"type": "string", "description": "Слово или имя, которое точно звучало"},
            "day": {"type": "string", "description": "День ГГГГ-ММ-ДД, если поиск про конкретный"},
        },
        "required": ["query"],
    })
    async def вспомнить(args: dict[str, Any]) -> dict[str, Any]:
        слово = (args.get("query") or "").strip()
        день = (args.get("day") or "").strip()
        if not слово:
            return {"content": [{"type": "text", "text": (
                "Нечего искать: назови слово или имя, которое точно звучало."
            )}]}
        try:
            найдено = await asyncio.to_thread(_искать, db_path, слово, день)
        except sqlite3.Error as err:
            log.exception("поиск по архиву сорвался")
            return {"content": [{"type": "text", "text": (
                f"Архив не отвечает: {err}. Скажи об этом вслух, а не молчи."
            )}]}

        мс = найдено["мс"]
        # Признак для полнотекстового указателя проверяется числом, а не на глаз.
        уровень = log.warning if мс > МЕДЛЕННО * 1000 else log.info
        уровень(
            "вспомнить «%s»%s: дней %d, реплик %d, %.1f мс%s",
            слово[:40], f" за {день}" if день else "",
            len(найдено["дни"]), len(найдено["реплики"]), мс,
            " — ПОРА ЗАВОДИТЬ FTS5" if мс > МЕДЛЕННО * 1000 else "",
        )
        return {"content": [{"type": "text", "text": _собрать(слово, найдено)}]}

    return create_sdk_mcp_server(name="recall", version="1.0.0", tools=[вспомнить])
