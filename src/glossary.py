"""Слова из глоссария памяти — для подсказки распознавателю голоса.

Имена и названия, которые распознаватель стабильно калечит, уже описаны
в глоссарии: там прямо сказано, как они пишутся правильно. Но глоссарий читала
только модель, а распознаватель — нет, и те же слова приходилось вести вторым
списком в настройках. Два дома у одного факта, и цена известна: слово просят
добавить, оно ложится в память — а расшифровка неделю спустя всё равно приносит
не то.

Поэтому машиночитаемая часть глоссария живёт в его шапке:

    ---
    title: глоссарий
    voice: [Название, Другое Название]
    ---

Шапка, а не пометки в тексте: она не зависит от вёрстки абзацев и разбирается
тем же YAML, что и остальные файлы, которые читает код.

**Ключ по-английски, хотя весь остальной мозг по-русски.** Так требует
стандарт памяти (`standard/core.md` § 3.5): ключи frontmatter — `[a-z][a-z0-9_]*`,
и валидатор памяти проверкой 19 краснеет на русском ключе как на ошибке.
Русское `голос:` сделало бы заметку невалидной, то есть починка одного
сломала бы другое.

Ключа нет, файла нет, шапка сломана — отдаём пустой список и живём как раньше.
Подсказка распознавателю — улучшение, а не условие работы: из-за неё голосовые
перестать разбираться не должны.

Файл человеческий и меняется редко, поэтому читаем его один раз и перечитываем
только когда файл тронули. Признак «тронули» — время правки и размер: новое
слово начинает работать без перезапуска бота, ровно как настройки.
"""

from __future__ import annotations

import logging
import re
from pathlib import Path

import yaml

log = logging.getLogger(__name__)

GLOSSARY_FILE = "глоссарий.md"
КЛЮЧ = "voice"

FRONTMATTER = re.compile(r"\A---\s*\n(.*?)\n---\s*\n", re.DOTALL)

# Путь → (отпечаток файла, слова). Отпечаток — время правки и размер.
_кэш: dict[Path, tuple[tuple[int, int], list[str]]] = {}


def path_in(brain_dir: Path) -> Path:
    return brain_dir / "память" / "знания" / GLOSSARY_FILE


def _отпечаток(path: Path) -> tuple[int, int] | None:
    """Чем отличается тронутый файл от нетронутого. Нет файла — None."""
    try:
        stat = path.stat()
    except OSError:
        return None
    return (stat.st_mtime_ns, stat.st_size)


def _разобрать(path: Path) -> list[str]:
    """Список слов из шапки глоссария. Любая беда — пустой список и жалоба в лог."""
    try:
        текст = path.read_text(encoding="utf-8")
    except OSError:
        log.warning("глоссарий не читается: %s", path)
        return []

    шапка = FRONTMATTER.search(текст)
    if not шапка:
        return []
    try:
        data = yaml.safe_load(шапка.group(1))
    except yaml.YAMLError as err:
        log.warning("шапка глоссария не разбирается (%s): %s", err, path)
        return []
    if not isinstance(data, dict) or КЛЮЧ not in data:
        return []

    значение = data[КЛЮЧ]
    if значение is None:
        return []
    if not isinstance(значение, list):
        # Молча проглоченная строка вместо списка означала бы, что человек
        # думает, будто слова уехали в подсказку, а их там нет.
        log.warning("«%s» в шапке глоссария — нужен список слов: %s", КЛЮЧ, path)
        return []

    слова = [str(w).strip() for w in значение if isinstance(w, str) and str(w).strip()]
    лишние = [w for w in значение if not isinstance(w, str)]
    if лишние:
        log.warning("«%s» в шапке глоссария — это должны быть слова, а не %s: %s",
                    КЛЮЧ, лишние, path)
    return слова


def слова(brain_dir: Path) -> list[str]:
    """Слова глоссария для распознавателя. Читаем заново только тронутый файл."""
    path = path_in(brain_dir)
    отпечаток = _отпечаток(path)
    if отпечаток is None:
        _кэш.pop(path, None)
        return []
    попало = _кэш.get(path)
    if попало is not None and попало[0] == отпечаток:
        return list(попало[1])
    найденные = _разобрать(path)
    _кэш[path] = (отпечаток, найденные)
    return list(найденные)


def забыть() -> None:
    """Сбросить кэш. Нужно тестам и разовой перестройке памяти, не бою."""
    _кэш.clear()
