"""Инструменты FINDAY для движка бота — дела, привычки и деньги приложения.

FINDAY живёт на том же сервере отдельным приложением: телефонные экраны, задачи
с осями «важно/срочно», привычки с ритмами, операции в копейках, подписки,
долги, остаток и напоминания о сроках. Коуч про всё это до сих пор не знал
ничего и вёл разговор о делах, которых не видит.

**Почему по токену через HTTP, а не в базу напрямую.** База у приложения рядом,
и дотянуться до неё было бы короче. Но у FINDAY есть закон: функция, меняющая
запись по номеру, ставит хозяина условием в самом запросе, — а маршруты
`/api/v1/*` достают человека из токена. Значит, придя дверью, коуч физически не
может назвать чужой номер записи: ни ошибкой, ни выдумкой модели. Прямой доступ
к базе это свойство отменил бы, и держать его пришлось бы уже здесь, в питоне,
где о нём никто не помнит.

Побочная выгода того же решения: токен — обычная сессия с меткой «Коуч». Она
видна человеку в профиле среди устройств и отзывается одним тапом, как телефон.
Машинный секрет так не умеет.

**Токен не кладётся в мозг.** Мозг — git-репозиторий, который уезжает на
GitHub. Токен живёт только в окружении контейнера (FINDAY_TOKEN).

**Имена кнопок и полей — латиницей.** Кириллическое имя движок принимает молча,
а потом ошибается на КАЖДОМ ходу, то есть коуч немеет целиком (зонд 02.08.2026,
см. inbox_tool.py). Русский остаётся там, где его читает модель, — в описаниях.

**Удаления здесь нет намеренно.** Ни дела, ни привычки, ни операции. Удаление
необратимо, а в приложении оно стоит одного тапа — та же логика, по которой
коуч не может править собственный код. Записать может, стереть — человек.
"""

from __future__ import annotations

import logging
