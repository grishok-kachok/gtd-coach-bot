log = logging.getLogger(__name__)

# Ход коуча длиннее одного запроса, а телефон на плохой сети отвечает медленно.
# Двадцать пять секунд: меньше — и разбор длинного месяца успевал бы отвалиться,
# больше — человек в телеграме решит, что коуч завис.
ТАЙМАУТ = 25.0

# Токен человека, от чьего имени идёт ход.
#
# Переменная контекста, а не просто чтение окружения внутри кнопки: сегодня
# человек один и токен приезжает из FINDAY_TOKEN, но дверь из приложения будет
# ставить сюда токен того, кто говорит. Читать окружение прямо в обработчике
# значило бы закрыть себе эту дорогу — и обнаружить это в тот день, когда
# людей станет двое.
_токен: ContextVar[str] = ContextVar("finday_token", default="")


def поставить_токен(token: str) -> None:
    """Чей токен идёт в ход. Вызывается перед ходом; пусто — берётся из окружения."""
    _токен.set(token or "")


class ОтказFINDAY(Exception):
    """Приложение не ответило или отказало. Всегда показывается модели словами."""


async def запрос(
    база: str, запасной_токен: str, метод: str, путь: str, тело: dict | None = None
) -> Any:
    """Один ход в приложение. Публичная: этой же дверью ходит сводка (agenda.py)."""
    token = _токен.get() or запасной_токен
    if not token:
        raise ОтказFINDAY("нет токена FINDAY — приложение недоступно, скажи об этом вслух")

    адрес = f"{база.rstrip('/')}/api/v1/{путь.lstrip('/')}"
    try:
        # trust_env: выход наружу у контейнера идёт через мост Xray, адрес
        # моста лежит в окружении. То же самое делает клиент Todoist.
        async with httpx.AsyncClient(timeout=ТАЙМАУТ, trust_env=True) as client:
            ответ = await client.request(
                метод, адрес, json=тело, headers={"Authorization": f"Bearer {token}"}
            )
    except httpx.HTTPError as err:
        raise ОтказFINDAY(f"приложение не отвечает: {err}") from err

    if ответ.status_code == 401:
        # Отдельной строкой: это не поломка, а отозванный доступ. Чинится
        # человеком в профиле, и коуч должен сказать именно это, а не «ошибка».
        raise ОтказFINDAY(
            "приложение не приняло токен. Похоже, вход «Коуч» отключён в профиле — "
            "скажи об этом вслух, сам починить это нельзя"
        )
    if ответ.status_code == 404:
        # Тоже отдельной строкой, и по той же причине, что 401: с появлением
        # кнопок правки коуч ВПЕРВЫЕ называет номер записи сам. Промах по
        # номеру — обычное дело (список устарел, номер придуман), и ответ на
        # него — сходить за списком заново, а не сообщать о поломке.
        raise ОтказFINDAY(
            "приложение не нашло такой записи: номер устарел или выдуман. "
            "Посмотри список заново и не говори, что сделал, — ты не сделал"
        )
    if ответ.status_code >= 400:
        raise ОтказFINDAY(f"приложение ответило {ответ.status_code}: {ответ.text[:200]}")

    try:
        return ответ.json()
    except ValueError as err:
        raise ОтказFINDAY(f"ответ приложения не разобран: {err}") from err


