def build_finday_server(base_url: str, token: str):
    """Собрать MCP-сервер приложения. Токен пуст — сервер не заводится (см. main)."""

    def ok(text: str) -> dict[str, Any]:
        return {"content": [{"type": "text", "text": text}]}

    async def позвать(метод: str, путь: str, тело: dict | None = None) -> Any:
        return await запрос(base_url, token, метод, путь, тело)

    @tool("finday_day", ДЕНЬ, {"type": "object", "properties": {}})
    async def день(_args: dict[str, Any]) -> dict[str, Any]:
        try:
            d = await позвать("GET", "today")
        except ОтказFINDAY as err:
            return ok(f"Не смог посмотреть день: {err}")

        дела = [
            f"#{t['id']} {t['emoji']} {t['title']} — {t['when']}"
            for t in d.get("tasks", [])
            if not t.get("done")
        ]
        привычки = [
            f"{h['emoji']} {h['title']} ({h['cadence']}) — {'отмечена' if h['done'] else 'нет'}"
            for h in d.get("habits", [])
        ]
        деньги = d.get("money") or {}
        строки = [
            f"{d.get('weekday', '')}, {d.get('date', '')}",
            "",
            "Дела: " + ("\n  " + "\n  ".join(дела) if дела else "на сегодня пусто"),
            "Привычки: " + ("\n  " + "\n  ".join(привычки) if привычки else "нет"),
            "",
            f"Месяц: потрачено {деньги.get('expense', '—')}, "
            f"пришло {деньги.get('income', '—')}, останется {деньги.get('projected', '—')}",
        ]
        if деньги.get("просрочено"):
            строки.append(f"Просрочено списаний на {деньги['просрочено']}")
        return ok("\n".join(строки))

    @tool("finday_tasks", ДЕЛА, {"type": "object", "properties": {}})
    async def дела(_args: dict[str, Any]) -> dict[str, Any]:
        try:
            d = await позвать("GET", "tasks")
        except ОтказFINDAY as err:
            return ok(f"Не смог посмотреть дела: {err}")

        открытые = [t for t in d.get("tasks", []) if not t.get("done")]
        if not открытые:
            return ok("Открытых дел нет. Так и скажи — и не выдумывай их из головы.")
        строки = [
            f"#{t['id']} {t['emoji']} {t['title']} — {t['when']} [{t.get('квадрант', '')}]"
            for t in открытые
        ]
        return ok(f"Открытых дел: {len(открытые)}.\n" + "\n".join(строки))

    @tool("finday_balance", ОСТАТОК, {"type": "object", "properties": {}})
    async def остаток(_args: dict[str, Any]) -> dict[str, Any]:
        try:
            b = await позвать("GET", "balance")
        except ОтказFINDAY as err:
            return ok(f"Не смог посмотреть деньги: {err}")

        if not b.get("естьСверка"):
            return ok(
                "Человек ни разу не сверял остаток, поэтому числа «сколько у меня денег» "
                "нет. Выдумывать его неоткуда — приложение ведёт остаток от названной "
                f"суммы. Обязательных списаний на {b.get('окноДней', 30)} дней вперёд: "
                f"{b.get('предстоит', '—')}."
            )
        return ok(
            f"На счету {b['остаток']} ({b.get('сверено', '')}).\n"
            f"Обязательных списаний на {b.get('окноДней', 30)} дней: {b.get('предстоит', '—')}.\n"
            f"Можно тратить: {b.get('свободно', '—')}."
            + ("\nПора сверить остаток." if b.get("пораСверить") else "")
        )

    @tool("finday_week", НЕДЕЛЯ, {"type": "object", "properties": {}})
    async def неделя(_args: dict[str, Any]) -> dict[str, Any]:
        try:
            w = await позвать("GET", "week")
        except ОтказFINDAY as err:
            return ok(f"Не смог посмотреть неделю: {err}")

        if not w.get("есть"):
            без_места = w.get("безМеста", [])
            return ok(
                f"Неделя с {w.get('начало')} ещё не собрана. Норма — {w.get('норма')} дел в день. "
                f"Открытых дел без места: {len(без_места)}."
            )
        куски = []
        for д in w.get("дни", []):
            метка = " (сегодня)" if д.get("сегодня") else " (прошёл)" if д.get("прошёл") else ""
            дела_дня = ", ".join(f"#{x['id']} {x['title']}" for x in д.get("дела", [])) or "—"
            якоря = ", ".join(x["title"] for x in д.get("якоря", []))
            куски.append(f"{д['день']}{метка}: {дела_дня}" + (f" | занято: {якоря}" if якоря else ""))
        состояние = (
            "принят"
            if w.get("принят")
            else "НЕ принят — это пока только картинка, сроков у задач нет"
        )
        хвост = ", ".join(f"#{x['id']} {x['title']}" for x in w.get("безМеста", []))
        return ok(
            f"Неделя с {w.get('начало')}, план {состояние}.\n"
            + "\n".join(куски)
            + (f"\nБез места: {хвост}" if хвост else "")
        )

    @tool("finday_gaps", ВОПРОСЫ, {"type": "object", "properties": {}})
    async def вопросы(_args: dict[str, Any]) -> dict[str, Any]:
        try:
            g = await позвать("GET", "gaps")
        except ОтказFINDAY as err:
            return ok(f"Не смог посмотреть вопросы: {err}")

        список = g.get("вопросы", [])
        if not список:
            return ok("Незакрытых вопросов о деньгах нет. Пустой список — это ответ.")
        строки = [f"#{в['id']} {в['вопрос']} (без ответа: {в['зачем']})" for в in список]
        return ok(
            f"Вопросов: {len(список)}. Задай не больше одного за ход.\n" + "\n".join(строки)
        )

    @tool("finday_add_expense", ТРАТА, {
        "type": "object",
        "properties": {
            "title": {"type": "string", "description": "На что ушли деньги, два-три слова"},
            "amount_minor": {"type": "integer", "description": "Сумма в КОПЕЙКАХ: 350 ₽ = 35000"},
            "kind": {"type": "string", "description": "expense или income, по умолчанию expense"},
            "scope": {"type": "string", "description": "personal или business, по умолчанию personal"},
            "category": {"type": "string", "description": "Ключ категории латиницей"},
            "occurred_at": {"type": "string", "description": "День вида 2026-09-02, без него сегодня"},
        },
        "required": ["title", "amount_minor"],
    })
    async def записать(args: dict[str, Any]) -> dict[str, Any]:
        сумма = int(args.get("amount_minor") or 0)
        if сумма <= 0:
            return ok("Не записал: нужна сумма в копейках, целым числом больше нуля.")
        название = (args.get("title") or "").strip()
        if not название:
            return ok("Не записал: нужно название — на что ушли деньги.")

        тело = {
            "title": название,
            "amountMinor": сумма,
            "kind": "income" if args.get("kind") == "income" else "expense",
            "scope": "business" if args.get("scope") == "business" else "personal",
        }
        if args.get("category"):
            тело["category"] = args["category"]
        if args.get("occurred_at"):
            тело["occurredAt"] = args["occurred_at"]

        try:
            d = await позвать("POST", "money/entries", тело)
        except ОтказFINDAY as err:
            return ok(f"Не записал: {err}")

        e = d.get("entry") or {}
        log.info("FINDAY: записана операция #%s", e.get("id"))
        return ok(
            f"Записал в приложение: {e.get('title', название)} — {e.get('amount', сумма)} "
            f"({e.get('category', '')}). Отменить человек может тапом в приложении."
        )

    @tool("finday_create_task", ЗАВЕСТИ, {
        "type": "object",
        "properties": {
            "title": {"type": "string", "description": "Что сделать, коротко"},
            "due_date": {"type": "string", "description": "День вида 2026-09-10"},
            "due_time": {"type": "string", "description": "Время вида 18:30"},
            "quadrant": {
                "type": "string",
                "description": "сейчас, планировать, между-делом, не-важно или неразобрано",
            },
            "category": {"type": "string", "description": "personal, work или other"},
        },
        "required": ["title"],
    })
    async def завести(args: dict[str, Any]) -> dict[str, Any]:
        название = (args.get("title") or "").strip()
        if not название:
            return ok("Не завёл: нужно название — что именно сделать.")

        тело: dict[str, Any] = {"title": название}
        for снаружи, внутри in (
            ("due_date", "dueDate"),
            ("due_time", "dueTime"),
            ("quadrant", "квадрант"),
            ("category", "category"),
        ):
            if args.get(снаружи):
                тело[внутри] = args[снаружи]

        try:
            d = await позвать("POST", "tasks", тело)
        except ОтказFINDAY as err:
            return ok(f"Не завёл: {err}")

        t = d.get("task") or {}
        log.info("FINDAY: заведено дело #%s", t.get("id"))
        return ok(
            f"Завёл в приложение: #{t.get('id')} {t.get('title', название)} — "
            f"{t.get('when', 'без срока')} [{t.get('квадрант', '')}]."
        )

    @tool("finday_close_task", ЗАКРЫТЬ, {
        "type": "object",
        "properties": {
            "task_id": {"type": "integer", "description": "Номер дела из finday_day или finday_tasks"},
            "done": {"type": "boolean", "description": "false — снять галочку обратно"},
        },
        "required": ["task_id"],
    })
    async def закрыть(args: dict[str, Any]) -> dict[str, Any]:
        номер = int(args.get("task_id") or 0)
        if номер <= 0:
            return ok("Не отметил: нужен номер дела — он есть в finday_day и finday_tasks.")
        сделано = args.get("done") is not False

        try:
            d = await позвать("POST", f"tasks/{номер}/complete", {"done": сделано})
        except ОтказFINDAY as err:
            return ok(f"Не отметил: {err}")

        t = d.get("task") or {}
        log.info("FINDAY: дело #%s -> done=%s", номер, сделано)
        return ok(
            (f"Отметил сделанным: #{номер} {t.get('title', '')}."
             if сделано
             else f"Снял галочку обратно: #{номер} {t.get('title', '')} — {t.get('when', '')}.")
        )

    @tool("finday_update_task", ПОПРАВИТЬ, {
        "type": "object",
        "properties": {
            "task_id": {"type": "integer", "description": "Номер дела из finday_day или finday_tasks"},
            "title": {"type": "string", "description": "Новое название"},
            "due_date": {"type": "string", "description": "Новый день вида 2026-09-10"},
            "due_time": {"type": "string", "description": "Новое время вида 18:30"},
            "drop_due": {"type": "boolean", "description": "true — снять срок вовсе"},
            "quadrant": {
                "type": "string",
                "description": "сейчас, планировать, между-делом, не-важно или неразобрано",
            },
        },
        "required": ["task_id"],
    })
    async def поправить(args: dict[str, Any]) -> dict[str, Any]:
        номер = int(args.get("task_id") or 0)
        if номер <= 0:
            return ok("Не поправил: нужен номер дела — он есть в finday_day и finday_tasks.")

        тело: dict[str, Any] = {}
        if (args.get("title") or "").strip():
            тело["title"] = args["title"].strip()
        if args.get("quadrant"):
            тело["квадрант"] = args["quadrant"]
        # Снять срок и перенести срок — разные просьбы, и различает их
        # ПРИСУТСТВИЕ ключа, а не его пустота: «не трогай» и «сотри» иначе
        # слились бы в одно, и перенос названия молча обнулял бы дату.
        if args.get("drop_due"):
            тело["dueDate"] = None
        else:
            if args.get("due_date"):
                тело["dueDate"] = args["due_date"]
            if args.get("due_time"):
                тело["dueTime"] = args["due_time"]

        if not тело:
            return ok("Не поправил: не сказано, что менять — срок, название или разбор.")

        try:
            d = await позвать("PATCH", f"tasks/{номер}", тело)
        except ОтказFINDAY as err:
            return ok(f"Не поправил: {err}")

        t = d.get("task") or {}
        log.info("FINDAY: поправлено дело #%s (%s)", номер, ", ".join(тело))
        return ok(
            f"Поправил: #{номер} {t.get('title', '')} — {t.get('when', '')} "
            f"[{t.get('квадрант', '')}]."
        )

