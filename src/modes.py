"""Режимы контекста: что коуч берёт с собой в разговор.

Объём загрузки перестал быть константой. Раньше утреннее «что сегодня»
и месячная стратсессия стоили одинаково — 40 430 токенов, замер живого
чек-ина 01.08.2026. Теперь рюкзак собирается под повод.

Дом состава — **плагин** (`режимы.md`), потому что это логика работы коуча,
а её дом плагин, а не мозг. Активный режим — наоборот, состояние, и живёт
в мозге, в `настройки.md`, рядом с моделью и тумблерами кнопок.

Файл читается **на старте и падает вслух**, а не подставляет умолчания.
У настроек умолчания уместны: там сломанный файл означает «думаем прежней
моделью». Здесь сломанный файл означает «неизвестно, что класть в голову
коучу», и зашитый в питон запасной состав был бы вторым домом того же факта —
ровно тем, от чего этот проект лечится второй месяц.
"""

from __future__ import annotations

import logging
import os
import re
from dataclasses import dataclass, field
from pathlib import Path

import yaml

log = logging.getLogger(__name__)

MODES_FILE = Path(os.environ.get("MODES_FILE", "/plugin/режимы.md"))
PARTS_DIR = Path(os.environ.get("CONSTITUTION_DIR", "/plugin/prompts/конституция"))

YAML_BLOCK = re.compile(r"```yaml\s*\n(.*?)\n```", re.DOTALL)

# Порядок склейки задаёт КОД, а не порядок строк в YAML. Иначе переставленная
# от руки строка молча меняла бы голос коуча, и найти это было бы неоткуда.
ЧАСТИ = ("ядро", "память", "стратегия", "ритуалы")

# Четыре родных режима — и только они. Своих пользователю не даём: механика
# позволяла бы дёшево, но цена свободы не в коде, а в путанице.
РОДНЫЕ = ("фоновый", "рабочий", "полный", "годовой")

ПО_УМОЛЧАНИЮ = "рабочий"
ФОНОВЫЙ = "фоновый"

# Режимы, которые могут стоять в настройках как режим разговора. Фонового
# среди них нет намеренно: его ставит код на ночную работу и на работника
# комментариев, а разговор в нём — это коуч без памяти и без имени человека.
РАЗГОВОРНЫЕ = tuple(имя for имя in РОДНЫЕ if имя != ФОНОВЫЙ)

# Слои окна памяти. В файле состава они по-русски — его правят человек и коуч;
# в архиве те же слои зовутся day/week/month, потому что так называются строки
# в базе. Перевод делается ЗДЕСЬ и один раз: пока его не было, `окно` уезжало
# в архив с русскими ключами, ни один запрос не совпадал, и коуч оставался
# без памяти — молча, без единой ошибки в логах. Поймано тестом 02.08.2026.
СЛОИ = ("дни", "недели", "месяцы")
В_АРХИВ = {"дни": "day", "недели": "week", "месяцы": "month"}

# Что код подкладывает в первый запрос сессии, кроме окна выжимок. Раньше это
# была просьба в конституции «читай в начале разговора» — по десяти последним
# сессиям она сработала в одной.
ФАЙЛЫ: dict[str, tuple[str, str]] = {
    "миссия": ("память/знания/миссия.md", "Миссия — ради чего всё"),
    "ценности": ("память/знания/ценности.md", "Ценности и сферы жизни"),
    "горизонты": ("память/состояние/горизонты.md", "Горизонты — год, квартал, месяц"),
    "профиль": ("память/состояние/профиль-показатели.md",
                "Показатели профиля — как этот человек работает на самом деле"),
}


@dataclass(frozen=True)
class Режим:
    имя: str
    значок: str
    ставит: str          # код | человек
    повод: str
    части: tuple[str, ...]
    правила_памяти: bool
    встроенные_инструменты: bool
    # Ключи здесь уже АРХИВНЫЕ (day/week/month), а не те, что в файле состава:
    # это словарь для запроса в базу, и переводится он ровно один раз, в read().
    окно: dict[str, int] = field(default_factory=dict)
    файлы: tuple[str, ...] = ()

    @property
    def человек_ставит(self) -> bool:
        return self.ставит == "человек"


def _претензии(data: object) -> list[str]:
    """Претензии к файлу состава человеческим языком. Пусто — состав годный."""
    problems: list[str] = []
    if not isinstance(data, dict):
        return ["в блоке ```yaml должен быть список режимов «имя: состав»"]

    лишние = sorted(set(data) - set(РОДНЫЕ))
    if лишние:
        problems.append(
            "режимы, которых код не знает: " + ", ".join(лишние)
            + ". Родных четыре: " + ", ".join(РОДНЫЕ)
        )
    нет = [имя for имя in РОДНЫЕ if имя not in data]
    if нет:
        problems.append("не хватает режимов: " + ", ".join(нет))

    for имя in РОДНЫЕ:
        тело = data.get(имя)
        if тело is None:
            continue
        if not isinstance(тело, dict):
            problems.append(f"«{имя}» — нужен список строк «ключ: значение»")
            continue
        лишнее = sorted(set(тело) - {"значок", "ставит", "повод", "состав"})
        if лишнее:
            problems.append(f"«{имя}» — лишние строки: {', '.join(лишнее)}")
        if not str(тело.get("значок") or "").strip():
            problems.append(f"«{имя}» — нет значка")
        if тело.get("ставит") not in ("код", "человек"):
            problems.append(f"«{имя} → ставит: {тело.get('ставит')}» — нужно «код» или «человек»")
        if not str(тело.get("повод") or "").strip():
            problems.append(f"«{имя}» — нет повода: непонятно, когда его включают")

        состав = тело.get("состав")
        if not isinstance(состав, dict):
            problems.append(f"«{имя} → состав» — нужен список из пяти рычагов")
            continue
        нужно = {"конституция", "правила_памяти", "встроенные_инструменты", "память", "файлы"}
        не_хватает = sorted(нужно - set(состав))
        if не_хватает:
            problems.append(f"«{имя} → состав» — нет рычагов: {', '.join(не_хватает)}")
        лишние_рычаги = sorted(set(состав) - нужно)
        if лишние_рычаги:
            problems.append(f"«{имя} → состав» — лишние рычаги: {', '.join(лишние_рычаги)}")

        части = состав.get("конституция")
        if части is None:
            части = []
        if not isinstance(части, list):
            problems.append(f"«{имя} → конституция» — нужен список частей")
        else:
            for часть in части:
                if часть not in ЧАСТИ:
                    problems.append(
                        f"«{имя} → конституция: {часть}» — такой части нет. "
                        "Есть: " + ", ".join(ЧАСТИ)
                    )
            if len(части) != len(set(части)):
                problems.append(f"«{имя} → конституция» — часть названа дважды")

        for ключ in ("правила_памяти", "встроенные_инструменты"):
            if ключ in состав and not isinstance(состав[ключ], bool):
                problems.append(f"«{имя} → {ключ}: {состав[ключ]}» — нужно on или off")

        окно = состав.get("память")
        if окно is not None:
            if not isinstance(окно, dict):
                problems.append(f"«{имя} → память» — нужно «дни: N, недели: N, месяцы: N»")
            else:
                лишние_слои = sorted(set(окно) - set(СЛОИ))
                if лишние_слои:
                    problems.append(f"«{имя} → память» — лишние слои: {', '.join(лишние_слои)}")
                for слой in СЛОИ:
                    значение = окно.get(слой)
                    if not isinstance(значение, int) or isinstance(значение, bool) or значение < 0:
                        problems.append(
                            f"«{имя} → память → {слой}: {значение}» — нужно целое число от нуля"
                        )

        файлы = состав.get("файлы")
        if файлы is None:
            файлы = []
        if not isinstance(файлы, list):
            problems.append(f"«{имя} → файлы» — нужен список имён")
        else:
            for имя_файла in файлы:
                if имя_файла not in ФАЙЛЫ:
                    problems.append(
                        f"«{имя} → файлы: {имя_файла}» — такого файла код не знает. "
                        "Есть: " + ", ".join(ФАЙЛЫ)
                    )
    return problems


def read(path: Path | None = None) -> tuple[dict[str, Режим], list[str]]:
    """Состав режимов и претензии к файлу.

    Претензии есть — режимов не отдаём вовсе. Половина состава хуже отсутствия:
    коуч, собранный из годных строк и подставленных умолчаний, выглядит рабочим
    и врёт про то, что у него в голове.
    """
    path = path or MODES_FILE
    try:
        raw = path.read_text(encoding="utf-8")
    except OSError as err:
        return {}, [f"файл состава режимов не читается: {path} ({err})"]

    блок = YAML_BLOCK.search(raw)
    if not блок:
        return {}, [f"в {path} нет блока ```yaml — состав читать неоткуда"]
    try:
        data = yaml.safe_load(блок.group(1))
    except yaml.YAMLError as err:
        return {}, [f"состав режимов не разбирается: {err}"]

    problems = _претензии(data)
    if problems:
        return {}, problems

    режимы: dict[str, Режим] = {}
    for имя in РОДНЫЕ:
        тело = data[имя]
        состав = тело["состав"]
        окно = состав["память"]
        режимы[имя] = Режим(
            имя=имя,
            значок=str(тело["значок"]).strip(),
            ставит=str(тело["ставит"]),
            повод=str(тело["повод"]).strip(),
            части=tuple(ч for ч in ЧАСТИ if ч in (состав["конституция"] or [])),
            правила_памяти=bool(состав["правила_памяти"]),
            встроенные_инструменты=bool(состав["встроенные_инструменты"]),
            окно={В_АРХИВ[слой]: int(окно[слой]) for слой in СЛОИ},
            файлы=tuple(состав["файлы"] or []),
        )
    return режимы, problems


def load(path: Path | None = None) -> dict[str, Режим]:
    """То же, но с падением вслух: без состава бот работать не должен."""
    режимы, problems = read(path)
    if problems:
        raise SystemExit(
            "Состав режимов не читается: " + "; ".join(problems)
            + f"\nФайл: {path or MODES_FILE}"
        )
    return режимы


# --- сборка рюкзака ---


def конституция(части: tuple[str, ...], папка: Path | None = None) -> str:
    """Склеить части конституции в системный промпт.

    Порядок — канонический (ЧАСТИ), а не тот, в котором части перечислены
    в файле состава. Нет файла — падаем и называем имя: молча упростившийся
    коуч хуже отсутствующего, а по логам такую пропажу не найти никогда.
    """
    папка = папка or PARTS_DIR
    куски: list[str] = []
    for часть in ЧАСТИ:
        if часть not in части:
            continue
        путь = папка / f"{часть}.md"
        try:
            текст = путь.read_text(encoding="utf-8").strip()
        except OSError as err:
            raise SystemExit(
                f"Часть конституции «{часть}» не читается: {путь} ({err}). "
                "Проверь, что клон плагина на сервере свежий и том /plugin смонтирован."
            ) from err
        if not текст:
            raise SystemExit(f"Часть конституции «{часть}» пустая: {путь}")
        куски.append(текст)
    return "\n\n".join(куски)


НАДСТРОЙКА = "память/состояние/личная-надстройка.md"

ЗАГОЛОВОК_НАДСТРОЙКИ = (
    "## Личная надстройка\n\n"
    "Ниже — то, что этот человек добавил к твоей роли сам. "
    "Расходится с общей частью — побеждает эта."
)


def личная_надстройка(brain_dir: Path) -> str:
    """Что человек дописал к роли коуча — своими словами, в своём мозге.

    **Дом надстройки — мозг, а не плагин.** На компьютере Claude Code кладёт
    плагин в папку, названную версией (`cache/…/gtd-coach/0.1.0/`). Новая
    версия — новая папка, и файл, положенный в старую, не затирается — он
    просто перестаёт читаться. Тихая пропажа без единой ошибки. Отсюда общее
    правило: **плагин можно снести и поставить заново, ничего не потеряв.**

    Файла нет — это норма, а не поломка: большинству ничего дописывать
    не нужно. Пустой файл — тоже норма.

    Читается перед каждым ответом, а не кэшируется: правка должна работать
    со следующей реплики, как ритмы и настройки. Это чтение одного маленького
    файла с диска, платить за него нечем.
    """
    путь = brain_dir.joinpath(*НАДСТРОЙКА.split("/"))
    try:
        текст = путь.read_text(encoding="utf-8").strip()
    except OSError:
        return ""
    return f"{ЗАГОЛОВОК_НАДСТРОЙКИ}\n\n{текст}" if текст else ""


def недостающие_части(папка: Path | None = None) -> list[str]:
    """Каких частей конституции нет в плагине. Пусто — комплект на месте."""
    папка = папка or PARTS_DIR
    return [часть for часть in ЧАСТИ if not (папка / f"{часть}.md").is_file()]


def файлы_стратегии(brain_dir: Path, имена: tuple[str, ...]) -> str:
    """Прочитать файлы стратегии, которые режим кладёт в рюкзак.

    Отсутствие файла здесь — не повод падать: это данные мозга, а не наш код.
    Профиля может не быть до первой ночи, миссии — до первого разговора о ней.
    Но молчать нельзя: пропажу обязано быть видно в логах.
    """
    куски: list[str] = []
    for имя in имена:
        адрес, заголовок = ФАЙЛЫ[имя]
        путь = brain_dir.joinpath(*адрес.split("/"))
        try:
            текст = путь.read_text(encoding="utf-8").strip()
        except OSError:
            log.error("файл стратегии «%s» не читается: %s", имя, путь)
            continue
        if текст:
            куски.append(f"### {заголовок}\n\n{текст}")
    return "\n\n".join(куски)
