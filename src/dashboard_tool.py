"""Инструмент «прислать дашборд» — потому что отправка обязана случаться.

Стратсессия **без файла не считается проведённой** (решение владельца 31.07).
А то, что обязано случаться, делается инструментом, а не просьбой в тексте:
просьба срабатывает, если модель не отвлеклась; вызов инструмента либо
случился, либо нет.

Отсюда же форма ответа: инструмент возвращает коучу, что файл ушёл, — и коуч
об этом говорит вслух. Молча отправленный файл неотличим от неотправленного.

**Окна периодов заведены все четыре 08.08.2026, в этапе 18.** До этого их было
два: всё, что не начиналось на «мес», молча превращалось в неделю. Пока
стратсессий было две, это работало; с появлением квартальной и годовой
`period: "квартал"` тихо присылал бы недельную картину — и разговор шёл бы
про три месяца по семидневным числам. Молчаливая подмена хуже отказа:
отказ виден, подмена нет.
"""

from __future__ import annotations

import logging
from collections.abc import Awaitable, Callable
from pathlib import Path
from typing import Any

from claude_agent_sdk import create_sdk_mcp_server, tool

from .dashboard import собрать_файл

log = logging.getLogger(__name__)

# Окно дашборда по слову периода. Первое совпадение по началу слова —
# «мес», «месяц», «месячная» ведут в одно место, и коуч может назвать период
# как угодно из этого ряда.
ОКНА: tuple[tuple[str, int, str], ...] = (
    ("нед", 7, "Стратегия за неделю"),
    ("мес", 30, "Стратегия за месяц"),
    ("квартал", 90, "Стратегия за квартал"),
    ("год", 365, "Стратегия за год"),
)
ОКНО_ПО_УМОЛЧАНИЮ = (7, "Стратегия за неделю")


def _окно(период: str) -> tuple[int, str]:
    """Сколько дней брать и как подписать файл.

    Незнакомое слово даёт неделю — но об этом пишется в лог. Раньше подмена
    была немой, и `period: "квартал"` присылал недельную картину без единого
    следа."""
    for начало, дней, подпись in ОКНА:
        if период.startswith(начало):
            return дней, подпись
    log.warning("дашборд: период «%s» не узнан, беру неделю", период)
    return ОКНО_ПО_УМОЛЧАНИЮ


def build_dashboard_server(
    brain_dir: Path,
    db_path: Path,
    todoist_token: str,
    send: Callable[[Path, str], Awaitable[bool]],
):
    """`send(путь, подпись)` — как файл уходит владельцу. Возвращает, дошёл ли."""

    @tool(
        "send_dashboard",
        "Собрать дашборд стратегии и прислать пользователю файлом в телеграм. Звать "
        "на стратсессиях — там это ОБЯЗАТЕЛЬНАЯ часть ритуала, без файла "
        "стратсессия не считается проведённой, — а также когда пользователь "
        "просит «покажи картину» или «где я сейчас». period: неделя, месяц, "
        "квартал или год. Файл открывается прямо в телеграме, на телефоне "
        "и на компьютере.",
        {"period": str},
    )
    async def send_dashboard(args: dict[str, Any]) -> dict[str, Any]:
        период = (args.get("period") or "неделя").strip().lower()
        дней, подпись = _окно(период)

        try:
            путь = await собрать_файл(brain_dir, db_path, todoist_token, дней=дней)
        except OSError:
            log.exception("дашборд не собрался")
            return {"content": [{"type": "text", "text": (
                "Дашборд не собрался — скажи пользователю вслух, что файла не будет, "
                "и разбери стратсессию словами."
            )}]}

        if not await send(путь, подпись):
            return {"content": [{"type": "text", "text": (
                "Файл собрался, но не ушёл в телеграм. Скажи об этом вслух — "
                "ритуал без файла не считается проведённым."
            )}]}

        размер = путь.stat().st_size
        log.info("дашборд отправлен: %s (%d Б)", путь.name, размер)
        return {"content": [{"type": "text", "text": (
            f"Дашборд «{путь.name}» отправлен ({размер // 1024} КБ). "
            "Скажи пользователю, что файл пришёл и его можно открыть прямо здесь."
        )}]}

    return create_sdk_mcp_server(name="dashboard", version="1.0.0", tools=[send_dashboard])
