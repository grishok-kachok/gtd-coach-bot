"""Профиль: как человек устроен — счётом, а не прилагательными.

Психопрофиль легко выродить в гороскоп: «упорный, склонен к перфекционизму».
Поэтому здесь форма жёсткая — **показатель, у которого есть следствие для
поведения коуча**. Нет следствия, значит показатель украшение, и его тут быть
не должно.

| Показатель | Откуда | Что меняет |
|---|---|---|
| часы работы | время закрытий | когда пинговать, куда ставить тяжёлое |
| срок жизни задачи | от заведения до закрытия | не назначать «сегодня» тому, что живёт девять дней |
| что делается, что лежит | срез по проектам и меткам | какая сфера идёт под нож на самом деле |
| переносы до закрытия | снимки | что дробить, а от чего отказаться |
| приток против оттока | снимки | система набирает воду или разгружается |
| отклик на пинги | архив разговоров | какой чек-ин работает, какой пропускается молча |

**Окно обязательно.** Считаем за последние 30 и 90 дней, а не за всё время:
осенью человек переезжает, поменяются пояс и ритм, — вечная средняя будет
рассказывать про прошлогоднего.

**Граница записи.** Цифра — факт, её пишет код и сразу. «Ты сова» — вывод,
и он идёт через подтверждение человеком, как всё остальное в этой памяти.
Поэтому наружу отдаются показания, а не приговоры.
"""

from __future__ import annotations

import logging
import os
import sqlite3
from collections import Counter, defaultdict
from dataclasses import dataclass
from datetime import date, datetime, timedelta
from pathlib import Path
from statistics import median
from zoneinfo import ZoneInfo

log = logging.getLogger(__name__)

# Два окна, а не одно: 30 дней — «какой ты сейчас», 90 — «какой ты вообще».
# Расхождение между ними само по себе показание: что-то изменилось.
ОКНА = (30, 90)

# Служебные каналы — это тексты пингов, а не слова человека (см. archive.py).
ПИНГИ = ("morning", "midday", "evening")


@dataclass(frozen=True)
class Показатель:
    """Одно измерение. `следствие` — то, ради чего показатель вообще считается."""

    имя: str
    значение: str
    следствие: str
    окно: int
    основание: int  # на скольких событиях посчитано; мало — верить рано

    def строка(self) -> str:
        основа = f"{self.основание} событий за {self.окно} дн."
        return f"**{self.имя}:** {self.значение} ({основа}). {self.следствие}"


def _зона() -> ZoneInfo:
    return ZoneInfo(os.environ.get("COACH_TZ") or "Europe/Moscow")


def _местное(метка: str) -> datetime | None:
    """`2026-08-01T09:06:38.010100Z` → местное время. Todoist пишет в UTC."""
    if not метка:
        return None
    try:
        сырое = datetime.fromisoformat(метка.replace("Z", "+00:00"))
    except ValueError:
        return None
    if сырое.tzinfo is None:
        сырое = сырое.replace(tzinfo=ZoneInfo("UTC"))
    return сырое.astimezone(_зона())


def _порог(окно: int, сегодня: date | None = None) -> str:
    сегодня = сегодня or datetime.now(_зона()).date()
    return (сегодня - timedelta(days=окно)).isoformat()


def _закрытые(db: sqlite3.Connection, окно: int, сегодня: date | None = None) -> list[tuple]:
    return db.execute(
        "SELECT completed_at, added_at, labels, project, content FROM todoist_closed"
        " WHERE completed_at >= ?", (_порог(окно, сегодня),),
    ).fetchall()


# ── показатели, которые работают сразу ───────────────────────────────────────

def часы_работы(db: sqlite3.Connection, окно: int = 30,
                сегодня: date | None = None) -> Показатель | None:
    """В какие часы человек реально закрывает дела.

    Проверено на живой истории 01.08: за июль пик приходится на полдень,
    а до 11 утра закрыто 5 задач за месяц. Утренний пинг в 10:00 при таком
    раскладе попадает в мёртвый час — это и есть следствие показателя.
    """
    строки = _закрытые(db, окно, сегодня)
    часы = Counter()
    for completed_at, *_ in строки:
        когда = _местное(completed_at)
        if когда:
            часы[когда.hour] += 1
    if not часы:
        return None
    топ = часы.most_common(3)
    до_полудня = sum(n for ч, n in часы.items() if ч < 12)
    всего = sum(часы.values())
    значение = ", ".join(f"{ч:02d}:00 — {n}" for ч, n in топ) \
        + f"; до полудня {round(100 * до_полудня / всего)} %"
    return Показатель(
        "Часы закрытий", значение,
        "Тяжёлое ставить в пиковые часы, а не в те, что кажутся правильными.",
        окно, всего,
    )


def срок_жизни(db: sqlite3.Connection, окно: int = 90,
               сегодня: date | None = None) -> Показатель | None:
    """Сколько дней задача живёт от заведения до закрытия — медианой по размеру.

    Медиана, а не среднее: одна задача, пролежавшая полгода, утащила бы среднее
    и соврала про обычный день.
    """
    строки = _закрытые(db, окно, сегодня)
    по_размеру: dict[str, list[float]] = defaultdict(list)
    for completed_at, added_at, labels, *_ in строки:
        конец, начало = _местное(completed_at), _местное(added_at)
        if not (конец and начало) or конец < начало:
            continue
        дней = (конец - начало).total_seconds() / 86400
        размер = next((м for м in (labels or "").split(",") if м.startswith("⏱️")), "без размера")
        по_размеру[размер].append(дней)
    все = [д for куски in по_размеру.values() for д in куски]
    if not все:
        return None
    части = ", ".join(
        f"{размер}: {round(median(дни), 1)} дн."
        for размер, дни in sorted(по_размеру.items(), key=lambda p: -len(p[1]))[:4]
    )
    return Показатель(
        "Срок жизни задачи", f"медиана {round(median(все), 1)} дн. ({части})",
        "Не назначать «сегодня» тому, что по опыту живёт дольше: срок должен быть "
        "честным, иначе он воспитывает привычку не верить срокам.",
        окно, len(все),
    )


def что_делается(db: sqlite3.Connection, окно: int = 30,
                 сегодня: date | None = None) -> Показатель | None:
    """Где работа идёт, а где стоит: закрытые против лежащих, по проектам.

    Это колесо баланса, измеренное фактом. Опрос раз в месяц спрашивает,
    как человек себя чувствует; здесь видно, куда он на самом деле тратил
    время — и расхождение между этими двумя вещами и есть разговор.
    """
    закрыто = Counter(проект for _, _, _, проект, _ in _закрытые(db, окно, сегодня) if проект)
    свежий = db.execute("SELECT MAX(day) FROM todoist_tasks").fetchone()
    лежит = Counter()
    if свежий and свежий[0]:
        лежит = Counter(
            проект for (проект,) in db.execute(
                "SELECT project FROM todoist_tasks WHERE day = ? AND project <> ''", (свежий[0],)
            )
        )
    if not закрыто and not лежит:
        return None
    проекты = sorted(set(закрыто) | set(лежит), key=lambda п: -(лежит[п] + закрыто[п]))[:4]
    значение = "; ".join(f"{п}: закрыто {закрыто[п]}, лежит {лежит[п]}" for п in проекты)
    return Показатель(
        "Где идёт работа", значение,
        "Сфера, где месяцами лежит и не закрывается, — это не «нет времени», "
        "а решение, которое не принято вслух. Об этом стоит спросить.",
        окно, sum(закрыто.values()),
    )


# ── показатели по снимкам: заговорят, когда накопятся ────────────────────────

def переносы(db: sqlite3.Connection, окно: int = 30,
             сегодня: date | None = None) -> Показатель | None:
    """Сколько раз задача переезжает, прежде чем случиться."""
    строки = db.execute(
        "SELECT task_id FROM todoist_diff WHERE kind = 'перенесена' AND day >= ?",
        (_порог(окно, сегодня),),
    ).fetchall()
    if not строки:
        return None
    счёт = Counter(task_id for (task_id,) in строки)
    хроников = sum(1 for n in счёт.values() if n >= 3)
    return Показатель(
        "Переносы", f"{len(строки)} переносов у {len(счёт)} задач, "
                    f"из них хроников (3+): {хроников}",
        "Задача, которая переезжает третий раз, не станет сделанной от четвёртого "
        "переноса: её надо дробить или отпускать.",
        окно, len(строки),
    )


def приток_отток(db: sqlite3.Connection, окно: int = 30,
                 сегодня: date | None = None) -> Показатель | None:
    """Сколько дел приходит и сколько уходит. Набирает ли система воду."""
    строки = db.execute(
        "SELECT kind, COUNT(*) FROM todoist_diff WHERE day >= ?"
        " AND kind IN ('появилась', 'закрыта') GROUP BY kind",
        (_порог(окно, сегодня),),
    ).fetchall()
    if not строки:
        return None
    счёт = dict(строки)
    пришло, ушло = счёт.get("появилась", 0), счёт.get("закрыта", 0)
    итог = "приток больше оттока" if пришло > ушло else "успевает"
    return Показатель(
        "Приток и отток", f"пришло {пришло}, закрыто {ушло} — {итог}",
        "Устойчивый перевес притока значит, что список растёт быстрее человека, "
        "и лечится это отказом, а не темпом.",
        окно, пришло + ушло,
    )


def обещания(db: sqlite3.Connection, окно: int = 30,
             сегодня: date | None = None) -> Показатель | None:
    """Попадает ли человек в обещание дня — и делает ли именно обещанное.

    Самый неприятный и самый честный показатель: закрыть двенадцать дел
    и не сделать то, что назвал главным, — обычное дело, и увидеть это можно
    только сравнив слова с фактом. Строки копит ночной разбор (`promise.py`).
    """
    try:
        строки = db.execute(
            "SELECT исход, главное FROM day_promise WHERE day >= ? AND обещание <> ''",
            (_порог(окно, сегодня),),
        ).fetchall()
    except sqlite3.Error:
        return None  # таблицы ещё нет — первый разбор её и заведёт
    if not строки:
        return None
    исходы = Counter(исход for исход, _ in строки)
    сделал = исходы["выполнено"]
    вместо = sum(1 for _, главное in строки if главное == "другое")
    return Показатель(
        "Обещание дня", f"сдержано {сделал} из {len(строки)}"
        + (f"; в {вместо} случаях закрыл другое, а не обещанное" if вместо else ""),
        "Сколько обещаний давать брать за раз — по этому числу, а не по настроению. "
        "Регулярное «закрыл другое» значит, что главное выбирается неверно утром.",
        окно, len(строки),
    )


# ── показатель по архиву разговоров ──────────────────────────────────────────

def отклик_на_пинги(archive_db: Path, окно: int = 30,
                    сегодня: date | None = None) -> Показатель | None:
    """На какой чек-ин человек отзывается, а какой пропускает молча.

    Пинг лежит в архиве строкой с ролью «vasiliy» и служебным каналом — это
    текст задания коучу, а не слова человека (так устроен archive.py). Ответом
    считается ближайшая живая реплика: голосом или текстом.
    """
    if not archive_db.exists():
        return None
    порог = _порог(окно, сегодня)
    try:
        with sqlite3.connect(archive_db, timeout=30) as db:
            строки = db.execute(
                "SELECT created_at, role, channel FROM messages WHERE day >= ?"
                " ORDER BY created_at, id", (порог,),
            ).fetchall()
    except sqlite3.Error as err:
        log.warning("архив для отклика не читается: %s", err)
        return None

    ждут: dict[str, datetime] = {}
    задержки: dict[str, list[float]] = defaultdict(list)
    пропущено: Counter = Counter()
    всего: Counter = Counter()
    for created_at, role, channel in строки:
        когда = _местное(created_at) or None
        if когда is None:
            continue
        if role == "vasiliy" and channel in ПИНГИ:
            # Прошлый пинг остался без ответа — значит его пропустили молча.
            for канал, момент in list(ждут.items()):
                if (когда - момент).total_seconds() > 6 * 3600:
                    пропущено[канал] += 1
                    ждут.pop(канал)
            ждут[channel] = когда
            всего[channel] += 1
        elif role == "vasiliy" and channel not in ("nudge",):
            for канал, момент in list(ждут.items()):
                задержки[канал].append((когда - момент).total_seconds() / 60)
                ждут.pop(канал)
    for канал in ждут:
        пропущено[канал] += 1

    if not sum(всего.values()):
        return None
    куски = []
    for канал in ПИНГИ:
        if not всего[канал]:
            continue
        ответы = задержки[канал]
        медиана = f"{round(median(ответы))} мин" if ответы else "без ответа"
        куски.append(f"{канал}: {len(ответы)} из {всего[канал]}, обычно через {медиана}")
    return Показатель(
        "Отклик на чек-ины", "; ".join(куски),
        "Чек-ин, который пропускается молча, не работает — его надо двигать "
        "или менять, а не повторять громче.",
        окно, sum(всего.values()),
    )


# ── сборка ───────────────────────────────────────────────────────────────────

СОСТОЯНИЕ = "профиль-показатели.md"
ЗАМЕРЫ = "профиль-замеры.md"

ИНДЕКС_НАЧАЛО = "<!-- начало:профиль — собирается кодом, src/profile.py -->"
ИНДЕКС_КОНЕЦ = "<!-- конец:профиль -->"

ШАПКА_СОСТОЯНИЯ = """---
title: профиль-показатели
type: состояние
schema_version: "1.0"
status: stable
created: {создан}
as_of: {дата}
temporal: true
tags: [паттерн, работа]
---

# Профиль в цифрах: как человек работает на самом деле

> Живой модуль **состояние**: всегда актуально, перезаписывается на месте.
> Историю замеров смотри в журнале — [[профиль-замеры]].

Считает код (`src/profile.py`) по своим снимкам Todoist и архиву разговоров,
раз в сутки. Здесь **показания приборов, а не выводы про человека**: цифра —
факт и пишется сама, а «он сова» — вывод, и он попадает в знания только после
того, как человек это подтвердил.

У каждого показателя названо следствие — что он меняет в работе коуча.
Показатель без следствия здесь быть не должен: это украшение.

Мало событий в основании — верить рано. Показатели по снимкам набирают вес
недели за две, показатели по истории закрытий работают сразу.

"""


def _записать_состояние(brain_dir: Path, показатели: list[Показатель],
                        день: date) -> Path | None:
    """Перезаписать показания на месте. Так устроен модуль состояния."""
    if not показатели:
        return None
    путь = brain_dir / "память" / "состояние" / СОСТОЯНИЕ
    путь.parent.mkdir(parents=True, exist_ok=True)
    создан = день.isoformat()
    if путь.exists():
        первая = путь.read_text(encoding="utf-8")
        for строка in первая.splitlines():
            if строка.startswith("created:"):
                создан = строка.split(":", 1)[1].strip()
                break
    тело = "\n\n".join(f"- {п.строка()}" for п in показатели)
    путь.write_text(
        ШАПКА_СОСТОЯНИЯ.format(создан=создан, дата=день.isoformat()) + тело + "\n",
        encoding="utf-8",
    )
    return путь


def _дописать_замеры(brain_dir: Path, показатели: list[Показатель], день: date) -> Path | None:
    """Дописать строку замеров в журнал. Ряд, а не одна оценка.

    Одно измерение ничего не значит: важно, что часы работы поехали, а приток
    третью неделю обгоняет отток. Ровно так же устроено колесо баланса.
    """
    if not показатели:
        return None
    from .notes import append  # локально: notes ничего не знает про профиль

    блок = f"\n## {день.isoformat()}\n\n" + "".join(
        f"- {п.имя}: {п.значение} (окно {п.окно} дн., событий {п.основание})\n"
        for п in показатели
    )
    return append(
        brain_dir / "память" / "журнал" / ЗАМЕРЫ, day=день, block=блок,
        title="профиль-замеры", heading="Замеры профиля: строка в неделю",
        note="Собирает код (`src/profile.py`) раз в неделю. Это ряд показаний, "
             "а не выводы: по ряду видно, что поехало — часы работы, приток дел, "
             "отклик на чек-ины. Одно измерение не значит ничего.",
        ref="замеры профиля, по строке в неделю",
        author="код бота (src/profile.py)", tags="паттерн, работа",
    )


def _связать_с_индексом(brain_dir: Path) -> None:
    """Поставить ссылки на обе заметки в точке входа.

    Файл, созданный кодом без ссылки, — сирота; ссылка на несозданный файл —
    битая. Валидатор ругается в обоих случаях, поэтому заметки и ссылки
    заводятся одним заходом. Блок в метках, как список выжимок: код правит
    только своё, человек рядом пишет что угодно.
    """
    индекс = brain_dir / "память" / "00-index.md"
    if not индекс.exists():
        return
    текст = индекс.read_text(encoding="utf-8")
    блок = (f"{ИНДЕКС_НАЧАЛО}\n"
            f"- [[профиль-показатели]] — как человек работает: часы, сроки, переносы\n"
            f"- [[профиль-замеры]] — ряд тех же показаний по неделям\n"
            f"{ИНДЕКС_КОНЕЦ}")
    if ИНДЕКС_НАЧАЛО in текст and ИНДЕКС_КОНЕЦ in текст:
        голова, _, остаток = текст.partition(ИНДЕКС_НАЧАЛО)
        _, _, хвост = остаток.partition(ИНДЕКС_КОНЕЦ)
        новый = f"{голова}{блок}{хвост}"
    else:
        новый = текст.rstrip() + "\n\n## Профиль в цифрах\n\n" + блок + "\n"
    if новый != текст:
        индекс.write_text(новый, encoding="utf-8")


def записать(brain_dir: Path, показатели: list[Показатель], день: date,
             в_журнал: bool = False) -> list[Path]:
    """Разложить показатели по закону модуля. Возвращает тронутые файлы.

    Состояние перезаписывается каждую ночь — оно на то и состояние. Строка
    в журнал дописывается раз в неделю: журнал копится и не стирается,
    и строка в сутки превратила бы ряд в шум.
    """
    тронуто = [_записать_состояние(brain_dir, показатели, день)]
    if в_журнал:
        тронуто.append(_дописать_замеры(brain_dir, показатели, день))
    if any(тронуто):
        _связать_с_индексом(brain_dir)
    return [п for п in тронуто if п]


def собрать(db_path: Path, archive_db: Path, сегодня: date | None = None) -> list[Показатель]:
    """Все показатели, которые сегодня есть чем посчитать. Нет данных — нет строки."""
    if not db_path.exists():
        return []
    собранные: list[Показатель] = []
    try:
        with sqlite3.connect(db_path, timeout=30) as db:
            for считалка, окно in (
                (часы_работы, 30), (срок_жизни, 90), (что_делается, 30),
                (переносы, 30), (приток_отток, 30), (обещания, 30),
            ):
                показатель = считалка(db, окно, сегодня)
                if показатель:
                    собранные.append(показатель)
    except sqlite3.Error as err:
        log.warning("показатели профиля не посчитались: %s", err)
    отклик = отклик_на_пинги(archive_db, 30, сегодня)
    if отклик:
        собранные.append(отклик)
    return собранные
