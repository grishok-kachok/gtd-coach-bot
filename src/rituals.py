"""Четыре стратсессии: недельная, месячная, квартальная, годовая.

Три отличия от обычного разговора, и все три существенные.

**Повод называет код, а не память модели.** Понедельник, первое число и начало
квартала видит календарь — и это повод НАПОМНИТЬ. Включает человек командой
(`/week`, `/month`, `/quarter`, `/year`): словами обряд не начинается с 06.08.2026,
список фраз ниже работает подсказкой. Обязательное делает код, решение остаётся
за человеком.

**Стратсессия идёт отдельным заходом.** Не «новый разговор вместо старого»,
а закладка: текущий разговор откладывается, обряд идёт со своей головой,
по окончании человек возвращается ровно туда, где был. Так это и устроено
в жизни: сходил в другую комнату — вернулся к своей книжке.

**Нить не рвётся.** В начало обряда код подкладывает сегодняшний разговор —
то, что уже обсудили с утра. Технически положить текст в середину разговора
можно всегда (так каждый день работает сводка дел); окно выжимок кладут один
раз в начале не потому, что «иначе нельзя», а чтобы не гонять сорок килобайт
с каждой репликой. Здесь мы этой возможностью и пользуемся.

Дом у каждого факта свой, и определяется он сроком жизни:

    «обычно я работаю в таком режиме»   → настройки.md в мозге, живёт месяцами
    «прямо сейчас идёт стратсессия»     → состояние бота, живёт час
    «на чём остановились до неё»        → там же, отложенная закладка
"""

from __future__ import annotations

import re
from dataclasses import dataclass
from datetime import date
from pathlib import Path


# Два падежа, а не один: имена стратсессий женского рода, и склеивать их
# с глаголами одной строкой нельзя. «Начинается недельная стратсессия» —
# именительный, «Включил недельную стратсессию» — винительный. Пока имена были
# мужского рода («недельный обзор»), формы совпадали и поле было одно; на
# «квартальную стратсессию» это уже врало — код печатал «Начинается
# квартальную стратсессию». Заведено в этапе 18 вместе с переименованием.
@dataclass(frozen=True)
class Повод:
    ключ: str
    что: str          # именительный: «Начинается недельная стратсессия»
    вин: str          # винительный: «Включил недельную стратсессию»
    какая: str        # прилагательное к слову «стратсессия»
    режим: str        # с какой головой его вести
    навык: str        # где лежит процедура
    задача: str       # ключ находки в backstage — какую задачу ставить
    окно: int         # сколько дней проведённая стратсессия ещё в силе


ПОВОДЫ: dict[str, Повод] = {
    "недельный": Повод(
        ключ="недельный", какая="недельная", режим="полный",
        что="недельная стратсессия", вин="недельную стратсессию",
        навык="недельная-стратсессия", задача="недельная стратсессия", окно=7,
    ),
    "месячный": Повод(
        ключ="месячный", какая="месячная", режим="полный",
        что="месячная стратсессия", вин="месячную стратсессию",
        навык="месячная-стратсессия", задача="месячная стратсессия", окно=28,
    ),
    # Квартал — ревизия среднего срока: не «много ли сделали», а не пора ли
    # править сами годовые цели, поставленные полгода назад. Уровень КВАРТАЛ
    # в горизонтах есть с самого начала, но до этапа 18 его не переписывал
    # никто: знакомство заполняло один раз, и он застывал.
    "квартальный": Повод(
        ключ="квартальный", какая="квартальная", режим="полный",
        что="квартальная стратсессия", вин="квартальную стратсессию",
        навык="квартальная-стратсессия", задача="квартальная стратсессия", окно=80,
    ),
    "годовой": Повод(
        ключ="годовой", какая="годовая", режим="годовой",
        что="годовая стратсессия", вин="годовую стратсессию",
        навык="годовая-стратсессия", задача="годовая стратсессия", окно=300,
    ),
}

# Фразы, по которым видно, что человек ЗАВЁЛ РЕЧЬ о стратсессии.
#
# **Обряд по ним больше не включается** (правка 06.08.2026 по заявке владельца
# от 04.08). Раньше включался, и предыдущая редакция этого комментария защищала
# такое поведение так: список ловит и лишнее, но включение говорится вслух
# и отменяется одним словом, значит ложное срабатывание стоит одной реплики.
#
# Довод не выдержал жизни. Косяк 04.08: фраза «надо поправить скилл недельного
# обзора» включила сам недельный обзор. Это не редкая осечка, а свойство:
# **список ловит слова, а не смысл**, и разговор ПРО инструмент неотличим для
# него от просьбы инструмент применить. Хитрить с распознаванием бесполезно —
# оно ломается на первой же живой фразе.
#
# Теперь список работает подсказкой: увидели фразу — говорим «сам включить
# не могу» и даём ту же слэш-команду, что в меню. Включает человек, одним
# нажатием. Обязательное по-прежнему делает код (подсказка появится всегда),
# а решение осталось у человека — там, где ему и место.
ФРАЗЫ: dict[str, tuple[str, ...]] = {
    "годовой": (
        "годовую стратсессию", "годовая стратсессия", "стратсессию за год",
        "итоги года", "подведем год", "стратсессия за год",
    ),
    "квартальный": (
        "квартальную стратсессию", "квартальная стратсессия", "итоги квартала",
        "подведем квартал", "разбор квартала", "квартальный обзор",
    ),
    "месячный": (
        "месячный итог", "итоги месяца", "подведем месяц",
        "месячную стратсессию", "месячная стратсессия", "разбор месяца",
    ),
    "недельный": (
        "недельный обзор", "обзор недели", "итоги недели", "подведем неделю",
        "недельную стратсессию", "недельная стратсессия", "разбор недели",
    ),
}
# Порядок проверки — от крупного к мелкому: «итоги года» содержит «года»,
# и мелкий повод не должен перехватывать крупный.
ПОРЯДОК = ("годовой", "квартальный", "месячный", "недельный")

КОНЕЦ = (
    "закончить стратсессию", "закончили стратсессию", "закончим стратсессию",
    "завершить стратсессию", "стратсессия закончена", "закончить обзор",
    "закончили обзор", "вернись к обычному разговору", "выйди из стратсессии",
)

ПРОБЕЛЫ = re.compile(r"\s+")


def _норма(текст: str) -> str:
    """Всё в нижний регистр, ё→е, лишние пробелы прочь.

    Голосовые расшифровки приходят с разной пунктуацией и то с «ё», то без —
    сравнивать сырой текст значило бы ловить фразу через раз.
    """
    т = текст.lower().replace("ё", "е")
    т = re.sub(r"[^\w\s]", " ", т)
    return ПРОБЕЛЫ.sub(" ", т).strip()


def по_фразе(текст: str) -> Повод | None:
    """Завёл ли человек речь о стратсессии. Ловим ядро фразы, а не реплику целиком.

    **Обряд по этому не включается** — только подсказывается команда. Имя
    функции осталось прежним намеренно: она отвечает на тот же вопрос, что
    и раньше, изменилось лишь то, что делают с ответом.
    """
    норма = _норма(текст)
    if not норма or конец_ли(текст):
        return None
    for ключ in ПОРЯДОК:
        for фраза in ФРАЗЫ[ключ]:
            ядро = _норма(фраза)
            if ядро and ядро in норма:
                return ПОВОДЫ[ключ]
    return None


def конец_ли(текст: str) -> bool:
    """Просит ли человек закончить обряд и вернуться к прежнему разговору."""
    норма = _норма(текст)
    return any(_норма(ф) in норма for ф in КОНЕЦ)


def по_календарю(now) -> Повод | None:
    """Есть ли сегодня повод НАПОМНИТЬ про обряд.

    Порядок от крупного к мелкому: первое января — это ещё и первое число,
    и, случись оно понедельником, три повода разом. Напоминаем об одном,
    самом крупном: три напоминания подряд читаются как три задачи, хотя
    это один разговор.

    Заметьте: это повод НАПОМНИТЬ, а не начать. Начинает человек.
    """
    if now.month == 1 and now.day == 1:
        return ПОВОДЫ["годовой"]
    # Первое апреля, июля и октября. Первое января сюда не доходит — там
    # повод крупнее, и он уже вернулся выше.
    if now.day == 1 and now.month in (4, 7, 10):
        return ПОВОДЫ["квартальный"]
    if now.day == 1:
        return ПОВОДЫ["месячный"]
    if now.weekday() == 0:
        return ПОВОДЫ["недельный"]
    return None


# Журнал — единственное место, где видно, что стратсессия ВСЁ-ТАКИ прошла.
# Кнопка `/week` про это не знает: 22.08.2026 стратсессия была проведена
# разговором, без команды, а в понедельник коуч предложил её заново и получил
# «я в субботу провёл». Состояние бота помнит только те обряды, что включали
# кнопкой, — значит спрашивать надо у журнала, где итог лежит всегда.
ЖУРНАЛ = "память/журнал"
ЗАПИСЬ = re.compile(r"^(\d{4})-(\d{2})-(\d{2})-(.+)\.md$")


def когда_проводили(brain_dir, повод: Повод) -> date | None:
    """Дата последней записи об этой стратсессии в журнале. Нет записи — None.

    Ищем по имени файла: `ГГГГ-ММ-ДД-<какая>-стратсессия.md`. Имя, а не
    содержимое, — потому что дата в журнале и так стоит первой, а читать
    десятки файлов ради одной проверки дорого.
    """
    папка = Path(brain_dir) / ЖУРНАЛ
    хвост_имени = f"{повод.какая}-стратсессия"
    последняя = None
    try:
        файлы = list(папка.glob("*.md"))
    except OSError:
        return None
    for файл in файлы:
        совпало = ЗАПИСЬ.match(файл.name)
        if not совпало or not совпало.group(4).startswith(хвост_имени):
            continue
        try:
            когда = date(int(совпало.group(1)), int(совпало.group(2)),
                         int(совпало.group(3)))
        except ValueError:
            continue
        if последняя is None or когда > последняя:
            последняя = когда
    return последняя


def напоминать_ли(brain_dir, повод: Повод, сегодня: date) -> bool:
    """Стоит ли напоминать о стратсессии, или она недавно прошла.

    Окно считается от дня записи: недельная, проведённая в субботу, держит
    следующую неделю, и в понедельник напоминать о ней нечего. Ровно через
    окно — напоминаем снова: неделя, отсчитанная от прошлого понедельника,
    в этот понедельник уже кончилась.
    """
    когда = когда_проводили(brain_dir, повод)
    if когда is None:
        return True
    return (сегодня - когда).days >= повод.окно
