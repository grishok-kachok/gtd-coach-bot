"""Сверка стартовой загрузки с паспортом памяти — теперь в токенах.

Паспорт (`config.yaml` мозга, стандарт § 6.3) объявляет, что коуч несёт
в каждой сессии, и ставит этому потолок. Пока никто не считает — это украшение:
ровно так 31.07 выяснилось, что записанные «28 097» были символами, а не
байтами, и потолок 80 000 пробили в день, когда его записали.

**Считаем в токенах, а не в байтах.** Байт — верная единица для кода, но платит
человек токенами, а курс у русского markdown свой (≈4,1 Б на токен) и на глаз
не берётся. Главное же — байты полезной нагрузки и байты, доехавшие
до контекста, оказались разными величинами: описания 18 кнопок весят 20 КБ,
а стоят 241 токен, потому что движок кладёт в контекст имена, а описание
подтягивает при вызове (замер 01.08.2026). Мерить надо то, что доехало,
и спрашивать об этом саму модель.

**Потолок у каждого режима свой.** Один потолок на все четыре бессмыслен:
годовая стратсессия обязана быть дороже утреннего «что сегодня» вчетверо,
и общий потолок либо промолчит про раздутый фоновый прогон, либо будет
кричать на каждую стратсессию. Сверяется потолок того режима, в котором
сессия и собрана.

Потолок здесь — сигнализация, а не нож. Пробили — грузим всё равно и говорим
вслух: § 6.3 п. 4 прямо требует, чтобы пробой был работой человека, а не поводом
оставить коуча без памяти.

Байтовая сверка построчно осталась и никуда не денется: токенов по строкам
модель не разбивает, а именно построчная сверка ловит враньё вида «объявлено
69 400, на деле 37 962». Одно другое не заменяет — это два разных сторожа.
"""

from __future__ import annotations

import logging
from pathlib import Path

import yaml

log = logging.getLogger(__name__)


def _паспорт(brain_dir: Path) -> tuple[dict, str]:
    config = brain_dir / "config.yaml"
    if not config.exists():
        return {}, ""
    try:
        data = yaml.safe_load(config.read_text(encoding="utf-8")) or {}
    except yaml.YAMLError as err:
        return {}, f"паспорт памяти не разбирается: {err}"
    return (data.get("startup") or {}), ""


def check(brain_dir: Path, loaded: dict[str, int], *, mode: str = "",
          tokens: int | None = None) -> str:
    """Сверить фактическое с паспортом. Возвращает жалобу или пустую строку.

    `loaded` — что бот реально положил в контекст, в БАЙТАХ: {название: байт}.
    Названия должны совпадать с полем `what` в паспорте, иначе сверять нечего
    и об этом говорится отдельно: молчание про несведённую строку читается
    как «сошлось».

    `tokens` — сколько на самом деле стоил первый ход сессии в этом режиме,
    по счёту самой модели. Есть число — сверяем с потолком режима.
    """
    passport, беда = _паспорт(brain_dir)
    if беда:
        return беда
    if not passport:
        return ""

    declared = {row.get("what"): row for row in passport.get("loads") or []}

    beefs = []
    for what, actual in loaded.items():
        row = declared.get(what)
        if row is None:
            beefs.append(f"«{what}» ({actual} Б) грузится, но в паспорте не объявлен")
            continue
        size = row.get("bytes")
        # 15% — не вкус, а природа величин: блок выжимок меняется каждую ночь,
        # и требовать от паспорта точности до байта значило бы переписывать его
        # ежедневно. Уход вдвое так не спрячешь, а именно его мы и ловим.
        if isinstance(size, int) and size and abs(actual - size) > max(200, size * 0.15):
            beefs.append(f"«{what}»: в паспорте {size} Б, на деле {actual} Б")

    beefs.extend(_потолок(passport, mode, tokens))
    return "; ".join(beefs)


def _потолок(passport: dict, mode: str, tokens: int | None) -> list[str]:
    """Сверка измеренной цены режима с его потолком."""
    if not mode or tokens is None:
        return []
    budgets = passport.get("budgets") or {}
    if not isinstance(budgets, dict) or mode not in budgets:
        # Сторож, который не знает своего потолка, показывает спокойствие.
        # Это уже покупали трижды, поэтому молчать здесь нельзя.
        return [f"у режима «{mode}» нет потолка в паспорте, сверять не с чем "
                f"(измерено {tokens} токенов)"]
    budget = budgets[mode]
    if not isinstance(budget, int) or budget <= 0:
        return [f"потолок режима «{mode}» в паспорте не число: {budget!r}"]
    if tokens > budget:
        return [
            f"ПОТОЛОК ПРОБИТ: режим «{mode}» стоил {tokens} токенов при потолке "
            f"{budget}. Грузим всё равно — но это работа, а не отметка: либо "
            f"поднять потолок осознанно, либо снять загрузчик."
        ]
    return []
