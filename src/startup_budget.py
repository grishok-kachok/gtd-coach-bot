"""Сверка стартовой загрузки с потолком из паспорта памяти.

Паспорт (`config.yaml` мозга, стандарт § 6.3) объявляет, что коуч несёт в каждой
сессии, и ставит этому сумме потолок. Пока никто не считает — это украшение:
ровно так 31.07 выяснилось, что записанные «28 097» были символами, а не
байтами, и потолок 80 000 пробили в день, когда его записали.

Считает тот, кто грузит. У обычного агента Loreground это делает хук комплекта
`startup-load.py`; у коуча грузит код бота, поэтому и сверяет код бота —
подключать вдобавок хук значило бы грузить конституцию дважды (объяснение целиком:
`plugin/hooks/README.md`).

Потолок здесь — сигнализация, а не нож. Пробили — грузим всё равно и говорим
вслух: § 6.3 п. 4 прямо требует, чтобы пробой был работой человека, а не поводом
оставить коуча без памяти. Резать по живому нечем: количество кусков памяти
постоянно, значит выросшая сумма означает ровно одно — выжимки стали
многословнее, и чинить надо промпт выжимки.
"""

from __future__ import annotations

import logging
from pathlib import Path

import yaml

log = logging.getLogger(__name__)


def check(brain_dir: Path, loaded: dict[str, int]) -> str:
    """Сверить фактические размеры с паспортом. Возвращает жалобу или пустую строку.

    `loaded` — что бот реально положил в контекст: {название: байт}. Названия
    должны совпадать с полем `what` в паспорте, иначе сверять нечего и об этом
    говорится отдельно: молчание про несведённую строку читается как «сошлось».
    """
    config = brain_dir / "config.yaml"
    if not config.exists():
        return ""
    try:
        data = yaml.safe_load(config.read_text(encoding="utf-8")) or {}
    except yaml.YAMLError as err:
        return f"паспорт памяти не разбирается: {err}"

    passport = (data.get("startup") or {})
    budget = passport.get("budget")
    declared = {row.get("what"): row.get("size") for row in passport.get("loads") or []}

    beefs = []
    for what, actual in loaded.items():
        if what not in declared:
            beefs.append(f"«{what}» ({actual} Б) грузится, но в паспорте не объявлен")
            continue
        size = declared[what]
        # 15% — не вкус, а природа величин: блок выжимок меняется каждую ночь,
        # и требовать от паспорта точности до байта значило бы переписывать его
        # ежедневно. Уход вдвое так не спрячешь, а именно его мы и ловим.
        if isinstance(size, int) and size and abs(actual - size) > max(200, size * 0.15):
            beefs.append(f"«{what}»: в паспорте {size} Б, на деле {actual} Б")

    # Потолок стоит на ВСЕЙ загрузке, а код меряет только свою часть: конституцию,
    # окно выжимок и сводку дел. Остальное — правила памяти, точку входа, миссию,
    # ценности, горизонты — грузит движок и модель, и байт их код не видит.
    # Считать сумму по одному лишь измеренному значило бы никогда не пробить
    # потолок: недостача в паспорте молча вычиталась бы из перерасхода.
    # Поэтому берём объявленное и подменяем измеренным там, где измерили.
    сведённое = dict(declared)
    сведённое.update({what: actual for what, actual in loaded.items() if what in declared})
    total = sum(v for v in сведённое.values() if isinstance(v, int))
    if isinstance(budget, int) and total > budget:
        beefs.append(
            f"ПОТОЛОК ПРОБИТ: загрузка {total} Б при потолке {budget} Б. "
            "Грузим всё равно — но это работа, а не отметка: либо поднять потолок "
            "осознанно, либо снять загрузчик."
        )
    return "; ".join(beefs)
