# пересказ технической беды словами того, кто в ней не разбирается, — самая
# дорогая часть починки и первое место, где теряются подробности.
#
# Поэтому задача несёт **готовый текст**: скопировал целиком — отправил.
# Текст пишется здесь, рядом с находкой, а не в голове человека.
ШАПКА_АГЕНТУ = "──── Скопируй всё, что ниже, и отправь агенту, который правит код коуча ────"
ХВОСТ_АГЕНТУ = (
    "Цифры выше — находка той ночи, когда задача завелась. Если в задаче есть "
    "комментарии, добавь их тоже: это находки следующих ночей, и в описании их нет."
)


def описание(finding: "Finding", note: str) -> str:
    """Текст карточки: почему дёргаем, что нашли и что переслать агенту."""
    куски = [finding.why, note]
    if finding.агенту:
        куски.append(f"{ШАПКА_АГЕНТУ}\n\n{finding.агенту.strip()}\n\nНаходка: {note}\n\n"
                     f"{ХВОСТ_АГЕНТУ}")
    return "\n\n".join(к for к in куски if к)


