@dataclass(frozen=True)
class Finding:
    """Что фоновая работа нашла и какой задачей это дёргает за рукав."""

    title: str        # ровно эта строка ищется в Todoist — она и есть опознавание
    why: str          # уходит в описание карточки при заведении
    due: str = "сегодня"
    агенту: str = ""  # готовое задание тому, кто правит код коуча; пусто — чинит человек
    размер: str = S   # сколько времени берёт у ЧЕЛОВЕКА, а не сколько идёт работа


# Половина находок чинится не человеком, а сессией Claude Code в папке
