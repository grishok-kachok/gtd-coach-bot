async def _open_task(client: TodoistClient, title: str) -> dict | None:
    """Незакрытая задача ровно с таким названием, если она уже стоит.

    Перебором всех активных задач, а НЕ поиском `search:`. Куплено прогоном
    02.08.2026: две задачи заведены подряд, и `search:` не нашёл ни одной,
    хотя перебор нашёл обе. Указатель поиска у Todoist догоняет реальность
    не сразу — то есть правило «одна задача на копилку, а не на находку»
    молча ломалось ровно в том окне, когда задача только что появилась,
    и именно тогда, когда две находки приходят подряд.

    Признак шире случая, и он уже записан: **чужой сервис отвечает то, что
    он умеет ответить, а не то, что есть на самом деле.** Перебор дороже
    на один запрос и честнее целиком.

    Ищем по названию, а не по метке: метка — ещё одна сущность, за которой
    пришлось бы следить, а название мы задаём сами и оно стабильно.
    """
    try:
        data = await client.get("/tasks", params={"limit": 200})
    except TodoistError as err:
        log.warning("не смог перебрать задачи ради «%s»: %s", title, err)
        raise
    tasks = data.get("results", []) if isinstance(data, dict) else (data or [])
    for task in tasks:
        if (task.get("content") or "").strip() == title:
            return task
    return None


async def _крыша(client: TodoistClient, project: str | None) -> str | None:
    """id карточки-крыши; заводит её при первом обращении. Не вышло — None.

    Восемь технических поводов висели восемью карточками, и человек видел
    россыпь вместо одного дела (просьба владельца 05.08). Теперь у них общая
    крыша, а каждый повод — подзадача под ней: вычёркивается по одной, как
    и было, но глазами читается как одно место.

    **У крыши нет ни даты, ни метки `актив`, и это не небрежность.** Дата
    заставила бы её висеть в «сегодня» вечно; метка без даты уронила бы её
    в «Потеряшки», у которых норма «пусто», — коуч начал бы ругаться
    на собственную карточку. То же правило шире случая и записано
    в методологии: **у карточки-контейнера дата живёт у подзадач.**
    """
    standing = await _open_task(client, КРЫША)
    if standing:
        return standing.get("id")
    payload = {"content": КРЫША, "description": КРЫША_ОПИСАНИЕ}
    if project:
        payload["project_id"] = project
    try:
        созданная = await client.post("/tasks", json=payload)
    except TodoistError as err:
        log.warning("не смог завести карточку-крышу: %s", err)
        return None
    log.info("завёл карточку-крышу «%s»", КРЫША)
    return (созданная or {}).get("id")


async def _project_id(client: TodoistClient, name: str) -> str | None:
    try:
        data = await client.get("/projects", params={"limit": 100})
    except TodoistError as err:
        log.warning("не смог прочитать проекты: %s", err)
        return None
    projects = data.get("results", []) if isinstance(data, dict) else (data or [])
    for project in projects:
        if (project.get("name") or "").strip() == name:
            return project.get("id")
    log.warning("проект «%s» не найден — кладу задачу в Inbox", name)
    return None


async def raise_task(token: str, kind: str, note: str, inbox=None) -> str:
    """Дёрнуть за рукав задачей. Возвращает «создана», «дополнена» или «».

    Пустая строка — значит до Todoist не доехали. Молча глотать нельзя, но
    и ронять ночной прогон из-за недоступного Todoist тоже нельзя: находка
    уже лежит в копилке, задача — второй контур, а не единственный.

    **Поломка попутно ложится на полку входящих** и возвращается в текст задачи
    строкой «случилось N-й раз». До этого у технической находки не было следа
    вовсе: закрыл задачу — истории нет, и каждый случай выглядел первым. Цена
    известна — глухота бота 03.08 опозналась третьим случаем только потому,
    что предыдущие два человек записал в инциденты руками.
    """
    finding = FINDINGS.get(kind)
    if finding is None:
        raise KeyError(f"неизвестный источник фоновой находки: {kind}")

    if inbox is not None and kind in ПОЛОМКИ:
        try:
            случаев = await asyncio.to_thread(inbox.поломка, kind, note)
            if случаев > 1:
                note = f"{note}\n\nСлучилось {случаев}-й раз. " \
                       f"Повтор — признак: чинить надо причину, а не симптом."
        except (sqlite3.Error, ValueError):
            # Полка не ответила — задача всё равно обязана встать: она и была
            # единственным контуром до сегодняшнего дня.
            log.exception("поломка «%s» не легла на полку", kind)

    try:
        async with TodoistClient(token) as client:
            standing = await _open_task(client, finding.title)
            if standing:
                # Маркер и запись в реестр — не украшение: канал комментариев
                # опрашивает Todoist и увидит эту запись как новый комментарий.
                # Свой комментарий приходит с тем же posted_uid, что хозяйский
                # (бот работает токеном пользователя), поэтому по автору его
                # не отличить — см. comments.py.
                комментарий = await client.post(
                    "/comments",
                    json={"task_id": standing["id"], "content": f"{МАРКЕР} {note}"},
                )
                comment_state.запомнить_свой(str((комментарий or {}).get("id") or ""))
                log.info("фоновая находка «%s»: задача уже стоит, дописал комментарий", kind)
                return "дополнена"

            payload = {
                "content": finding.title,
                "description": описание(finding, note),
                "due_string": finding.due,
                "due_lang": "ru",
                # Метки состояния тут нет намеренно: у задачи есть срок
                # (`due_string`), а срок сильнее метки — правило оси состояния
                # с 06.08.2026, этап 21. Раньше бот вешал сюда `актив` и сам себе
                # рисовал отклонение «без размера»: пять его задач из девяти
                # активных были без размера, потому что метку он ставил, а размер
                # (тогда ещё) нет.
                "labels": [finding.размер],
            }
            project = await _project_id(client, PROJECT)
            # Техническое живёт подзадачей под общей крышей, остальное — само
            # по себе. `project_id` подзадаче не шлём: место ей задаёт родитель,
            # и два указания места — это два источника правды у одного факта.
            крыша = await _крыша(client, project) if kind in ПОД_КРЫШЕЙ else None
            if крыша:
                payload["parent_id"] = крыша
            elif project:
                payload["project_id"] = project
            await client.post("/tasks", json=payload)
            log.info("фоновая находка «%s»: завёл %s «%s»", kind,
                     "подзадачу" if крыша else "задачу", finding.title)
            return "создана"
    except TodoistError as err:
        log.error("фоновая находка «%s» не доехала до Todoist: %s", kind, err)
        return ""
    except OSError as err:  # сеть отвалилась — тот же исход, ночной прогон не роняем
        log.error("фоновая находка «%s»: сеть недоступна: %s", kind, err)
        return ""
