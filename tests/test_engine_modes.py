"""Смена режима закрывает разговор и открывает новый.

Иначе переключение не значит ничего: выжимки и файлы стратегии подкладываются
только в ПЕРВЫЙ запрос сессии, и «переключись в полный» посреди разговора дало
бы другую конституцию поверх старого рюкзака — то есть половину переключения,
которая выглядит как целое.
"""

from pathlib import Path

import pytest

from src import modes as режимы_модуль
from src.engine import CoachEngine
from src.sessions import SessionStorage


class Заглушка(CoachEngine):
    """Движок без движка: нас интересует выбор режима и обрыв разговора."""

    def __init__(self, состояние: Path, режим: str):
        self.sessions = SessionStorage(состояние / "session_id")
        self.modes = режимы_модуль.load()
        self._режим = режим
        self.brain_dir = состояние
        self._prompt_cache = {}
        self.обряд = None

    def _settings(self):
        return {"режим": self._режим, "модель_разговора": "claude-fable-5"}


def test_режим_берётся_из_настроек(tmp_path):
    движок = Заглушка(tmp_path, "полный")
    assert движок.режим().имя == "полный"
    assert движок.режим().значок == "🧠"


def test_неизвестный_режим_даёт_рабочий(tmp_path):
    """Молча уехать в дорогой режим из-за опечатки нельзя."""
    assert Заглушка(tmp_path, "полны").режим().имя == "рабочий"


def test_смена_режима_видна(tmp_path):
    движок = Заглушка(tmp_path, "рабочий")
    движок.sessions.save("сессия-1")
    движок.sessions.save_mode("рабочий")
    сменился, режим = движок.сменился_режим()
    assert not сменился

    движок._режим = "полный"
    сменился, режим = движок.сменился_режим()
    assert сменился and режим.имя == "полный"


def test_рестарт_не_рвёт_разговор(tmp_path):
    """Режим сессии переживает перезапуск контейнера — он лежит рядом
    с закладкой. Иначе бот после каждого рестарта считал бы, что режим
    сменился, и рвал бы разговор на ровном месте."""
    движок = Заглушка(tmp_path, "рабочий")
    движок.sessions.save("сессия-1")
    движок.sessions.save_mode("рабочий")

    свежий = Заглушка(tmp_path, "рабочий")   # как после рестарта
    assert свежий.sessions.load() == "сессия-1"
    assert свежий.sessions.mode() == "рабочий"
    сменился, _ = свежий.сменился_режим()
    assert not сменился


def test_старая_закладка_без_режима_разговор_не_рвёт(tmp_path):
    """Первый запуск после выкатки: закладка есть, режима рядом ещё нет.
    Считать это сменой значило бы оборвать живой разговор на выкатке."""
    движок = Заглушка(tmp_path, "рабочий")
    движок.sessions.save("сессия-1")
    assert движок.sessions.mode() is None
    сменился, _ = движок.сменился_режим()
    assert not сменился


def test_сброс_разговора_забывает_и_режим(tmp_path):
    движок = Заглушка(tmp_path, "полный")
    движок.sessions.save("сессия-1")
    движок.sessions.save_mode("полный")
    движок.sessions.clear()
    assert движок.sessions.load() is None and движок.sessions.mode() is None


def test_конституция_режима_склеивается_и_кэшируется(tmp_path):
    движок = Заглушка(tmp_path, "рабочий")
    рабочая = движок._конституция(движок.режим())
    движок._режим = "полный"
    полная = движок._конституция(движок.режим())
    assert len(полная) > len(рабочая)
    # В полном есть раздел сверки со стратегией, в рабочем его нет — на то
    # и режимы: обычный день не платит за то, чем не пользуется.
    assert "Сверяй новую цель со стратегией" in полная
    assert "Сверяй новую цель со стратегией" not in рабочая
    assert len(движок._prompt_cache) == 2


# ── личная надстройка ─────────────────────────────────────────────────────────

НАДСТРОЙКА = "Зови меня Аглаей. После эфиров не грузи — сил нет."


def _положить_надстройку(brain: Path, текст: str) -> Path:
    путь = brain / "память" / "состояние" / "личная-надстройка.md"
    путь.parent.mkdir(parents=True, exist_ok=True)
    путь.write_text(текст, encoding="utf-8")
    return путь


def test_надстройки_нет_это_норма(tmp_path):
    """Большинству дописывать к роли нечего — и коуч от этого не ломается."""
    движок = Заглушка(tmp_path, "рабочий")
    роль = движок._конституция(движок.режим())
    assert роль and "Личная надстройка" not in роль


def test_надстройка_приезжает_после_конституции(tmp_path):
    _положить_надстройку(tmp_path, НАДСТРОЙКА)
    движок = Заглушка(tmp_path, "рабочий")
    роль = движок._конституция(движок.режим())
    assert НАДСТРОЙКА in роль
    # После, а не до: расходится с общей частью — побеждает личное.
    assert роль.index("Личная надстройка") > роль.index("коуч по личной эффективности")


def test_правка_надстройки_работает_со_следующей_реплики(tmp_path):
    """Общая часть кэшируется, личная — нет.

    Иначе «допиши про меня вот это» начинало бы работать только после
    перезапуска бота, а обещано, что работает как ритмы — сразу.
    """
    путь = _положить_надстройку(tmp_path, "первая версия")
    движок = Заглушка(tmp_path, "рабочий")
    assert "первая версия" in движок._конституция(движок.режим())
    путь.write_text("вторая версия", encoding="utf-8")
    роль = движок._конституция(движок.режим())
    assert "вторая версия" in роль and "первая версия" not in роль


def test_пустая_надстройка_не_добавляет_заголовка(tmp_path):
    _положить_надстройку(tmp_path, "   \n\n")
    движок = Заглушка(tmp_path, "рабочий")
    assert "Личная надстройка" not in движок._конституция(движок.режим())


def test_фоновый_прогон_надстройку_не_несёт(tmp_path):
    """У фонового режима роли нет вовсе — надстраивать нечего."""
    _положить_надстройку(tmp_path, НАДСТРОЙКА)
    движок = Заглушка(tmp_path, "рабочий")
    фоновый = движок.modes["фоновый"]
    assert движок._конституция(фоновый) == ""
