"""Ночная сверка оглавления памяти: сирота и битая ссылка.

Валидатор ловит обе беды, но при записи, а запись могла пройти мимо хука —
например, файл приехал `git pull` с другой машины. Раз в сутки проверяем ещё
раз: расхождение обязано находиться не тогда, когда о него споткнутся.

Две беды зеркальные. **Сирота** — файл есть, ссылки нет ниоткуда: найдёт его
только тот, кто уже знает адрес. **Битая ссылка** — вход есть, файла нет.
"""

from pathlib import Path

from src.main import CoachBot


def мозг(tmp_path: Path, индекс: str, файлы: dict[str, str]) -> Path:
    (tmp_path / "память").mkdir()
    (tmp_path / "память" / "00-index.md").write_text(индекс, encoding="utf-8")
    for адрес, текст in файлы.items():
        путь = tmp_path / "память" / адрес
        путь.parent.mkdir(parents=True, exist_ok=True)
        путь.write_text(текст, encoding="utf-8")
    return tmp_path


def сверить(brain: Path) -> tuple[list[str], list[str]]:
    """Тот же разбор, что делает ночной прогон, без похода в Todoist."""
    import re

    память = brain / "память"
    текст = (память / "00-index.md").read_text(encoding="utf-8")
    связанные = set(re.findall(r"\[\[([^\]|#]+)", текст))
    файлы = {п.stem: п for п in память.rglob("*.md") if п.name != "00-index.md"}
    сироты = sorted(и for и, п in файлы.items()
                    if и not in связанные and "выжимки" not in п.parts)
    битые = sorted(и for и in связанные if и not in файлы)
    return сироты, битые


def test_всё_сходится_молчим(tmp_path):
    brain = мозг(tmp_path, "- [[миссия]]\n- [[ритмы]]\n",
                 {"знания/миссия.md": "м", "состояние/ритмы.md": "р"})
    assert сверить(brain) == ([], [])


def test_сирота_ловится(tmp_path):
    brain = мозг(tmp_path, "- [[миссия]]\n",
                 {"знания/миссия.md": "м", "знания/тайна.md": "никто не знает"})
    сироты, битые = сверить(brain)
    assert сироты == ["тайна"] and битые == []


def test_битая_ссылка_ловится(tmp_path):
    brain = мозг(tmp_path, "- [[миссия]]\n- [[призрак]]\n", {"знания/миссия.md": "м"})
    сироты, битые = сверить(brain)
    assert сироты == [] and битые == ["призрак"]


def test_живые_выжимки_битыми_не_считаются(tmp_path):
    """Дефект, пойманный прогоном 02.08.2026: первая версия исключала выжимки
    из списка файлов целиком — и объявила битыми семь живых ссылок."""
    brain = мозг(tmp_path, "- [[миссия]]\n- [[2026-07-27]]\n- [[2026-W30]]\n", {
        "знания/миссия.md": "м",
        "журнал/выжимки/дни/2026-07-27.md": "день",
        "журнал/выжимки/недели/2026-W30.md": "неделя",
    })
    assert сверить(brain) == ([], [])


def test_несвязанная_выжимка_сиротой_не_считается(tmp_path):
    """Файл пишет ночной прогон, список в оглавлении собирает он же чуть позже.
    Между этими мгновениями выжимка законно ничья — тревожить некого."""
    brain = мозг(tmp_path, "- [[миссия]]\n", {
        "знания/миссия.md": "м",
        "журнал/выжимки/дни/2026-08-01.md": "свежая, ещё не в списке",
    })
    assert сверить(brain) == ([], [])


def test_ссылка_с_подписью_и_якорем_разбирается(tmp_path):
    brain = мозг(tmp_path, "- [[миссия|ради чего всё]]\n- [[ритмы#утро]]\n",
                 {"знания/миссия.md": "м", "состояние/ритмы.md": "р"})
    assert сверить(brain) == ([], [])


def test_нет_оглавления_не_роняет_ночной_прогон(tmp_path, caplog):
    import asyncio

    бот = CoachBot.__new__(CoachBot)
    бот.brain_dir = tmp_path
    (tmp_path / "память").mkdir()
    asyncio.run(бот._проверить_оглавление())
    assert "не читается" in caplog.text
