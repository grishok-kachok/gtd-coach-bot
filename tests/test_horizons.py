"""Разбор строгой строки `карточка:` в горизонтах.

Формат читает код, поэтому у него есть тесты: молча не разобравшийся файл
означает «целей нет», а «целей нет» выглядит как «всё в порядке».
"""

from pathlib import Path

from src import horizons

ФАЙЛ = """---
title: горизонты
---

# Горизонты

## ГОД 2026–27

**1. Провести 6 поток.**
Почему главное: обучение — источник дохода.
карточка: нет — до сентября в работу не берём, заведём, когда начнётся.

**2. Автопродукт.**
Цена: делается сразу после закрытия потока.
карточка: * 💰 Автопродукт — автовебинар + продукт 5–10 тыс.

## КВАРТАЛ

**Закрыть 5 поток.**
Тут строки «карточка» нет вовсе.
"""


def _файл(tmp_path: Path, текст: str = ФАЙЛ) -> Path:
    путь = tmp_path / "горизонты.md"
    путь.write_text(текст, encoding="utf-8")
    return путь


def test_имя_карточки_читается_дословно(tmp_path):
    """Дословно — потому что по нему код ищет задачу в Todoist."""
    цели = horizons.читать(_файл(tmp_path))
    assert [ц.карточка for ц in цели if ц.карточка] == [
        "* 💰 Автопродукт — автовебинар + продукт 5–10 тыс."
    ]


def test_нет_с_причиной_это_законный_ответ(tmp_path):
    """Цель может жить в горизонтах без карточки (решение 06.08.2026),
    но причина обязана стоять рядом — иначе карточку заведут заново."""
    цель = horizons.читать(_файл(tmp_path))[0]
    assert цель.без_карточки
    assert "до сентября" in цель.почему_нет


def test_имя_цели_берётся_из_заголовка(tmp_path):
    цели = horizons.читать(_файл(tmp_path))
    assert [ц.имя for ц in цели] == ["Провести 6 поток.", "Автопродукт."]


def test_в_проверку_идут_только_настоящие_имена(tmp_path):
    """`нет` в список имён не попадает: искать в Todoist нечего."""
    assert horizons.имена_карточек(_файл(tmp_path)) == [
        "* 💰 Автопродукт — автовебинар + продукт 5–10 тыс."
    ]


def test_нет_файла_нет_претензий(tmp_path):
    """У ученика на первом запуске целей нет вовсе — это не поломка."""
    assert horizons.читать(tmp_path / "нет-такого.md") == []


def test_строка_без_заголовка_не_считается_целью(tmp_path):
    """Иначе случайная строка «карточка:» в преамбуле стала бы целью-призраком."""
    путь = _файл(tmp_path, "карточка: * Что-то\n\n# Горизонты\n")
    assert horizons.читать(путь) == []
