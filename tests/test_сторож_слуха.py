"""Сторож слуха: бот сам замечает, что оглох, и уходит в перезапуск.

Отдельный тест, потому что беда трижды приходила одинаково и трижды была
незаметна. 03.08.2026 в 20:57 балансир выхода переключил узел, соединение
с Telegram оборвалось на полуслове, и приём обновлений умер насовсем — одна
ошибка, ни одной попытки подняться. Процесс при этом остался жив и продолжал
ГОВОРИТЬ: слал утреннюю сводку и напоминания, healthcheck был зелёный. Глухота
длилась 10,6 часа и вскрылась, только когда владелец написал и не получил ответа.
До этого то же самое было 25.07 (6,5 ч) и 30.07 (10,5 ч).

Отсюда два требования, которые здесь и проверяются: отметка живости обязана
трогать ПРИЁМНУЮ половину (иначе исходящие её маскируют, как маскировал
healthcheck), а протухшая отметка обязана уводить процесс в перезапуск —
Docker поднимет контейнер сам, `restart: unless-stopped`.
"""

import asyncio
from time import monotonic

from src.main import CoachBot, ГЛУХОТА_ПРЕДЕЛ_СЕК, СлышащийТранспорт


def _сторож():
    """Зов сторожа без живого бота: он смотрит только на отметку класса."""
    return asyncio.run(CoachBot.watch_hearing(None, None))


def test_транспорт_отмечает_удачный_ответ(monkeypatch):
    async def ответ(self, *args, **kwargs):
        return 200, b"{}"

    monkeypatch.setattr("telegram.request.HTTPXRequest.do_request", ответ)
    СлышащийТранспорт.последний_успех = 0.0

    транспорт = СлышащийТранспорт.__new__(СлышащийТранспорт)
    asyncio.run(транспорт.do_request("https://example/getUpdates", "POST"))

    assert СлышащийТранспорт.последний_успех > 0


def test_свежая_отметка_процесс_не_трогает(monkeypatch):
    вышел = []
    monkeypatch.setattr("os._exit", lambda код: вышел.append(код))
    monkeypatch.setattr("logging.shutdown", lambda *a: None)
    СлышащийТранспорт.последний_успех = monotonic()

    _сторож()

    assert вышел == []


def test_протухшая_отметка_уводит_в_перезапуск(monkeypatch):
    вышел = []
    monkeypatch.setattr("os._exit", lambda код: вышел.append(код))
    monkeypatch.setattr("logging.shutdown", lambda *a: None)
    СлышащийТранспорт.последний_успех = monotonic() - (ГЛУХОТА_ПРЕДЕЛ_СЕК + 10)

    _сторож()

    assert вышел == [1], "молчание дольше предела обязано уронить процесс"


def test_граница_предела_не_срабатывает_раньше_времени(monkeypatch):
    """Ровно на пределе ещё молчим: срабатывание строго дольше нормы.

    Важно не из аккуратности: сторож, срабатывающий на секунду раньше, при
    каждой сетевой заминке ронял бы живого бота.
    """
    вышел = []
    monkeypatch.setattr("os._exit", lambda код: вышел.append(код))
    monkeypatch.setattr("logging.shutdown", lambda *a: None)
    СлышащийТранспорт.последний_успех = monotonic() - (ГЛУХОТА_ПРЕДЕЛ_СЕК - 5)

    _сторож()

    assert вышел == []
