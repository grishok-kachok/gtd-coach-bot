def test_поломка_копит_счётчик_а_не_записи(полка):
    """Три ночи одной поломки — одна строка со счётчиком, а не три строки."""
    полка.положить(ПОЛОМКА, "ритмы не читаются", ключ="ритмы", день=date(2026, 8, 1))
    полка.положить(ПОЛОМКА, "ритмы не читаются", ключ="ритмы", день=date(2026, 8, 3))
    полка.положить(ПОЛОМКА, "ритмы не читаются", ключ="ритмы", день=date(2026, 8, 5))
    открытые = полка.открытые(ПОЛОМКА)
    assert len(открытые) == 1
    assert открытые[0]["случаев"] == 3
    assert открытые[0]["последний"] == "2026-08-05"
    assert открытые[0]["день"] == "2026-08-01", "день первого случая не переписывается"


