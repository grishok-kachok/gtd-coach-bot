def test_старая_база_доживает_до_новой_колонки(tmp_path):
    """`CREATE TABLE IF NOT EXISTS` молчит о существующей таблице: новая колонка
    в тексте схемы до живой базы не доедет, и код упадёт на первом запросе.

    Тест не выдуманный: полка заведена 05.08.2026, лежит на сервере в одном
    экземпляре и пересозданию не подлежит — колонка «карточка» пришла к ней
    восьмого дня жизни.
    """
    import sqlite3

    путь = tmp_path / "coach.db"
    # База ровно такая, какой её создала прежняя версия кода: без «карточки».
    with sqlite3.connect(путь) as db:
        db.executescript("""
            CREATE TABLE inbox (
                id INTEGER PRIMARY KEY AUTOINCREMENT,
                вид TEXT NOT NULL, день TEXT NOT NULL, создано TEXT NOT NULL,
                текст TEXT NOT NULL, зачем TEXT NOT NULL DEFAULT '',
                ключ TEXT NOT NULL DEFAULT '', случаев INTEGER NOT NULL DEFAULT 1,
                последний TEXT NOT NULL DEFAULT '',
                статус TEXT NOT NULL DEFAULT 'новая', итог TEXT NOT NULL DEFAULT '',
                разобрано TEXT NOT NULL DEFAULT '', вернуться TEXT NOT NULL DEFAULT ''
            );
        """)
        db.execute(
            "INSERT INTO inbox(вид, день, создано, текст) VALUES(?,?,?,?)",
            (ЗАЯВКА, "2026-08-09", "2026-08-09T10:00:00+03:00", "Старая заявка."),
        )

    полка = Inbox(путь)
    assert полка.запись(1)["текст"] == "Старая заявка.", "старые записи потерялись"
    assert полка.запись(1)["карточка"] == "", "колонка не дописалась"
    assert полка.запомнить_карточку(1, "t7")
    assert полка.запись(1)["карточка"] == "t7"


def test_карточка_помнится_только_у_разобранного(полка):
    """`непогашенные` — список для того, кто ходит в Todoist. Открытая запись
    в него не идёт: её карточка — живое дело, а не хвост."""
    открытая = полка.положить(ЗАЯВКА, "Ещё не разбирали.")
    закрытая = полка.положить(ЗАЯВКА, "Уже разобрали.")
    полка.запомнить_карточку(открытая, "t1")
    полка.запомнить_карточку(закрытая, "t2")
    полка.закрыть(закрытая, "сделана", "готово")

    ждут = полка.непогашенные()
    assert [з["id"] for з in ждут] == [закрытая]
    assert ждут[0]["итог"] == "готово", "итог не доедет до комментария в карточке"

    полка.карточка_погашена(закрытая)
    assert полка.непогашенные() == []


def test_пустой_номер_карточки_не_запоминается(полка):
    """Todoist не вернул id — помнить нечего. Пустая строка в базе означала бы
    «карточка есть», и гашение пошло бы стучаться в никуда."""
