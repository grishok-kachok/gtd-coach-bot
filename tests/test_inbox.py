def test_чинили_считает_только_починенное(полка):
    """Второе из двух чисел копилки: сколько раз поломку УЖЕ закрывали.

    Без него копилка не делала того, ради чего заводилась: `случаев` смотрит
    в открытую запись, а вернувшаяся после починки поломка начинает счёт
    с единицы — третий приступ выглядит первым.
    """
    полка.поломка("ритмы", "не читается")
    полка.закрыть(полка.открытые(ПОЛОМКА)[0]["id"], "сделана", "поправил")
    полка.поломка("ритмы", "снова не читается")
    полка.закрыть(полка.открытые(ПОЛОМКА)[0]["id"], "сделана", "поправил ещё раз")
    полка.поломка("ритмы", "и опять")

    assert полка.чинили("ритмы") == 2, "закрытые записи снова не ищутся"
    assert полка.открытые(ПОЛОМКА)[0]["случаев"] == 1, "новый приступ — новый счёт"


def test_чинили_не_путает_поломки_между_собой(полка):
    полка.поломка("ритмы", "не читается")
    полка.закрыть(полка.открытые(ПОЛОМКА)[0]["id"], "сделана", "поправил")
    assert полка.чинили("оглавление") == 0 and полка.чинили("") == 0


