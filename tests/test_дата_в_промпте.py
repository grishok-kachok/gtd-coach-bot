"""Коуч знает, какое сегодня число и какой день недели.

Промах 03.08.2026: коуч сказал «у тебя сегодня и понедельник», хотя понедельник
уже шёл. Дата в контексте была, но нигде не объявлялась вслух, а день недели
не назывался вовсе — модель считала его сама и ошиблась.

Тесты держат ровно две вещи: строка собирается верно (включая тот самый день,
на котором промахнулись) и она доезжает до системного промпта, не застревая
в кэше общей части.
"""

from datetime import datetime
from pathlib import Path

from src import modes as режимы_модуль
from src.engine import CoachEngine, сегодня_строкой


class Заглушка(CoachEngine):
    """Движок без движка: нас интересует только сборка системного промпта."""

    def __init__(self, состояние: Path):
        self.brain_dir = состояние
        self.modes = режимы_модуль.load()
        self._prompt_cache = {}


def test_тот_самый_понедельник():
    """3 августа 2026 — день промаха. Именно он и должен читаться понедельником."""
    assert сегодня_строкой(datetime(2026, 8, 3)) == (
        "Сегодня понедельник, 3 августа 2026 года (2026-08-03)."
    )


def test_все_дни_недели_названы():
    """Неделя 03–09.08.2026 подряд: ни один день не должен выпасть или сдвинуться."""
    ожидаем = ["понедельник", "вторник", "среда", "четверг",
               "пятница", "суббота", "воскресенье"]
    вышло = [сегодня_строкой(datetime(2026, 8, 3 + сдвиг)).split()[1].rstrip(",")
             for сдвиг in range(7)]
    assert вышло == ожидаем


def test_месяц_по_русски():
    """Число и месяц — словами, как их произносит человек, а не 2026-01-01."""
    assert "1 января 2026 года (2026-01-01)" in сегодня_строкой(datetime(2026, 1, 1))
    assert "31 декабря 2026 года (2026-12-31)" in сегодня_строкой(datetime(2026, 12, 31))


def test_дата_доезжает_до_системного_промпта(tmp_path):
    """Промпт без даты — это ровно то состояние, в котором случился промах."""
    движок = Заглушка(tmp_path)
    промпт = движок._конституция(движок.modes["рабочий"])
    assert сегодня_строкой() in промпт


def test_дата_приклеена_последней(tmp_path):
    """Последняя строка читается внимательнее всего — там ей и место."""
    движок = Заглушка(tmp_path)
    промпт = движок._конституция(движок.modes["рабочий"])
    assert промпт.rstrip().endswith(сегодня_строкой())


def test_кэш_даты_не_держит(tmp_path):
    """Процесс живёт неделями. Вчерашнее число из кэша хуже, чем никакого:
    коуч уверенно назвал бы неверный день."""
    движок = Заглушка(tmp_path)
    первый = движок._конституция(движок.modes["рабочий"])
    assert движок._prompt_cache, "общая часть обязана кэшироваться"
    for кусок in движок._prompt_cache.values():
        assert "Сегодня" not in кусок.split("\n")[-1], "дата не должна попасть в кэш"
    assert движок._конституция(движок.modes["рабочий"]) == первый


def test_фоновый_прогон_без_конституции_даты_не_получает(tmp_path):
    """У фонового прогона нет роли и нет разговора — числа он считает кодом."""
    движок = Заглушка(tmp_path)
    пустой = [режим for режим in движок.modes.values()
              if not режимы_модуль.конституция(режим.части)]
    for режим in пустой:
        assert движок._конституция(режим) == ""
