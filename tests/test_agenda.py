"""Сводка дел: агрегат, который уезжает в контекст на КАЖДОМ ходу.

Почему на неё отдельные проверки. Это единственное знание о делах, которое
коуч получает без спроса, и с 03.09.2026 оно приезжает из FINDAY, а не из
Todoist. Пока источник был прежним, никакая просьба в конституции не могла
переехать: код по будильнику сильнее текста, и коуч в каждом ходе говорил про
список, в который человек уже не смотрит.

Проверяется то, что ломается молча:

- сводка не имеет права БРОСИТЬ. Она собирается внутри хода, и исключение здесь
  уносит ответ целиком — человек видит молчание вместо разговора;
- лежащее приложение — это пустая строка, а не выдуманные числа;
- второй запрос (ближайший срок) отдельный: его отказ не должен уносить первую
  строку, которая уже собралась;
- закрытые дела в счёт не идут, иначе коуч спрашивает про сделанное;
- дела без срока не идут в число «дел на сегодня»: их полсписка, и они
  превратили бы счёт в бессмыслицу.
"""

from __future__ import annotations

import asyncio

import httpx
import pytest

from src import agenda, finday

БАЗА = "https://finday.test"
ТОКЕН = "test-token"
НАСТРОЙКИ = {"base_url": БАЗА, "token": ТОКЕН}


@pytest.fixture
def приложение(monkeypatch):
    """Подменяет сеть: маршрут → (код, тело). Значение-исключение — обрыв связи."""

    def настроить(ответы: dict):
        def обработчик(request: httpx.Request) -> httpx.Response:
            ответ = ответы.get(request.url.path)
            if ответ is None:
                return httpx.Response(404, json={"error": "нет такого маршрута"})
            if isinstance(ответ, Exception):
                raise ответ
            код, тело = ответ
            return httpx.Response(код, json=тело)

        транспорт = httpx.MockTransport(обработчик)
        настоящий = httpx.AsyncClient

        def подделка(**kwargs):
            kwargs.pop("trust_env", None)
            return настоящий(transport=транспорт, **kwargs)

        monkeypatch.setattr(finday.httpx, "AsyncClient", подделка)

    return настроить


def сводка() -> str:
    return asyncio.run(agenda.summary(НАСТРОЙКИ))


ДЕНЬ = {
    "date": "3 сентября",
    "weekday": "четверг",
    "tasks": [
        {"id": 1, "title": "Отдать документы", "when": "Вчера (просрочено)",
         "daysLeft": -1, "done": False, "квадрант": "сейчас"},
        {"id": 2, "title": "Купить билеты", "when": "Сегодня",
         "daysLeft": 0, "done": False, "квадрант": "сейчас"},
        {"id": 3, "title": "Разобрать почту", "when": "Сегодня",
         "daysLeft": 0, "done": False, "квадрант": "между-делом"},
        {"id": 4, "title": "Позвонить маме", "when": "Сегодня",
         "daysLeft": 0, "done": True, "квадрант": "планировать"},
        {"id": 5, "title": "Придумать название", "when": "—",
         "daysLeft": None, "done": False, "квадрант": "неразобрано"},
    ],
    "habits": [],
    "money": {"expense": "0 ₽", "income": "0 ₽", "projected": "0 ₽"},
}

ВСЕ_ДЕЛА = {
    "tasks": [
        {"id": 9, "title": "Оплатить хостинг", "when": "5 сентября",
         "daysLeft": 2, "done": False},
        {"id": 10, "title": "Продлить домен", "when": "20 сентября",
         "daysLeft": 17, "done": False},
        {"id": 11, "title": "Старое дело", "when": "1 сентября",
         "daysLeft": -2, "done": True},
    ],
}


def test_считает_сегодняшнее_просроченное_и_горящее(приложение):
    приложение({"/api/v1/today": (200, ДЕНЬ), "/api/v1/tasks": (200, ВСЕ_ДЕЛА)})
    текст = сводка()
    # Два открытых дела на сегодня: закрытое не в счёт, без срока — тоже.
    assert "дел 2" in текст
    assert "«сейчас» — 2" in текст
    assert "Просрочено: 1" in текст
    assert "Без срока висит 1" in текст


def test_ближайший_срок_берётся_из_всего_списка(приложение):
    приложение({"/api/v1/today": (200, ДЕНЬ), "/api/v1/tasks": (200, ВСЕ_ДЕЛА)})
    текст = сводка()
    assert "Оплатить хостинг" in текст, "взято не самое близкое дело"
    assert "Продлить домен" not in текст


def test_лежащее_приложение_даёт_пустоту_а_не_исключение(приложение):
    приложение({"/api/v1/today": httpx.ConnectError("сеть недоступна")})
    assert сводка() == ""


def test_отказ_второго_запроса_не_уносит_первую_строку(приложение):
    """Ближайший срок — приправа к приправе. Его отказ не стоит целой сводки."""
    приложение({"/api/v1/today": (200, ДЕНЬ),
                "/api/v1/tasks": httpx.ConnectError("сеть недоступна")})
    текст = сводка()
    assert "дел 2" in текст
    assert "Ближайший срок" not in текст


def test_без_настроек_молчит(приложение):
    """FINDAY_TOKEN не задан — коуч работает как раньше, а не падает."""
    assert asyncio.run(agenda.summary(None)) == ""


def test_пустой_день_говорит_про_пустоту(приложение):
    приложение({"/api/v1/today": (200, {"tasks": [], "habits": [], "money": {}}),
                "/api/v1/tasks": (200, {"tasks": []})})
    текст = сводка()
    assert "дел 0" in текст
    assert "Просроченного нет" in текст
    # Куда идти за подробностями — названо кнопкой приложения, а не Todoist.
    assert "finday_tasks" in текст
