"""Полка: разговор откладывается на время обряда и возвращается после.

Не «начать новый вместо старого», а закладка: сходил в другую комнату —
вернулся к своей книжке. Старая сессия при этом никуда не девается, движок
хранит её у себя, и `resume` по отложенному id поднимает её как ни в чём
не бывало.
"""

from pathlib import Path

from src import modes as режимы_модуль
from src.engine import CoachEngine
from src.sessions import SessionStorage


def полка(tmp_path: Path) -> SessionStorage:
    return SessionStorage(tmp_path / "session_id")


def test_отложить_и_вернуть(tmp_path):
    с = полка(tmp_path)
    с.save("утренний-разговор")
    с.save_mode("рабочий")

    assert с.отложить() is True
    # Пока идёт обряд, текущего разговора нет — он начнётся с чистого листа
    # и со своей головой.
    assert с.load() is None and с.mode() is None
    assert с.отложено()["session_id"] == "утренний-разговор"

    # Обряд пожил своей жизнью и записал свою закладку.
    с.save("стратсессия")
    с.save_mode("полный")

    assert с.вернуть() == "утренний-разговор"
    assert с.load() == "утренний-разговор" and с.mode() == "рабочий"
    assert с.отложено() is None


def test_полка_переживает_рестарт(tmp_path):
    """Стратсессия идёт час, а контейнер может перезапуститься посреди неё.
    Потерять при этом прежний разговор нельзя."""
    с = полка(tmp_path)
    с.save("утренний-разговор")
    с.save_mode("рабочий")
    с.отложить()

    свежая = полка(tmp_path)          # как после рестарта
    assert свежая.отложено()["session_id"] == "утренний-разговор"
    assert свежая.вернуть() == "утренний-разговор"


def test_обряд_внутри_обряда_не_кладётся(tmp_path):
    """Полка одна. Второе откладывание поверх первого — способ потерять оба."""
    с = полка(tmp_path)
    с.save("первый")
    с.отложить()
    с.save("обряд")
    assert с.отложить() is False
    assert с.отложено()["session_id"] == "первый"   # первый на месте


def test_нечего_откладывать(tmp_path):
    """Обряд начали с чистого листа — возвращаться будет некуда, и это норма."""
    с = полка(tmp_path)
    assert с.отложить() is False
    assert с.отложено() is None
    assert с.вернуть() is None


def test_битая_полка_не_роняет(tmp_path):
    с = полка(tmp_path)
    (tmp_path / "session_id_отложено").write_text("не json", encoding="utf-8")
    assert с.отложено() is None
    assert с.вернуть() is None


# --- обряд перебивает настройку ---


class Заглушка(CoachEngine):
    def __init__(self, состояние: Path, режим: str):
        self.sessions = полка(состояние)
        self.modes = режимы_модуль.load()
        self._режим = режим
        self.brain_dir = состояние
        self._prompt_cache = {}
        self.обряд = None

    def _settings(self):
        return {"режим": self._режим, "модель_разговора": "claude-fable-5"}


def test_обряд_перебивает_настройку(tmp_path):
    """Два разных факта с разным сроком жизни, а не два дома одного.

    «Обычно я работаю в рабочем» живёт месяцами и лежит в мозге. «Сейчас идёт
    стратсессия» живёт час и лежит в состоянии бота. Пока идёт обряд — решает он.
    """
    движок = Заглушка(tmp_path, "рабочий")
    assert движок.режим().имя == "рабочий"

    движок.обряд = "годовой"
    assert движок.режим().имя == "годовой"

    движок.обряд = None
    assert движок.режим().имя == "рабочий"   # настройка не тронута


def test_неизвестный_обряд_не_ломает_режим(tmp_path):
    движок = Заглушка(tmp_path, "полный")
    движок.обряд = "выдуманный"
    assert движок.режим().имя == "полный"
