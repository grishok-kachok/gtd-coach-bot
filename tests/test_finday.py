"""Кнопки FINDAY: что коуч видит в приложении и чем в него записывает.

Проверяется то, что ломается молча:

- имена кнопок и полей латиницей — кириллическое движок принимает и потом
  ошибается на КАЖДОМ ходу, то есть коуч немеет целиком (зонд 02.08.2026);
- необязательные поля не объявлены обязательными — короткая форма схемы делает
  обязательными все, и кнопка отвечает «required property» вместо работы;
- сумма уезжает В КОПЕЙКАХ: 350 ₽ это 35000. Самая предсказуемая будущая
  ошибка, и стоит она испорченного месячного итога;
- отказ приложения возвращается СЛОВАМИ, а не исключением. Кнопка, которая
  бросает, уносит ход целиком, и человек видит молчание вместо ответа;
- отозванный токен назван отдельно: это не поломка, а выключенный доступ,
  и чинит его человек в профиле;
- пустого остатка коуч не выдумывает. Приложение ведёт остаток ОТ названной
  человеком суммы, и «примерно тысяч сорок» здесь хуже, чем «не знаю».
"""

from __future__ import annotations

import asyncio

import httpx
import pytest

from src import finday
from src.finday import build_finday_server

БАЗА = "https://finday.test"
ТОКЕН = "test-token"


def _собрать(сервер) -> dict:
    """Достать объявления кнопок из sdk-сервера, как это делает движок."""
    from mcp.types import ListToolsRequest

    instance = сервер["instance"]
    listed = asyncio.run(
        instance.request_handlers[ListToolsRequest](ListToolsRequest(method="tools/list"))
    ).root.tools
    return {t.name: t for t in listed}


def позвать(сервер, имя, аргументы=None):
    from mcp.types import CallToolRequest, CallToolRequestParams

    instance = сервер["instance"]
    запрос = CallToolRequest(
        method="tools/call",
        params=CallToolRequestParams(name=имя, arguments=аргументы or {}),
    )
    ответ = asyncio.run(instance.request_handlers[CallToolRequest](запрос))
    return "\n".join(ч.text for ч in ответ.root.content)


@pytest.fixture
def запросы():
    return []


@pytest.fixture
def приложение(monkeypatch, запросы):
    """Подменяет сеть: маршрут → (код, тело). Значение-исключение — обрыв связи."""

    def настроить(ответы: dict):
        def обработчик(request: httpx.Request) -> httpx.Response:
            запросы.append(request)
            ответ = ответы.get(request.url.path)
            if ответ is None:
                return httpx.Response(404, json={"error": "нет такого маршрута"})
            if isinstance(ответ, Exception):
                raise ответ
            код, тело = ответ
            return httpx.Response(код, json=тело)

        транспорт = httpx.MockTransport(обработчик)
        настоящий = httpx.AsyncClient

        def подделка(**kwargs):
            # trust_env в мок-транспорте не нужен и не поддерживается вместе с ним.
            kwargs.pop("trust_env", None)
            return настоящий(transport=транспорт, **kwargs)

        monkeypatch.setattr(finday.httpx, "AsyncClient", подделка)
        return build_finday_server(БАЗА, ТОКЕН)

    return настроить


