def test_трата_уходит_в_копейках_и_с_токеном(приложение, запросы):
    сервер = приложение({
        "/api/v1/money/entries": (200, {"entry": {
            "id": 5, "title": "Кофе", "amount": "350 ₽", "category": "Кафе и рестораны",
        }}),
    })
    текст = позвать(сервер, "finday_add_expense", {
        "title": "Кофе", "amount_minor": 35000, "category": "dining",
    })
    assert "Кофе" in текст
    отправлено = запросы[-1]
    assert отправлено.headers["authorization"] == f"Bearer {ТОКЕН}"
    import json

    тело = json.loads(отправлено.content)
    assert тело["amountMinor"] == 35000, "сумма обязана уезжать в копейках"
    assert тело["kind"] == "expense"
    # Кошелёк один: сторона — метка, и по умолчанию личная.
    assert тело["scope"] == "personal"


