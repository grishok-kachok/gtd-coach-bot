def _замысел(id_="p", подзадач=3, дата="2026-08-05", content="* 📦 Замысел"):
    """Карточка с подзадачами; дата — своя, у самой карточки."""
    родитель = {"id": id_, "content": content, "labels": []}
    if дата:
        родитель["due"] = {"date": дата}
    дети = [{"id": f"{id_}-{i}", "content": f"шаг {i}", "parent_id": id_, "labels": []}
            for i in range(подзадач)]
    return [родитель, *дети]


