# ── память сторожа ───────────────────────────────────────────────────────────

def _свод(*строки):
    свод = detectors.Свод()
    свод.отклонения = [detectors.Отклонение("прибор", имя, f"{имя}: беда") for имя in строки]
    return свод


def test_лампочка_дёргает_за_рукав_на_третьи_сутки(tmp_path):
    путь = tmp_path / "coach.db"
    первый = date(2026, 8, 1)
    assert detectors.запомнить(путь, _свод("Просрочено"), первый) == []
    assert detectors.запомнить(путь, _свод("Просрочено"), первый + timedelta(days=1)) == []
    созревшие = detectors.запомнить(путь, _свод("Просрочено"), первый + timedelta(days=2))
    assert [о.имя for о in созревшие] == ["Просрочено"]


def test_задача_поднимается_один_раз_за_приступ(tmp_path):
    путь = tmp_path / "coach.db"
    первый = date(2026, 8, 1)
    for сдвиг in range(3):
        detectors.запомнить(путь, _свод("Просрочено"), первый + timedelta(days=сдвиг))
    ещё = detectors.запомнить(путь, _свод("Просрочено"), первый + timedelta(days=3))
    assert ещё == [], "второй раз за тот же приступ дёргать нельзя"


def test_норма_восстановилась_счёт_обнулился(tmp_path):
    путь = tmp_path / "coach.db"
    первый = date(2026, 8, 1)
    detectors.запомнить(путь, _свод("Просрочено"), первый)
    detectors.запомнить(путь, _свод("Просрочено"), первый + timedelta(days=1))
    detectors.запомнить(путь, detectors.Свод(), первый + timedelta(days=2))  # всё в норме
    # Загорелось снова — счёт начинается заново, а не «уже два дня горело».
    assert detectors.запомнить(путь, _свод("Просрочено"), первый + timedelta(days=3)) == []


def test_мелочь_никогда_не_становится_задачей(tmp_path):
    путь = tmp_path / "coach.db"
    свод = detectors.Свод()
    свод.отклонения = [detectors.Отклонение("мелочь", "Мелочь дня", "на 20 минут")]
    for сдвиг in range(5):
        assert detectors.запомнить(путь, свод, date(2026, 8, 1) + timedelta(days=сдвиг)) == []


