"""Сторож завалов: считает ли он то, что обещает.

Проверяем не «код не упал», а арифметику и границы: перегруз считается против
календаря, а не против суток; цель со сроками у подзадач не объявляется спящей;
лампочка дёргает за рукав на третьи сутки, а не на первые.
"""

from datetime import date, timedelta

import pytest

from src import detectors


@pytest.fixture(autouse=True)
def сегодня(monkeypatch):
    """Фиксируем «сегодня»: тест не должен зависеть от дня прогона."""
    день = date(2026, 8, 3)
    monkeypatch.setattr(detectors, "_сегодня", lambda: день)
    return день


def задача(content, **поля):
    основа = {"id": content, "content": content, "labels": [], "due": None,
              "parent_id": None, "project": "Рабочее"}
    основа.update(поля)
    return основа


def срок(дней: int):
    return {"date": (date(2026, 8, 3) + timedelta(days=дней)).isoformat()}


# ── перегруз ─────────────────────────────────────────────────────────────────

def test_перегруз_считается_против_календаря():
    задачи = [задача(f"дело {i}", labels=["⏱️L"], due=срок(1)) for i in range(2)]  # 8 ч
    найдено = detectors.перегруз(задачи, {"2026-08-04": 2.0})
    assert len(найдено) == 1
    assert "8.0 ч" in найдено[0].строка and "свободно 2.0 ч" in найдено[0].строка
    assert "по календарю" in найдено[0].строка


def test_без_календаря_считаем_от_рабочего_дня_и_говорим_об_этом():
    задачи = [задача(f"дело {i}", labels=["⏱️L"], due=срок(1)) for i in range(3)]  # 12 ч
    найдено = detectors.перегруз(задачи, {})
    assert найдено and "рабочий день без календаря" in найдено[0].строка


def test_день_который_влезает_молчит():
    задачи = [задача("одно", labels=["⏱️M"], due=срок(1))]  # 2 ч при 8 свободных
    assert detectors.перегруз(задачи, {}) == []


def test_свободный_день_по_календарю_не_считается_перегруженным():
    """Восемь часов дел при десяти свободных — это плотный день, а не завал."""
    задачи = [задача(f"дело {i}", labels=["⏱️L"], due=срок(2)) for i in range(2)]
    assert detectors.перегруз(задачи, {"2026-08-05": 10.0}) == []


