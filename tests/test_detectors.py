def _свод(*строки):
    свод = detectors.Свод()
    свод.отклонения = [detectors.Отклонение("прибор", имя, f"{имя}: беда") for имя in строки]
    return свод


def test_лампочка_дёргает_за_рукав_на_третьи_сутки(tmp_path):
    путь = tmp_path / "coach.db"
    первый = date(2026, 8, 1)
    assert detectors.запомнить(путь, _свод("Просрочено"), первый) == []
    assert detectors.запомнить(путь, _свод("Просрочено"), первый + timedelta(days=1)) == []
    созревшие = detectors.запомнить(путь, _свод("Просрочено"), первый + timedelta(days=2))
    assert [о.имя for о in созревшие] == ["Просрочено"]


