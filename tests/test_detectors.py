def test_живая_лампочка_напоминает_через_неделю(tmp_path):
    """Задачу закрыли руками, ничего не починив, — отклонение обязано вернуться.

    До 05.08.2026 отметка «поднято» снималась только при восстановлении нормы:
    человек закрывал задачу, беспорядок оставался, и коуч про него больше
    не напоминал никогда. Дымовая сигнализация с кнопкой «выключить писк».
    """
    путь = tmp_path / "coach.db"
    первый = date(2026, 8, 1)
    for сдвиг in range(3):
        detectors.запомнить(путь, _свод("Просрочено"), первый + timedelta(days=сдвиг))

    # Шесть дней после подъёма — молчим: иначе вернётся тот самый шум,
    # от которого защищались порогом в три дня.
    for сдвиг in range(3, 9):
        assert detectors.запомнить(путь, _свод("Просрочено"), первый + timedelta(days=сдвиг)) == []

    неделя_спустя = detectors.запомнить(путь, _свод("Просрочено"), первый + timedelta(days=9))
    assert [о.имя for о in неделя_спустя] == ["Просрочено"], "лампочка горит, а напоминания нет"


def test_после_напоминания_счёт_идёт_заново(tmp_path):
    """Напомнили — снова неделя тишины, а не каждую ночь подряд."""
    путь = tmp_path / "coach.db"
    первый = date(2026, 8, 1)
    for сдвиг in list(range(3)) + [9]:
        detectors.запомнить(путь, _свод("Просрочено"), первый + timedelta(days=сдвиг))
    assert detectors.запомнить(путь, _свод("Просрочено"), первый + timedelta(days=10)) == []


def test_починенное_и_вернувшееся_считается_новым_приступом(tmp_path):
    """Норма восстановилась — приступ забыт целиком, вместе с отметкой."""
    путь = tmp_path / "coach.db"
    первый = date(2026, 8, 1)
    for сдвиг in range(3):
        detectors.запомнить(путь, _свод("Просрочено"), первый + timedelta(days=сдвиг))
    detectors.запомнить(путь, detectors.Свод(), первый + timedelta(days=3))
    for сдвиг in range(4, 6):
        assert detectors.запомнить(путь, _свод("Просрочено"), первый + timedelta(days=сдвиг)) == []
    созревшие = detectors.запомнить(путь, _свод("Просрочено"), первый + timedelta(days=6))
    assert [о.имя for о in созревшие] == ["Просрочено"], "новый приступ зреет свои три дня"


