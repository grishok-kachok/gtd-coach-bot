def _большая_с_меткой(id_="b", метка="вработе", подзадач=2, дата=None):
    """Большая задача (есть живые подзадачи) с меткой состояния."""
    родитель = {"id": id_, "content": f"* {id_}", "labels": [метка] if метка else [],
                "parent_id": None}
