"""Имя навыка в коде обязано указывать на существующий навык плагина.

Коуч получает имя строкой: «веди по навыку `недельная-стратсессия`». Если такого
навыка нет, ничего не падает — модель просто ведёт разговор по памяти, и со
стороны это выглядит как проведённая стратсессия. Поломки не видно вообще:
ни в логах, ни в ответе.

До этапа 18 квартальная и годовая честно ходили по чужому навыку (месячному),
и это было помечено в коде как времянка. Опасна не времянка, а её тихий
вариант: опечатка в имени или переименованная папка дают тот же результат
без всякой пометки.

Плагина рядом нет — тесты пропускаются с объяснением: склонировать один только
бот законно.
"""

import re

import pytest
import yaml

from src import rituals

from conftest import ПЛАГИН, ПЛАГИН_ИМЕНА

pytestmark = pytest.mark.skipif(
    ПЛАГИН is None,
    reason="плагина рядом нет — искал папки " + ", ".join(ПЛАГИН_ИМЕНА)
    + ". Склонируй gtd-coach соседней папкой, и тесты навыков оживут.",
)

ШАПКА = re.compile(r"\A---\s*\n(.*?)\n---\s*\n", re.DOTALL)


def шапка(файл):
    """Разобранная шапка навыка — именно РАЗБОРОМ, а не регуляркой.

    Первая редакция этого файла доставала имя регуляркой, и она честно его
    доставала даже из шапки, которую YAML прочитать не может. Поймано третьим
    циклом приёмки 08.08.2026: в описании квартальной стояло «эта цель ещё
    жива?»: сверяет…» — двоеточие с пробелом внутри незакавыченной строки
    рвёт разбор. Регулярка этого не видит по устройству, а движок читает
    шапку разбором. Сторож обязан ломаться там же, где сломается движок."""
    текст = файл.read_text(encoding="utf-8")
    совпало = ШАПКА.match(текст)
    assert совпало, f"{файл.parent.name}: шапки нет вовсе"
    try:
        разобрано = yaml.safe_load(совпало.group(1))
    except yaml.YAMLError as беда:
        raise AssertionError(
            f"{файл.parent.name}: шапка не разбирается — {беда}. "
            f"Частая причина: двоеточие с пробелом внутри описания."
        ) from беда
    assert isinstance(разобрано, dict), f"{файл.parent.name}: шапка не словарь"
    return разобрано


def имена_навыков() -> dict[str, str]:
    """Имя навыка → папка, в которой он лежит. Имя берём из шапки файла,
    а не из имени папки: коуч зовёт навык именно по шапке."""
    найдено = {}
    for файл in sorted((ПЛАГИН / "skills").glob("*/SKILL.md")):
        имя = шапка(файл).get("name")
        assert имя, f"{файл.parent.name}: в шапке нет имени"
        найдено[имя] = файл.parent.name
    return найдено


def test_шапка_каждого_навыка_разбирается_и_полна():
    """Движок читает шапку разбором. Битая шапка — это навык, которого нет,
    и узнать об этом неоткуда: ошибки не будет, просто коуч поведёт разговор
    по памяти."""
    for файл in sorted((ПЛАГИН / "skills").glob("*/SKILL.md")):
        д = шапка(файл)
        assert д.get("name"), f"{файл.parent.name}: нет имени"
        assert д.get("description"), f"{файл.parent.name}: нет описания"
        лишние = set(д) - {"name", "description"}
        assert not лишние, f"{файл.parent.name}: лишние ключи {лишние}"


def test_каждый_повод_ведёт_в_существующий_навык():
    навыки = имена_навыков()
    for ключ, повод in rituals.ПОВОДЫ.items():
        assert повод.навык in навыки, (
            f"«{ключ}» зовёт навык «{повод.навык}», а такого в плагине нет. "
            f"Есть: {', '.join(sorted(навыки))}"
        )


def test_ни_одна_стратсессия_не_идёт_по_чужому_навыку():
    """Четыре повода — четыре разных навыка. Общий навык на двоих был
    времянкой до этапа 18 и вернуться не должен."""
    навыки = [повод.навык for повод in rituals.ПОВОДЫ.values()]
    assert len(навыки) == len(set(навыки)), f"навык на двоих: {навыки}"


def test_навыки_стратсессий_помечены_сырыми():
    """Решение владельца 08.08.2026: этап сдаётся без живых прогонов, значит
    каждый навык обязан честно сказать, что не проверен. Пометка снимается
    руками, когда стратсессия прожита вживую, — и тогда падает этот тест,
    напоминая поправить его вместе с пометкой."""
    навыки = имена_навыков()
    for повод in rituals.ПОВОДЫ.values():
        текст = (ПЛАГИН / "skills" / навыки[повод.навык] / "SKILL.md").read_text(
            encoding="utf-8")
        assert "живым разговором не проверен" in текст, (
            f"«{повод.навык}»: нет пометки про сырость")


def test_каждая_стратсессия_собирает_обратную_связь():
    """Без этого шага «докрутим потом» остаётся обещанием: человек не обязан
    помнить, что навык новый, — помнить обязан механизм."""
    навыки = имена_навыков()
    for повод in rituals.ПОВОДЫ.values():
        текст = (ПЛАГИН / "skills" / навыки[повод.навык] / "SKILL.md").read_text(
            encoding="utf-8")
        assert "record_wish" in текст, (
            f"«{повод.навык}»: не кладёт обратную связь на полку")


def test_навыки_не_зашивают_имена_меток_и_мест():
    """Требование владельца 08.08.2026: система в Todoist живая, и навык,
    перечисляющий имена, ломается в ближайший вторник — молча.

    Ловим метки: у них узнаваемая форма `@что-то`. Имена проектов и секций
    так не поймать, их сторожит чтение."""
    навыки = имена_навыков()
    метка = re.compile(r"(?<![\w`])@[а-яёa-z][\w-]*", re.IGNORECASE)
    for повод in rituals.ПОВОДЫ.values():
        текст = (ПЛАГИН / "skills" / навыки[повод.навык] / "SKILL.md").read_text(
            encoding="utf-8")
        найдено = метка.findall(текст)
        assert not найдено, (
            f"«{повод.навык}» зашил метки {найдено}: переименуют — сломается")
