# --- окно памяти по режиму ---


def test_окно_собирается_по_режиму(tmp_path):
    """Фоновому прогону память не нужна вовсе, годовому — двенадцать месяцев.

    Проверяем на живой базе, а не на моке: окно отбирается тремя отдельными
    запросами, и ноль в одном слое обязан означать «этого слоя нет», а не
    «взять все».
    """
    import sqlite3
    from src.archive import Archive

    архив = Archive(tmp_path / "coach.db")
    with sqlite3.connect(архив.path) as db:
        for n in range(1, 10):
            db.execute("INSERT INTO digests(period, period_key, created_at, text) "
                       "VALUES(?,?,?,?)", ("day", f"2026-07-0{n}", "t", f"день {n}"))
        for n in range(1, 8):
            db.execute("INSERT INTO digests(period, period_key, created_at, text) "
                       "VALUES(?,?,?,?)", ("month", f"2025-0{n}", "t", f"месяц {n}"))
        for n in range(1, 4):
            db.execute("INSERT INTO digests(period, period_key, created_at, text) "
                       "VALUES(?,?,?,?)", ("week", f"2026-W0{n}", "t", f"неделя {n}"))

    фон, _ = modes.read(файл(tmp_path, ГОДНЫЙ))
    assert архив.window_rows(фон["фоновый"].окно) == []
    assert архив.recent_digests(фон["фоновый"].окно) == ""

    # Главное здесь — что ключи режима ПОДХОДЯТ архиву. Пока перевода не было,
    # окно уезжало в базу с русскими ключами, ни один запрос не совпадал,
    # и коуч оставался без памяти молча, без единой ошибки в логах.
    рабочее = архив.window_rows(фон["рабочий"].окно)
    assert len(рабочее) == 7 + 3 + 3        # 7 дней, 3 недели из 5, 3 месяца из 7
    assert архив.recent_digests(фон["рабочий"].окно) != ""

    годовое = архив.window_rows(фон["годовой"].окно)
    assert len([1 for период, _, _ in годовое if период == "month"]) == 7
    assert len(годовое) > len(рабочее)      # годовой обязан быть шире рабочего
