"""Состав режимов: строгая схема и сборка рюкзака.

Правило то же, что у ритмов и настроек: файл читает КОД, значит опечатка
обязана ругаться вслух, а не проглатываться. Разница в исходе: у настроек
сломанный файл означает «думаем прежней моделью» и лечится умолчаниями,
а здесь — «неизвестно, что класть коучу в голову». Умолчаний тут нет
намеренно: зашитый в питон запасной состав был бы вторым домом.
"""

import textwrap
from pathlib import Path

import pytest

from src import modes


ГОДНЫЙ = """
```yaml
фоновый:
  значок: "⚙️"
  ставит: код
  повод: ночная работа
  состав:
    конституция: []
    правила_памяти: off
    встроенные_инструменты: off
    память: {дни: 0, недели: 0, месяцы: 0}
    файлы: []
рабочий:
  значок: "🎯"
  ставит: код
  повод: обычный день
  состав:
    конституция: [ядро, память, ритуалы]
    правила_памяти: on
    встроенные_инструменты: on
    память: {дни: 7, недели: 5, месяцы: 3}
    файлы: [горизонты]
полный:
  значок: "🧠"
  ставит: человек
  повод: обзор
  состав:
    конституция: [ядро, память, стратегия, ритуалы]
    правила_памяти: on
    встроенные_инструменты: on
    память: {дни: 7, недели: 5, месяцы: 3}
    файлы: [миссия, ценности, горизонты, профиль]
годовой:
  значок: "🌍"
  ставит: человек
  повод: год
  состав:
    конституция: [ядро, память, стратегия, ритуалы]
    правила_памяти: on
    встроенные_инструменты: on
    память: {дни: 7, недели: 5, месяцы: 12}
    файлы: [миссия, ценности, горизонты, профиль]
```
"""


def файл(tmp_path: Path, текст: str) -> Path:
    путь = tmp_path / "режимы.md"
    путь.write_text(текст, encoding="utf-8")
    return путь


def test_годный_файл_разбирается(tmp_path):
    режимы, беды = modes.read(файл(tmp_path, ГОДНЫЙ))
    assert беды == []
    assert set(режимы) == set(modes.РОДНЫЕ)
    assert режимы["рабочий"].части == ("ядро", "память", "ритуалы")
    assert режимы["фоновый"].встроенные_инструменты is False
    assert режимы["годовой"].окно["month"] == 12
    assert режимы["полный"].человек_ставит is True
    assert режимы["рабочий"].человек_ставит is False


def test_порядок_частей_задаёт_код_а_не_файл(tmp_path):
    """Переставленная в файле строка не должна менять голос коуча.

    Иначе поправленный от руки порядок молча выдавал бы другую конституцию,
    а понять это было бы неоткуда: логи остались бы чистыми.
    """
    криво = ГОДНЫЙ.replace(
        "конституция: [ядро, память, ритуалы]", "конституция: [ритуалы, память, ядро]")
    режимы, беды = modes.read(файл(tmp_path, криво))
    assert беды == []
    assert режимы["рабочий"].части == ("ядро", "память", "ритуалы")


def test_опечатка_в_имени_части_ругается(tmp_path):
    криво = ГОДНЫЙ.replace("конституция: [ядро, память, ритуалы]",
                           "конституция: [ядро, памят, ритуалы]")
