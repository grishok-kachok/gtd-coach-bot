# --- сборка конституции ---


def части(tmp_path: Path) -> Path:
    папка = tmp_path / "конституция"
    папка.mkdir()
    for имя in modes.ЧАСТИ:
        (папка / f"{имя}.md").write_text(f"# {имя}\nтекст {имя}", encoding="utf-8")
    return папка


def test_склейка_в_каноническом_порядке(tmp_path):
    папка = части(tmp_path)
    текст = modes.конституция(("ритуалы", "ядро"), папка)
    assert текст.index("# ядро") < текст.index("# ритуалы")


def test_пустой_состав_даёт_пустую_конституцию(tmp_path):
    assert modes.конституция((), части(tmp_path)) == ""


def test_пропавшая_часть_ругается_громко(tmp_path):
    """Молча упростившийся коуч хуже отсутствующего: он продолжит отвечать,
    просто перестанет быть собой, и понять это будет неоткуда."""
    папка = части(tmp_path)
    (папка / "стратегия.md").unlink()
    with pytest.raises(SystemExit) as упал:
        modes.конституция(("ядро", "стратегия"), папка)
    assert "стратегия" in str(упал.value)


def test_пустая_часть_тоже_ругается(tmp_path):
    папка = части(tmp_path)
    (папка / "ядро.md").write_text("   \n", encoding="utf-8")
    with pytest.raises(SystemExit):
        modes.конституция(("ядро",), папка)


def test_недостающие_части_перечисляются(tmp_path):
    папка = части(tmp_path)
    (папка / "память.md").unlink()
    assert modes.недостающие_части(папка) == ["память"]


