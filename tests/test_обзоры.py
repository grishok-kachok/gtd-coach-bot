"""Обзоры: коуч предлагает, человек решает. И кнопка — это фраза, а не код.

До этапа 17 первого числа код сам ЗАПУСКАЛ месячный итог. Разница не
в вежливости: стратсессия по звонку всё равно не случается, а вот дорогая
голова там, где человек просил «что сегодня», случается вполне.
"""

from datetime import datetime
from zoneinfo import ZoneInfo

from src.main import CoachBot, КЛАВИАТУРА

MSK = ZoneInfo("Europe/Moscow")


def когда(строка: str) -> datetime:
    return datetime.fromisoformat(строка).replace(tzinfo=MSK)


def test_понедельник_предлагает_недельный_обзор():
    повод = CoachBot._повод_обзора(когда("2026-08-03T10:00"))  # понедельник
    assert повод["что"] == "недельный обзор"
    assert повод["режим"] == "полный"
    assert повод["навык"] == "недельный-обзор"


def test_первое_число_предлагает_месячный_итог():
    повод = CoachBot._повод_обзора(когда("2026-09-01T10:00"))  # вторник
    assert повод["что"] == "месячный итог"
    # Подводим ЗАКРЫВШИЙСЯ месяц, а не начавшийся.
    assert повод["повод"] == "месяц 2026-08"


def test_первое_января_предлагает_годовую_и_только_её():
    """Три повода разом читаются как три задачи, хотя это один разговор."""
    повод = CoachBot._повод_обзора(когда("2027-01-01T10:00"))
    assert повод["что"] == "годовую стратсессию"
    assert повод["режим"] == "годовой"
    assert повод["повод"] == "2026 год"


def test_первое_число_в_понедельник_даёт_месячный_а_не_недельный():
    """Первое июня 2026 — понедельник. Предлагаем самый крупный повод."""
    повод = CoachBot._повод_обзора(когда("2026-06-01T10:00"))
    assert повод["что"] == "месячный итог"


def test_обычный_день_повода_не_даёт():
    assert CoachBot._повод_обзора(когда("2026-08-05T10:00")) is None


def test_кнопки_это_фразы_а_не_команды():
    """Кнопка печатает за человека — и всё. Выключил клавиатуру, говоришь
    словами, ничего не сломалось. Скрытый код в кнопке сделал бы её второй
    дверью со своей логикой."""
    надписи = [к.text for ряд in КЛАВИАТУРА.keyboard for к in ряд]
    assert надписи
    for надпись in надписи:
        assert not надпись.startswith("/"), f"«{надпись}» — команда, а не фраза"
        assert len(надпись.split()) >= 2, f"«{надпись}» не похоже на живую фразу"
    # Переключение режима обязано быть среди кнопок: иначе про режимы
    # никто не узнает, и функцией не воспользуется никто.
    assert any("режим" in н.lower() for н in надписи)
