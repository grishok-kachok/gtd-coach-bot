def test_кнопка_доносит_до_обряда_право_включать():
    """Проводка, а не метод. Поймано мутацией 06.08.2026: убрать `из_команды=True`
    в `on_команда` — и все тесты выше остаются зелёными, потому что зовут
    `_переключить_обряд` напрямую. А в жизни кнопка при этом перестаёт работать:
    нажал — ничего не произошло, поломки не видно.
    """
    поймано = {}

    class Сообщение:
        text = "/week"

        @staticmethod
        async def delete():
            return None   # стирание «/week» из ленты — косметика, не наш предмет

    class Апдейт:
        message = Сообщение()
        effective_chat = type("Чат", (), {"id": 7})()

    class Бот:
        owner_id = 7

        @staticmethod
        def _mine(update):
            return True

        @staticmethod
        async def _think_and_reply(text, chat_id, context, **прочее):
            поймано.update(text=text, **прочее)

    asyncio.run(CoachBot.on_команда(Бот(), Апдейт(), None))
    assert поймано.get("из_команды") is True, (
        "кнопка не донесла право включать — обряд по ней не начнётся")
    assert поймано["text"] == ФРАЗЫ_КОМАНД["week"]
