class ПоддельныйБот:
    """Ровно то, что трогает `_переключить_обряд`, и ничего сверх."""

    def __init__(self):
        self.owner_id = 1
        self.включено = None
        self.отправлено = []
        сам = self

        class Сессии:
            @staticmethod
            def отложить():
                return True

        class Режим:
            значок, имя = "🧭", "полный"

        class Движок:
            обряд = ""
            sessions = Сессии()

            @staticmethod
            def начать_обряд(режим, ключ):
                сам.включено = ключ

            @staticmethod
            def режим():
                return Режим()

        self.engine = Движок()

    def _мостик(self, повод):
        return f"<мостик {повод.ключ}>"

    _команда_обряда = staticmethod(CoachBot._команда_обряда)

    async def _закончить_обряд(self, context):
        return ""


class ПоддельныйКонтекст:
    def __init__(self, бот):
        сам = бот

        class Бот:
            @staticmethod
            async def send_message(chat_id, text):
                сам.отправлено.append(text)

        self.bot = Бот()


def _переключить(текст, из_команды):
    бот = ПоддельныйБот()
    мостик = asyncio.run(CoachBot._переключить_обряд(
        бот, текст, ПоддельныйКонтекст(бот), из_команды))
    return бот, мостик


def test_слова_обряд_не_включают_а_подсказывают_команду():
    """Косяк 04.08: разговор ПРО навык включил сам навык. Список ловит слова,
    а не смысл, и «поправить недельный обзор» для него неотличимо от «провести».

    Фраза здесь не дословно из описания задачи («скилл недельного обзора»):
    та в родительном падеже и списком не ловится вовсе — `_норма` приводит
    регистр и знаки, но не падежи. Берём формулировку, которая ловится
    по-настоящему, иначе тест проверял бы пустоту.
    """
    бот, мостик = _переключить("давай поправим недельный обзор в плагине", False)
    assert бот.включено is None, "обряд включился словами"
    assert мостик == "", "мостик выдан без обряда"
    assert len(бот.отправлено) == 1
    assert "сам включить не могу" in бот.отправлено[0].lower()
    assert "/week" in бот.отправлено[0], "подсказана не та команда"


