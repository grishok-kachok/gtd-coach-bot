"""Стратсессии: календарь напоминает, человек включает, код исполняет.

Утренний чек-ин **не подменяется**: у него своя работа — главное дело дня
и обещание. Понедельник и первое число дописывают к нему записку, как свод
завалов. А сам обряд включает код по кнопке или фразе: «включи» обязано
случаться, а обязательное не поручают модели.
"""

from datetime import datetime
from zoneinfo import ZoneInfo

from src import rituals
from src.main import CoachBot, КЛАВИАТУРА, КЛАВИАТУРА_ОБРЯДА

MSK = ZoneInfo("Europe/Moscow")


def когда(строка: str) -> datetime:
    return datetime.fromisoformat(строка).replace(tzinfo=MSK)


# --- напоминание по календарю ---


def test_понедельник_напоминает_про_недельный():
    повод = rituals.по_календарю(когда("2026-08-03T10:00"))
    assert повод.что == "недельный обзор" and повод.режим == "полный"
    assert повод.навык == "недельный-обзор"


def test_первое_число_напоминает_про_месячный():
    повод = rituals.по_календарю(когда("2026-09-01T10:00"))
    assert повод.что == "месячный итог"
    # Подводим ЗАКРЫВШИЙСЯ месяц, а не начавшийся.
    assert CoachBot._словами(когда("2026-09-01T10:00"), повод) == "месяц 2026-08"


def test_первое_января_напоминает_про_годовую_и_только_про_неё():
    """Три напоминания подряд читаются как три задачи, хотя это один разговор."""
    момент = когда("2027-01-01T10:00")
    повод = rituals.по_календарю(момент)
    assert повод.что == "годовую стратсессию" and повод.режим == "годовой"
    assert CoachBot._словами(момент, повод) == "2026 год"


def test_первое_число_в_понедельник_даёт_месячный_а_не_недельный():
    """Первое июня 2026 — понедельник. Напоминаем о самом крупном."""
    assert rituals.по_календарю(когда("2026-06-01T10:00")).что == "месячный итог"


def test_обычный_день_повода_не_даёт():
    assert rituals.по_календарю(когда("2026-08-05T10:00")) is None


# --- включение фразой ---


def test_фраза_включает_обряд():
    assert rituals.по_фразе("Давай проведём недельный обзор").ключ == "недельный"
    assert rituals.по_фразе("подведём месяц").ключ == "месячный"
    assert rituals.по_фразе("Хочу годовую стратсессию").ключ == "годовой"


def test_падежи_и_знаки_не_мешают():
    """Голос приходит с разной пунктуацией и то с «ё», то без."""
    for фраза in ("недельный обзор!", "Итоги недели.", "а давай — разбор недели",
                  "подведем неделю", "подведём неделю"):
        assert rituals.по_фразе(фраза) is not None, фраза


def test_крупный_повод_не_перехватывается_мелким():
    assert rituals.по_фразе("подведём год").ключ == "годовой" \
        or rituals.по_фразе("итоги года").ключ == "годовой"


def test_обычная_реплика_обряд_не_включает():
    for фраза in ("что сегодня?", "оплатил эквайринг", "как дела с Бали",
                  "закинь задачу на неделю"):
        assert rituals.по_фразе(фраза) is None, фраза


def test_кнопки_клавиатуры_реально_включают_обряд():
    """Кнопка печатает фразу — значит она обязана попадать в распознаватель.
    Иначе кнопка нажимается, а ничего не происходит, и это худший исход."""
    надписи = [к.text for ряд in КЛАВИАТУРА.keyboard for к in ряд]
    рабочие = [н for н in надписи if rituals.по_фразе(н)]
    assert рабочие, f"ни одна кнопка не включает обряд: {надписи}"


def test_кнопка_конца_реально_заканчивает_обряд():
    надписи = [к.text for ряд in КЛАВИАТУРА_ОБРЯДА.keyboard for к in ряд]
    assert any(rituals.конец_ли(н) for н in надписи), надписи


def test_конец_обряда_ловится():
    for фраза in ("закончить стратсессию", "Закончили обзор", "выйди из стратсессии"):
        assert rituals.конец_ли(фраза), фраза
    assert not rituals.конец_ли("проведём недельный обзор")


def test_просьба_закончить_не_считается_просьбой_начать():
    """«Закончить обзор» содержит слово «обзор» — но это выход, а не вход."""
    assert rituals.по_фразе("закончить обзор") is None


# --- клавиатуры ---


def test_кнопки_это_фразы_а_не_команды():
    """Кнопка печатает за человека — и всё. Выключил клавиатуру, говоришь
    словами, ничего не сломалось. Скрытый код в кнопке сделал бы её второй
    дверью со своей логикой."""
    for клавиатура in (КЛАВИАТУРА, КЛАВИАТУРА_ОБРЯДА):
        надписи = [к.text for ряд in клавиатура.keyboard for к in ряд]
        assert надписи
        for надпись in надписи:
            assert not надпись.startswith("/"), f"«{надпись}» — команда, а не фраза"
            assert len(надпись.split()) >= 2, f"«{надпись}» не похоже на живую фразу"


def test_во_время_обряда_клавиатура_другая():
    обычные = {к.text for ряд in КЛАВИАТУРА.keyboard for к in ряд}
    обрядовые = {к.text for ряд in КЛАВИАТУРА_ОБРЯДА.keyboard for к in ряд}
    assert обычные != обрядовые
    # Внутри обряда предлагать начать обряд — бессмыслица.
    assert not any(rituals.по_фразе(н) for н in обрядовые)
