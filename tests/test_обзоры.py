"""Стратсессии: календарь напоминает, человек включает, код исполняет.

Утренний чек-ин **не подменяется**: у него своя работа — главное дело дня
и обещание. Понедельник и первое число дописывают к нему записку, как свод
завалов. А сам обряд включает код по кнопке или фразе: «включи» обязано
случаться, а обязательное не поручают модели.
"""

import re
from datetime import datetime
from zoneinfo import ZoneInfo

from src import rituals
from src import settings as coach_settings
from src.main import CoachBot, ВИДНО_ЗНАКОВ, КОМАНДЫ, МОДЕЛИ, ФРАЗЫ_КОМАНД

MSK = ZoneInfo("Europe/Moscow")


def когда(строка: str) -> datetime:
    return datetime.fromisoformat(строка).replace(tzinfo=MSK)


# --- напоминание по календарю ---


def test_понедельник_напоминает_про_недельный():
    повод = rituals.по_календарю(когда("2026-08-03T10:00"))
    assert повод.что == "недельный обзор" and повод.режим == "полный"
    assert повод.навык == "недельный-обзор"


def test_первое_число_напоминает_про_месячный():
    повод = rituals.по_календарю(когда("2026-09-01T10:00"))
    assert повод.что == "месячный итог"
    # Подводим ЗАКРЫВШИЙСЯ месяц, а не начавшийся.
    assert CoachBot._словами(когда("2026-09-01T10:00"), повод) == "месяц 2026-08"


def test_первое_января_напоминает_про_годовую_и_только_про_неё():
    """Три напоминания подряд читаются как три задачи, хотя это один разговор."""
    момент = когда("2027-01-01T10:00")
    повод = rituals.по_календарю(момент)
    assert повод.что == "годовую стратсессию" and повод.режим == "годовой"
    assert CoachBot._словами(момент, повод) == "2026 год"


def test_первое_апреля_напоминает_про_квартальный_а_не_месячный():
    момент = когда("2026-04-01T10:00")
    повод = rituals.по_календарю(момент)
    assert повод.что == "квартальную стратсессию" and повод.режим == "полный"
    # Закрылся первый квартал, а не начался второй.
    assert CoachBot._словами(момент, повод) == "1-й квартал 2026"


def test_первое_января_это_год_а_не_квартал():
    """Первое января — начало и года, и квартала. Напоминаем о крупном."""
    assert rituals.по_календарю(когда("2027-01-01T10:00")).ключ == "годовой"


def test_первое_число_в_понедельник_даёт_месячный_а_не_недельный():
    """Первое июня 2026 — понедельник. Напоминаем о самом крупном."""
    assert rituals.по_календарю(когда("2026-06-01T10:00")).что == "месячный итог"


def test_обычный_день_повода_не_даёт():
    assert rituals.по_календарю(когда("2026-08-05T10:00")) is None


# --- включение фразой ---


def test_фраза_включает_обряд():
    assert rituals.по_фразе("Давай проведём недельный обзор").ключ == "недельный"
    assert rituals.по_фразе("подведём месяц").ключ == "месячный"
    assert rituals.по_фразе("Хочу годовую стратсессию").ключ == "годовой"


def test_падежи_и_знаки_не_мешают():
    """Голос приходит с разной пунктуацией и то с «ё», то без."""
    for фраза in ("недельный обзор!", "Итоги недели.", "а давай — разбор недели",
                  "подведем неделю", "подведём неделю"):
        assert rituals.по_фразе(фраза) is not None, фраза


def test_крупный_повод_не_перехватывается_мелким():
    assert rituals.по_фразе("подведём год").ключ == "годовой" \
        or rituals.по_фразе("итоги года").ключ == "годовой"


def test_обычная_реплика_обряд_не_включает():
    for фраза in ("что сегодня?", "оплатил эквайринг", "как дела с переездом",
                  "закинь задачу на неделю"):
        assert rituals.по_фразе(фраза) is None, фраза


def test_у_каждой_стратсессии_есть_рабочая_команда():
    """Кнопка меню печатает фразу — значит фраза обязана попадать
    в распознаватель. Кнопка нажимается, а ничего не происходит — худший исход:
    поломки не видно, человек решает, что коуч его проигнорировал.

    Проверяем с двух концов сразу. Завёлся новый повод без команды — падаем;
    завелась команда, которую распознаватель не ловит, — тоже падаем."""
    достали = {
        повод.ключ
        for фраза in ФРАЗЫ_КОМАНД.values()
        if (повод := rituals.по_фразе(фраза))
    }
    assert достали == set(rituals.ПОВОДЫ), (
        f"поводы без команды: {set(rituals.ПОВОДЫ) - достали}"
    )


def test_команда_конца_реально_заканчивает_обряд():
    assert rituals.конец_ли(ФРАЗЫ_КОМАНД["end"])


def test_конец_обряда_ловится():
    for фраза in ("закончить стратсессию", "Закончили обзор", "выйди из стратсессии"):
        assert rituals.конец_ли(фраза), фраза
    assert not rituals.конец_ли("проведём недельный обзор")


def test_просьба_закончить_не_считается_просьбой_начать():
    """«Закончить обзор» содержит слово «обзор» — но это выход, а не вход."""
    assert rituals.по_фразе("закончить обзор") is None


# --- меню команд ---


def test_команда_печатает_живую_фразу_а_не_код():
    """Команда печатает за человека — и всё. Снеси меню, говори словами,
    ничего не сломается. Скрытый код за кнопкой сделал бы её второй дверью
    со своей логикой, и разговор перестал бы быть единственным входом."""
    for имя, фраза in ФРАЗЫ_КОМАНД.items():
        assert not фраза.startswith("/"), f"/{имя} печатает команду, а не фразу"
        assert len(фраза.split()) >= 2, f"/{имя}: «{фраза}» не похоже на живую фразу"


def test_имена_команд_телеграм_примет():
    """Кириллицу, заглавные и пробелы телеграм в именах команд отвергает —
    и отвергает молча, оставляя витрину прежней."""
    for имя, описание, _ in КОМАНДЫ:
        assert re.fullmatch(r"[a-z0-9_]{1,32}", имя), имя
        assert описание.strip() and len(описание) <= 256, имя


def test_описание_целиком_влезает_в_экран():
    """Обрезанное описание не видно с мака вообще — только с телефона, и только
    если открыть меню. Значит сторож, а не внимательность: длинную строку
    телеграм примет молча, а человек увидит «Стратегия: миссия, горизо…»."""
    for имя, описание, _ in КОМАНДЫ:
        assert len(описание) <= ВИДНО_ЗНАКОВ, (
            f"/{имя}: {len(описание)} знаков, влезает {ВИДНО_ЗНАКОВ} — "
            f"«{описание[:ВИДНО_ЗНАКОВ]}…» это всё, что увидит человек"
        )


def test_в_витрине_нет_старта():
    """`/start` шлёт сам телеграм по кнопке «Запустить». Обработчик ей нужен,
    строка в меню после первого дня — нет."""
    assert "start" not in {имя for имя, _, _ in КОМАНДЫ}


def test_список_команд_без_повторов():
    имена = [имя for имя, _, _ in КОМАНДЫ] + [имя for имя, _, _ in МОДЕЛИ]
    assert len(имена) == len(set(имена)), имена


# --- выбор модели ---


def test_у_каждой_известной_модели_есть_команда():
    """Список моделей живёт в настройках, команды — в телеграм-канале.
    Разъедутся — и человек либо не сможет выбрать заведённую модель, либо
    выберет несуществующую и бот начнёт падать на каждом ответе."""
    assert {код for _, _, код in МОДЕЛИ} == set(coach_settings.KNOWN_MODELS)


def test_команды_моделей_не_в_витрине():
    """Их печатает сам бот в ответ на /model, и там они кликабельны.
    Витрина из двенадцати пунктов перестаёт читаться."""
    витрина = {имя for имя, _, _ in КОМАНДЫ}
    assert not витрина & {имя for имя, _, _ in МОДЕЛИ}
    assert "model" in витрина


def test_модель_ставится_в_настройки(tmp_path):
    настройки = tmp_path / "память" / "состояние" / "настройки.md"
    настройки.parent.mkdir(parents=True)
    настройки.write_text(
        "# Настройки\n\nПояснение человека, которое трогать нельзя.\n\n"
        '```yaml\nмодель_разговора: "claude-fable-5"   # комментарий человека\n'
        'модель_ночной_работы: "claude-fable-5"\n```\n\nХвост файла.\n',
        encoding="utf-8",
    )
    assert coach_settings.поставить_модель(tmp_path, "claude-opus-5")

    стало = настройки.read_text(encoding="utf-8")
    assert 'модель_разговора: "claude-opus-5"' in стало
    # Ночная модель — отдельная настройка, её не трогаем.
    assert 'модель_ночной_работы: "claude-fable-5"' in стало
    # Файл живой: текст человека и его комментарий переживают правку.
    assert "Пояснение человека, которое трогать нельзя." in стало
    assert "Хвост файла." in стало
    assert "# комментарий человека" in стало


def test_незнакомая_модель_в_настройки_не_попадает(tmp_path):
    """Опечатка в имени превращает бота в падающий на каждом ответе."""
    настройки = tmp_path / "память" / "состояние" / "настройки.md"
    настройки.parent.mkdir(parents=True)
    настройки.write_text('```yaml\nмодель_разговора: "claude-fable-5"\n```\n', encoding="utf-8")
    assert not coach_settings.поставить_модель(tmp_path, "claude-opus-6")
    assert 'claude-fable-5' in настройки.read_text(encoding="utf-8")
