class ПоддельныйTodoist:
    """Минимальный Todoist в памяти: задачи, комментарии, проекты."""

    def __init__(self, tasks=None):
        self.tasks = list(tasks or [])
        self.comments = []
        self.created = []

    def __call__(self, token):  # backstage зовёт TodoistClient(token)
        return self

    async def __aenter__(self):
        return self

    async def __aexit__(self, *exc):
        return False

    async def get(self, path, params=None):
        if path == "/projects":
            return {"results": [{"id": "p1", "name": "Рабочее"}]}
        if path == "/tasks":
            # Перебор, а не поиск: `search:` у Todoist не находит только что
            # созданную задачу (прогон 02.08.2026), и правило «одна задача
            # на копилку» ломалось молча.
            #
            # Закрытые не отдаём: живой `/tasks` возвращает только открытые.
            # Подделка, которая отдаёт закрытые, врёт в удобную сторону —
            # и тест на закрытую мастер-карточку проходил бы по неверной причине.
            return {"results": [з for з in self.tasks if not з.get("checked")]}
        if path == "/tasks/filter":
            raise AssertionError(
                "backstage снова ищет поиском — он врёт на свежих задачах")
        if path.startswith("/tasks/"):
            нужен = path.rsplit("/", 1)[-1]
            for з in self.tasks:
                if str(з.get("id")) == нужен:
                    return з
            from todoist_mcp.client import TodoistError
            raise TodoistError(f"404 нет задачи {нужен}")
        raise AssertionError(f"неожиданный GET {path}")

    @property
    def находки(self):
        """Созданные карточки без служебной мастер-карточки: тесты писались про находки."""
        return [з for з in self.created if з["content"] != backstage.МАСТЕР_КАРТОЧКА]

    async def post(self, path, json=None):
        if path == "/comments":
            self.comments.append(json)
            return {"id": "c1"}
        if path == "/tasks":
            self.created.append(json)
            self.tasks.append({"id": f"t{len(self.tasks) + 1}", "content": json["content"]})
            return self.tasks[-1]
        raise AssertionError(f"неожиданный POST {path}")


