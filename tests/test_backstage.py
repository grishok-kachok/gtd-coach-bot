def подделать_отчёт(monkeypatch, отчёт):
    """Подменить сверку версий: сеть в тестах не трогаем."""
    from src import main as главный

    async def проверить(*_а, **_к):
        return отчёт

    monkeypatch.setattr(главный.versions, "проверить", проверить)
    return главный


