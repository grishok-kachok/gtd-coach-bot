# папку удалили как дубль 08.08, метки не существовало вовсе. Разбор нашёл три
# задачи из пяти и молчал про две. Имена и признак ночной задачи жили в двух
# домах и разъехались; теперь дом один — этот файл, а спрашивают его функцией.


def test_ночные_задачи_отдают_все_поводы(todoist):
    """Имена берутся из FINDINGS, а не переписаны у спрашивающего."""
    for kind in ("промахи", "предложения", "завал", "движок"):
        todoist.tasks.append({"id": kind, "content": backstage.FINDINGS[kind].title})
    ночные = asyncio.run(backstage.ночные_задачи("токен"))
    assert {з["kind"] for з in ночные} == {"промахи", "предложения", "завал", "движок"}


def test_ночные_задачи_не_смотрят_ни_на_метку_ни_на_родителя(todoist):
    """Главное свойство: карточку переименовали, метки нет — задачи всё равно
    находятся. Именно это и сломалось у скилла."""
    todoist.tasks.append({
        "id": "1", "content": backstage.FINDINGS["движок"].title,
        "labels": [], "parent_id": "какая-то-другая-карточка",
    })
    ночные = asyncio.run(backstage.ночные_задачи("токен"))
    assert [з["kind"] for з in ночные] == ["движок"]
    assert ночные[0]["под_мастер_карточкой"] is True


def test_ночные_задачи_отличают_подкарточные_от_самостоятельных(todoist):
    """Разбирающему это нужно: техническое он чинит сам, разговорное —
    отправляет в телеграм. Признак живёт в коде, а не в глазах."""
    for kind in ("промахи", "предложения"):
        todoist.tasks.append({"id": kind, "content": backstage.FINDINGS[kind].title})
    ночные = {з["kind"]: з["под_мастер_карточкой"] for з in asyncio.run(
        backstage.ночные_задачи("токен"))}
    assert ночные == {"промахи": True, "предложения": False}


def test_ночные_задачи_не_тащат_чужое(todoist):
    """У человека сотни своих задач — ни одна не должна попасть в разбор."""
    todoist.tasks.append({"id": "чужая", "content": "Починить диодную ленту"})
    assert asyncio.run(backstage.ночные_задачи("токен")) == []


def test_ночные_задачи_молчат_отказом_а_не_пустотой(todoist, caplog):
    """Todoist не ответил — пустой список плюс запись в лог. Молчаливая пустота
    читается как «ночных задач нет» и врёт хуже отказа."""
    async def падает(path, params=None):
        from todoist_mcp.client import TodoistError
        raise TodoistError("500")
    todoist.get = падает
    with caplog.at_level("ERROR"):
        assert asyncio.run(backstage.ночные_задачи("токен")) == []
    assert any("ночные задачи" in з.getMessage() for з in caplog.records)


