import re as _re

ИНФИНИТИВ = _re.compile(r"^[а-яё]+(ться|тись|ть|ти|чься|чь)$", _re.I)
МУСОР_В_НАЧАЛЕ = _re.compile(r"^[\d\W_]+")


def _первое_слово(имя: str) -> str:
    слова = МУСОР_В_НАЧАЛЕ.sub("", имя).strip().split()
    return слова[0] if слова else ""


