"""Перевозка копилок: три формата, три разбора.

Образцы взяты с живого мозга 05.08.2026 и укорочены. Проверяем то, что молча
теряется при переезде: многострочная заявка (её текст в тридцать строк, и строки
внутри начинаются с `- `), заявка, разобранная абзацем «РАЗОБРАНО» вместо
зачёркивания, и вычеркнутое предложение вместе с припиской «чем кончилось».
"""

from __future__ import annotations

import sys
from datetime import date
from pathlib import Path

import pytest

sys.path.insert(0, str(Path(__file__).resolve().parents[1] / "scripts"))

from перевозка_копилок import (  # noqa: E402
    прочитать,
    перевезти,
    разобрать_заявки,
    разобрать_простую,
)

from src.inbox import ЗАЯВКА, ПРЕДЛОЖЕНИЕ, ПРОМАХ, Inbox  # noqa: E402

ПРЕДЛОЖЕНИЯ = """---
title: предложения-памяти
---

# Что стоит записать в память

> Собирает ночной прогон. Это ВХОДЯЩИЕ, а не память.

Пока пусто — первая ночная находка ляжет сюда сама.

## 2026-07-31

**Со слов пользователя — можно записывать сразу:**
- ~~Loreground в глоссарий~~ — перенесено 2.08.
- ~~Курс «Архитектор» в глоссарий~~

**Выводы коуча — сначала спросить пользователя:**
- «Ставка коуча заводит» — коуч этим пользуется, но в знаниях механики нет.

## 2026-08-04

**Со слов пользователя — можно записывать сразу:**
- Ограничение Todoist: из общего проекта задачу нельзя перенести в личный.
"""

ПРОМАХИ = """---
title: промахи-памяти
---

# Копилка промахов памяти

> Собирает ночной прогон.

## 2026-08-03

- Словарь распознавателя: слово просили добавить 29.07, осело только в дневнике.
- Дата: коуч сказал «сегодня и понедельник», хотя сегодня уже понедельник.
"""

ЗАЯВКИ = """---
title: заявки
---

# Заявки на новые способности коуча

> Собирает сам коуч инструментом record_wish.

## 2026-08-03

- **Словарь Whisper должен собираться из глоссария автоматически.

ТЕКУЩЕЕ УСТРОЙСТВО (проверено в коде):
- /app/src/voice.py, константа БАЗОВЫЙ_СЛОВАРЬ — общие слова.
- Личные слова лежат в настройках.

ЧТО СДЕЛАТЬ:
1. Завести в глоссарии машиночитаемую пометку.**
  Зачем: слова, которые давно просил добавить, в словарь не попали.

**РАЗОБРАНО 2026-08-03: сделано, но не так, как просила заявка.**
Слова берутся из строки `voice` в шапке глоссария — и больше ниоткуда.

## 2026-08-04

- **Убрать автоматический запуск недельного обзора по ключевым словам.**
  Зачем: автозапуск злит, обзор включается только кнопкой.
"""


@pytest.fixture
def журнал(tmp_path):
    папка = tmp_path / "память" / "журнал"
    папка.mkdir(parents=True)
    (папка / "предложения-памяти.md").write_text(ПРЕДЛОЖЕНИЯ, encoding="utf-8")
    (папка / "промахи-памяти.md").write_text(ПРОМАХИ, encoding="utf-8")
    (папка / "заявки.md").write_text(ЗАЯВКИ, encoding="utf-8")
    return папка


def test_шапка_не_считается_находкой():
    """Всё до первого заголовка дня — объяснение копилки, а не записи."""
    разбор = разобрать_простую(ПРЕДЛОЖЕНИЯ, ПРЕДЛОЖЕНИЕ)
    тексты = [з.текст for з in разбор.записи]
    assert not any("ВХОДЯЩИЕ" in т for т in тексты)
    assert len(разбор.записи) == 4


def test_вычеркнутое_приезжает_закрытым_с_итогом():
    разбор = разобрать_простую(ПРЕДЛОЖЕНИЯ, ПРЕДЛОЖЕНИЕ)
    закрытые = [з for з in разбор.записи if з.закрыта]
    assert len(закрытые) == 2
    assert закрытые[0].текст == "Loreground в глоссарий"
    assert закрытые[0].итог == "перенесено 2.08."


def test_вычеркнутое_без_приписки_всё_равно_закрыто():
    """Зачёркивание и было отметкой «разобрано» — итог тогда просто не записали."""
    разбор = разобрать_простую(ПРЕДЛОЖЕНИЯ, ПРЕДЛОЖЕНИЕ)
    без_приписки = [з for з in разбор.записи if з.текст == "Курс «Архитектор» в глоссарий"][0]
    assert без_приписки.закрыта
    assert "итог тогда не записан" in без_приписки.итог


def test_невычеркнутое_приезжает_новым():
    разбор = разобрать_простую(ПРЕДЛОЖЕНИЯ, ПРЕДЛОЖЕНИЕ)
    открытые = [з for з in разбор.записи if not з.закрыта]
    assert len(открытые) == 2
    assert открытые[0].день == date(2026, 7, 31)
    assert открытые[1].день == date(2026, 8, 4)


def test_промахи_разбираются_построчно():
    разбор = разобрать_простую(ПРОМАХИ, ПРОМАХ)
    assert len(разбор.записи) == 2
    assert all(not з.закрыта for з in разбор.записи), "промахи не вычёркивал никто"


def test_многострочная_заявка_приезжает_целиком():
    """Строки внутри заявки начинаются с `- `, но это не отдельные заявки."""
    разбор = разобрать_заявки(ЗАЯВКИ)
    assert len(разбор.записи) == 2, "две заявки, а не восемь строк"
    первая = разбор.записи[0]
    assert "БАЗОВЫЙ_СЛОВАРЬ" in первая.текст, "тело заявки не потерялось"
    assert "ЧТО СДЕЛАТЬ" in первая.текст


def test_заявка_разобрана_абзацем_а_не_зачёркиванием():
    """На заявках правило «разобранное вычёркивай» не соблюдалось ни разу."""
    первая = разобрать_заявки(ЗАЯВКИ).записи[0]
    assert первая.закрыта
    assert "РАЗОБРАНО 2026-08-03" in первая.итог
    assert "voice" in первая.итог, "продолжение итога подклеилось"


def test_зачем_отделяется_от_текста():
    первая = разобрать_заявки(ЗАЯВКИ).записи[0]
    assert первая.зачем.startswith("слова, которые давно просил")
    assert "Зачем:" not in первая.текст


def test_звёздочки_вёрстки_снимаются():
    записи = разобрать_заявки(ЗАЯВКИ).записи
    assert all("**" not in з.текст for з in записи)
    assert all("**" not in з.итог for з in записи)


def test_перевозка_целиком(журнал, tmp_path):
    разбор = прочитать(журнал)
    assert len(разбор.записи) == 8, "4 предложения + 2 промаха + 2 заявки"
    assert разбор.жалобы == []

    полка = Inbox(tmp_path / "coach.db")
    счёт = перевезти(полка, разбор)
    assert счёт["всего"] == 8
    assert счёт["закрытых"] == 3, "два вычеркнутых предложения и одна РАЗОБРАНО-заявка"
    assert полка.сколько() == {ПРЕДЛОЖЕНИЕ: 2, ПРОМАХ: 2, ЗАЯВКА: 1}


def test_повторный_прогон_ничего_не_задваивает(журнал, tmp_path):
    полка = Inbox(tmp_path / "coach.db")
    перевезти(полка, прочитать(журнал))
    счёт = перевезти(полка, прочитать(журнал))
    assert счёт["всего"] == 0


def test_отсутствующий_файл_не_роняет_перевозку(tmp_path):
    """Копилка заводится первой находкой — её может не быть вовсе."""
    пустой = tmp_path / "память" / "журнал"
    пустой.mkdir(parents=True)
    разбор = прочитать(пустой)
    assert разбор.записи == []
    assert len(разбор.жалобы) == 3
