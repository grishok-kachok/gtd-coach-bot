import os
import sys
from pathlib import Path

# Тесты запускаются из папки бота: `.venv/bin/pytest`. Пакет `src` лежит рядом,
# устанавливать его ради этого некуда — в контейнере он тоже просто лежит рядом.
sys.path.insert(0, str(Path(__file__).resolve().parents[1]))

РЯДОМ = Path(__file__).resolve().parents[2]

# ── где искать соседние репозитории ───────────────────────────────────────────
#
# Имя папки задаёт тот, кто клонировал, и совпадать с именем репозитория оно
# не обязано. Пока все репозитории жили в одной рабочей папке, плагин лежал
# под именем `plugin/`, и это имя уехало в тесты как константа. Поймано при
# развёртывании от лица ученика 02.08.2026: он клонирует под настоящим именем
# `gtd-coach`, путь ведёт в пустоту, и шестнадцать тестов падают на ровном месте.
#
# Поэтому не одно имя, а список, и первое существующее побеждает. Переменная
# окружения сильнее любого угадывания: кто задал путь явно, тот знает лучше.
ПЛАГИН_ИМЕНА = ("gtd-coach", "plugin")
TODOIST_ИМЕНА = ("todoist-mcp", "todoist")
CALENDAR_ИМЕНА = ("gcal-mcp", "gcal")


def сосед(имена: tuple[str, ...]) -> Path | None:
    """Первая существующая папка-сосед из списка имён. Нет ни одной — None."""
    for имя in имена:
        путь = РЯДОМ / имя
        if путь.is_dir():
            return путь
    return None


ПЛАГИН = сосед(ПЛАГИН_ИМЕНА)

# Промпты, части конституции и состав режимов живут в плагине. В контейнере он
# смонтирован в /plugin, при работе из исходников лежит соседней папкой. Ставится
# ДО импорта src: путь читается на импорте модуля.
#
# Плагина рядом нет — переменные не ставим вовсе. Тогда `src` возьмёт своё
# умолчание `/plugin`, а тесты, которым плагин нужен, честно пропустятся
# с объяснением, вместо того чтобы падать непонятной ошибкой у человека,
# склонировавшего один только бот.
if ПЛАГИН is not None:
    os.environ.setdefault("PROMPTS_DIR", str(ПЛАГИН / "prompts"))
    os.environ.setdefault("CONSTITUTION_DIR", str(ПЛАГИН / "prompts" / "конституция"))
    os.environ.setdefault("MODES_FILE", str(ПЛАГИН / "режимы.md"))

# Пакеты инструментов — отдельные репозитории (один дом). В контейнере они
# приезжают смонтированными клонами, при работе из исходников лежат соседями.
for имена in (TODOIST_ИМЕНА, CALENDAR_ИМЕНА):
    папка = сосед(имена)
    if папка is not None:
        sys.path.insert(0, str(папка / "src"))
