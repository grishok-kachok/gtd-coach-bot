"""Сигнализация потолка обязана считать ВСЮ загрузку, а не только свою часть.

Дефект, найденный при выполнении этапа 16: код меряет три строки (конституцию,
окно выжимок, сводку дел), а паспорт объявляет восемь — остальное грузят движок
и модель. Сумма только по измеренному никогда не пробила бы потолок: то, что
код не видит, молча вычиталось бы из перерасхода.
"""

from pathlib import Path

import pytest

from src.startup_budget import check


ПАСПОРТ = """
startup:
  budget: 1000
  loads:
    - what: конституция
      size: 300
    - what: правила памяти
      size: 400
    - what: окно выжимок
      size: 200
"""


@pytest.fixture
def мозг(tmp_path):
    (tmp_path / "config.yaml").write_text(ПАСПОРТ, encoding="utf-8")
    return tmp_path


def test_в_норме_молчит(мозг):
    assert check(мозг, {"конституция": 300, "окно выжимок": 200}) == ""


def test_потолок_считается_вместе_с_неизмеряемым(мозг):
    """300 + 200 = 500 влезло бы. Но правила памяти весят 400 — и не влезает."""
    жалоба = check(мозг, {"конституция": 300, "окно выжимок": 500})
    assert "ПОТОЛОК ПРОБИТ" in жалоба
    assert "1200 Б" in жалоба  # 300 + 400 + 500, а не 800


def test_расхождение_с_паспортом_названо(мозг):
    жалоба = check(мозг, {"конституция": 900, "окно выжимок": 200})
    assert "«конституция»: в паспорте 300 Б, на деле 900 Б" in жалоба


def test_незаявленная_строка_не_проходит_молча(мозг):
    assert "в паспорте не объявлен" in check(мозг, {"новая штука": 50})


def test_нет_паспорта_нет_претензий(tmp_path):
    assert check(tmp_path, {"что-то": 100}) == ""


def test_сломанный_паспорт_говорит_вслух(tmp_path):
    (tmp_path / "config.yaml").write_text("startup: {budget: [\n", encoding="utf-8")
    assert "не разбирается" in check(tmp_path, {})
