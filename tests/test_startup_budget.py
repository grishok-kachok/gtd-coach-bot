"""Сигнализация потолка: токены против потолка режима, байты — построчно.

С этапа 17 сторожа два, и это не дубль. Токены отвечают на вопрос «во что
обошёлся режим» и берутся у самой модели; байты по строкам — на другой,
«не врёт ли паспорт про отдельную строку». Именно построчная сверка поймала
«объявлено 69 400, на деле 37 962», и токенами её не заменить: по строкам
модель контекст не разбивает.

Прежняя сумма-по-всему-объявленному ушла вместе с единым потолком. Она была
костылём ровно потому, что мерить приходилось байтами то, что байтами
не меряется: описания 18 кнопок весят 20 КБ, а стоят 241 токен.
"""

from pathlib import Path

import pytest

from src.startup_budget import check


ПАСПОРТ = """
startup:
  budgets:
    фоновый: 20000
    рабочий: 45000
    полный: 65000
  loads:
    - what: конституция
      bytes: 300
    - what: окно выжимок
      bytes: 200
"""


@pytest.fixture
def мозг(tmp_path):
    (tmp_path / "config.yaml").write_text(ПАСПОРТ, encoding="utf-8")
    return tmp_path


def test_в_норме_молчит(мозг):
    жалоба = check(мозг, {"конституция": 300, "окно выжимок": 200},
                   mode="рабочий", tokens=39000)
    assert жалоба == ""


def test_потолок_режима_пробит(мозг):
    жалоба = check(мозг, {"конституция": 300}, mode="рабочий", tokens=46000)
    assert "ПОТОЛОК ПРОБИТ" in жалоба
    assert "рабочий" in жалоба and "46000" in жалоба and "45000" in жалоба


def test_потолок_у_каждого_режима_свой(мозг):
    """Годовой обязан быть дороже рабочего — на то и разные потолки.

    Одно и то же число в разных режимах даёт разный исход: 50 000 для рабочего
    пробой, для полного норма. Единый потолок либо молчал бы про раздутый
    рабочий, либо кричал бы на каждую стратсессию.
    """
    assert "ПОТОЛОК ПРОБИТ" in check(мозг, {}, mode="рабочий", tokens=50000)
    assert check(мозг, {}, mode="полный", tokens=50000) == ""


def test_режим_без_потолка_не_проходит_молча(мозг):
    """Сторож, который не знает своего потолка, показывает спокойствие.

    Это уже покупали трижды («сторож видит не всё, что охраняет»), поэтому
    отсутствие строки в паспорте — само по себе жалоба.
    """
    жалоба = check(мозг, {}, mode="годовой", tokens=70000)
    assert "нет потолка в паспорте" in жалоба and "годовой" in жалоба


def test_без_замера_потолок_не_проверяется(мозг):
    """Нет числа от модели — сверять нечего, и выдумывать его нельзя."""
    assert check(мозг, {}, mode="рабочий", tokens=None) == ""


def test_расхождение_по_строке_названо(мозг):
    жалоба = check(мозг, {"конституция": 900}, mode="рабочий", tokens=100)
    assert "«конституция»: в паспорте 300 Б, на деле 900 Б" in жалоба


def test_незаявленная_строка_не_проходит_молча(мозг):
    жалоба = check(мозг, {"новая штука": 50}, mode="рабочий", tokens=100)
    assert "в паспорте не объявлен" in жалоба


def test_нет_паспорта_нет_претензий(tmp_path):
    assert check(tmp_path, {"что-то": 100}, mode="рабочий", tokens=99999) == ""


def test_сломанный_паспорт_говорит_вслух(tmp_path):
    (tmp_path / "config.yaml").write_text("startup: {budgets: [\n", encoding="utf-8")
    assert "не разбирается" in check(tmp_path, {})


def test_потолок_не_число(tmp_path):
    (tmp_path / "config.yaml").write_text(
        "startup:\n  budgets:\n    рабочий: много\n", encoding="utf-8")
    assert "не число" in check(tmp_path, {}, mode="рабочий", tokens=10)
