"""Длинный текст режется на куски, которые примет телеграм, и режется по смыслу.

Куплено 04.08.2026: расшифровка длинной диктовки уехала в одно сообщение,
телеграм ответил «Message is too long», и отказ уронил обработчик голосового
раньше, чем коуч начинал думать. Человек не получил ни расшифровки, ни ответа,
ни причины — просто тишина.

Старая нарезка тут не спасала: она резала только по переносам строк, а речь
приходит сплошной стеной букв без единого перевода строки. Поэтому проверяется
не «нарезка вообще», а именно поведение на такой стене.

Тексты в фикстурах выдуманные: репозиторий публичный, проверяется механика.
"""

from __future__ import annotations

import pytest

from src.main import CoachBot, TELEGRAM_LIMIT

нарезать = CoachBot._split


def test_короткий_текст_остаётся_одним_куском():
    assert нарезать("Одна фраза.") == ["Одна фраза."]


def test_пустой_текст_не_даёт_пустой_отправки():
    # Телеграм отвергает пустое сообщение, поэтому взамен уходит многоточие.
    assert нарезать("") == ["…"]


def test_стена_букв_без_переносов_всё_равно_режется():
    """Главный случай: ровно на нём отправка и падала."""
    предложение = "Мысль без единого перевода строки. "
    стена = предложение * 400  # заведомо длиннее лимита

    куски = нарезать(стена)

    assert len(куски) > 1
    assert all(len(кусок) <= TELEGRAM_LIMIT for кусок in куски)


def test_режется_по_концу_предложения_а_не_посреди_слова():
    предложение = "Короткая мысль про дела. "
    куски = нарезать(предложение * 400)

    # Каждый кусок, кроме последнего, обязан кончаться концом предложения —
    # иначе человек читает обрубок на половине фразы.
    for кусок in куски[:-1]:
        assert кусок.endswith((".", "!", "?", "…")), кусок[-40:]


@pytest.mark.parametrize(
    "хвост",
    ["Вопрос закончился так?", "Восклицание вот такое!", "Многоточие вот такое…"],
)
def test_границей_считается_не_только_точка(хвост):
    куски = нарезать((хвост + " ") * 400)
    for кусок in куски[:-1]:
        assert кусок.endswith(хвост[-1])


def test_ничего_не_теряется():
    исходный = "Мысль номер один. " * 500
    склеенный = " ".join(нарезать(исходный))
    # Пробелы на швах съедаются намеренно, поэтому сравниваем без них.
    assert склеенный.replace(" ", "") == исходный.replace(" ", "")


def test_текст_с_абзацами_режется_по_абзацам():
    абзац = "Мысль, которая занимает свой абзац и живёт отдельно."
    куски = нарезать("\n".join([абзац] * 200))

    assert all(len(кусок) <= TELEGRAM_LIMIT for кусок in куски)
    # Абзац целиком внутри куска: ни один не разорван переносом посередине.
    for кусок in куски:
        for строка in кусок.split("\n"):
            assert строка == абзац


def test_слово_длиннее_лимита_рубится_по_символам():
    # Ссылка или набор без пробелов: шва нет вообще, но отправка обязана уйти.
    куски = нарезать("я" * (TELEGRAM_LIMIT * 2 + 17))

    assert len(куски) == 3
    assert all(len(кусок) <= TELEGRAM_LIMIT for кусок in куски)
    assert "".join(куски) == "я" * (TELEGRAM_LIMIT * 2 + 17)


def test_html_сущность_не_рвётся_пополам():
    """Экранирование идёт до нарезки, поэтому «&quot;» рубить нельзя.

    Половина сущности приедет в телеграм видимым мусором вместо кавычки.
    """
    # Сплошная лента сущностей без пробелов — резать придётся по символам.
    куски = нарезать("&quot;" * 2000)

    for кусок in куски:
        assert кусок.count("&") == кусок.count(";")
        assert not кусок.endswith("&")


def test_свой_лимит_уважается():
    # Расшифровка режется с запасом на теги рамки, поэтому лимит — параметр.
    куски = нарезать("Мысль про дело. " * 200, 500)
    assert all(len(кусок) <= 500 for кусок in куски)
