"""Фоновый прогон: рычаги режима применяются и переспорить их нельзя.

Пустой список в `tools` — это НЕ «умолчание»: он гасит встроенные инструменты,
а их описания стоят 3 781 токен в каждом запросе. Ровно та же разница
у `setting_sources`: None означает «как настроено у пользователя», то есть
непредсказуемо, а `[]` — «правил памяти нет».

Проверяем именно это различие, потому что до этапа 17 три прогона из четырёх
гасили инструменты, а четвёртый — нет, и никто не мог сказать почему.
"""

from src.backrun import настройки
from src.modes import Режим

ФОН = Режим(имя="фоновый", значок="⚙️", ставит="код", повод="ночь",
            части=(), правила_памяти=False, встроенные_инструменты=False,
            окно={"дни": 0, "недели": 0, "месяцы": 0}, файлы=())

РАЗГОВОР = Режим(имя="рабочий", значок="🎯", ставит="код", повод="день",
                 части=("ядро",), правила_памяти=True, встроенные_инструменты=True,
                 окно={"дни": 7, "недели": 5, "месяцы": 3}, файлы=("горизонты",))


def test_фоновый_гасит_оба_рычага():
    o = настройки(ФОН, system_prompt="роль", model="m")
    assert o.tools == []            # не None: пустой список именно гасит
    assert o.setting_sources == []  # не None: правил памяти нет
    assert o.system_prompt == "роль"


def test_разговорный_режим_ничего_не_гасит():
    o = настройки(РАЗГОВОР, system_prompt="роль", model="m")
    assert o.tools is None
    assert o.setting_sources == ["project"]


def test_свои_рычаги_вызывающего_не_принимаются():
    """Иначе через полгода один прогон снова окажется дороже прочих."""
    o = настройки(ФОН, system_prompt="роль", model="m",
                  tools=["Read", "Write"], setting_sources=["user", "project"])
    assert o.tools == []
    assert o.setting_sources == []


def test_остальное_пробрасывается():
    o = настройки(ФОН, system_prompt="роль", model="m",
                  allowed_tools=["mcp__todoist"], permission_mode="bypassPermissions")
    assert o.allowed_tools == ["mcp__todoist"]
    assert o.permission_mode == "bypassPermissions"
