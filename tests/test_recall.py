"""Инструмент «вспомнить»: два шага — выжимки, потом дословный архив.

Смысловой слой у коуча уже есть, и это выжимки: они написаны смыслом, а не
дословно. Поэтому шаг 1 ищет ДЕНЬ по ним, шаг 2 достаёт из архива реплики
того дня. Векторы отклонены числом, а не вкусом: поиск по всему архиву
занимает миллисекунды.
"""

import sqlite3

from src.archive import Archive
from src.recall import _искать, _собрать


def база(tmp_path):
    архив = Archive(tmp_path / "coach.db")
    with sqlite3.connect(архив.path) as db:
        db.execute(
            "INSERT INTO digests(period, period_key, created_at, text) VALUES(?,?,?,?)",
            ("day", "2026-07-14", "2026-07-15T03:00:00", "Разбирали переезд в Лиссабон и визы."),
        )
        db.execute(
            "INSERT INTO digests(period, period_key, created_at, text) VALUES(?,?,?,?)",
            ("month", "2026-07", "2026-08-01T03:00:00", "Месяц про Лиссабон и запуск курса."),
        )
        for час, роль, текст in (
            ("09:00", "user", "Слушай, а когда вылет на Лиссабон?"),
            ("09:01", "coach", "Билеты на 17 сентября, ты сам называл."),
            ("09:02", "user", "Точно, спасибо."),
        ):
            db.execute(
                "INSERT INTO messages(day, created_at, session_id, role, channel, text) "
                "VALUES(?,?,?,?,?,?)",
                ("2026-07-14", f"2026-07-14T{час}:00", None, роль, "text", текст),
            )
    return архив.path


def test_находит_день_по_выжимке_и_реплики_за_него(tmp_path):
    найдено = _искать(база(tmp_path), "Лиссабон")
    assert найдено["цель"] == "2026-07-14"
    assert len(найдено["реплики"]) == 3
    текст = _собрать("Лиссабон", найдено)
    assert "2026-07-14" in текст and "17 сентября" in текст


def test_названный_день_имеет_приоритет(tmp_path):
    найдено = _искать(база(tmp_path), "Лиссабон", day="2026-07-14")
    assert найдено["цель"] == "2026-07-14"
    assert len(найдено["реплики"]) == 3


def test_ничего_не_нашлось_говорится_прямо(tmp_path):
    найдено = _искать(база(tmp_path), "эквайринг")
    текст = _собрать("эквайринг", найдено)
    assert "ничего нет" in текст
    # Модель обязана сказать «не было», а не сочинить по мотивам.
    assert "не выдумывай" in текст


def test_без_выжимки_ищет_дословно_по_всему_архиву(tmp_path):
    """Выжимка могла не упомянуть слово, а разговор был. Это не «не было»."""
    путь = база(tmp_path)
    with sqlite3.connect(путь) as db:
        db.execute("DELETE FROM digests")
    найдено = _искать(путь, "17 сентября")
    assert not найдено["цель"]
    assert найдено["реплики"] and "17 сентября" in найдено["реплики"][0][2]


def test_пустое_слово_ничего_не_ищет(tmp_path):
    найдено = _искать(база(tmp_path), "   ")
    assert найдено == {"дни": [], "реплики": [], "мс": 0}


def test_поиск_меряет_себя(tmp_path):
    """Признак «пора заводить FTS5» — поиск дольше секунды. Значит время
    должно быть числом, а не ощущением."""
    найдено = _искать(база(tmp_path), "Лиссабон")
    assert isinstance(найдено["мс"], float) and найдено["мс"] >= 0


def test_архив_открывается_только_на_чтение(tmp_path):
    """Инструмент читает архив, а не правит его: у факта один писатель."""
    путь = база(tmp_path)
    with sqlite3.connect(f"file:{путь}?mode=ro", uri=True) as db:
        try:
            db.execute("DELETE FROM messages")
        except sqlite3.OperationalError as err:
            assert "readonly" in str(err).lower()
        else:  # pragma: no cover — сюда попадать не должны
            raise AssertionError("архив открылся на запись")


def test_кнопка_объявлена_латиницей_целиком(tmp_path):
    """Кириллица в объявлении кнопки роняет КАЖДЫЙ ответ коуча.

    Имя кнопки движок хотя бы ругает вслух (SEP-986). А кириллические имена
    ПОЛЕЙ схемы он принимает молча — и возвращает ошибочный результат на каждый
    ход, то есть коуч немеет целиком. Поймано зондом на сервере 02.08.2026:
    поле `слово` падает, оно же `word` работает.

    Проверяем весь набор и все поля, а не одну кнопку: следующая заведётся
    по образцу этой.
    """
    import asyncio

    from mcp.types import ListToolsRequest

    from src.recall import build_recall_server

    сервер = build_recall_server(tmp_path / "coach.db")
    обработчик = сервер["instance"].request_handlers[ListToolsRequest]
    кнопки = asyncio.run(обработчик(ListToolsRequest(method="tools/list"))).root.tools
    assert кнопки
    for кнопка in кнопки:
        assert кнопка.name.isascii(), f"«{кнопка.name}» — имя не латиницей, движок споткнётся"
        for поле in (кнопка.inputSchema.get("properties") or {}):
            assert поле.isascii(), f"поле «{поле}» не латиницей — коуч онемеет молча"
        # А вот описание обязано быть по-русски и говорить, КОГДА звать:
        # описание модель видит в каждом ходу, просьбу в конституции — через раз.
        assert "Зови" in кнопка.description
