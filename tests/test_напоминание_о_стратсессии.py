"""Не предлагать стратсессию, которая уже прошла.

Куплено промахом 24.08.2026: недельная стратсессия была проведена в субботу
22.08 разговором, без команды `/week`. Состояние бота о ней не знало — кнопку
никто не нажимал, — и в понедельник утренний чек-ин предложил её заново.
Ответ был короткий: «я в субботу провёл».

Спрашивать надо у журнала: итог стратсессии ложится туда всегда, независимо
от того, включали обряд кнопкой или нет.
"""

from datetime import date

from src import rituals


def _журнал(корень, *имена):
    папка = корень / "память" / "журнал"
    папка.mkdir(parents=True)
    for имя in имена:
        (папка / имя).write_text("итог", encoding="utf-8")
    return корень


НЕДЕЛЬНЫЙ = rituals.ПОВОДЫ["недельный"]
МЕСЯЧНЫЙ = rituals.ПОВОДЫ["месячный"]


def test_пустой_журнал_не_мешает_напоминать(tmp_path):
    _журнал(tmp_path)
    assert rituals.напоминать_ли(tmp_path, НЕДЕЛЬНЫЙ, date(2026, 8, 24))


def test_нет_папки_журнала_тоже_не_мешает(tmp_path):
    assert rituals.напоминать_ли(tmp_path, НЕДЕЛЬНЫЙ, date(2026, 8, 24))


def test_субботняя_стратсессия_гасит_понедельничное_напоминание(tmp_path):
    _журнал(tmp_path, "2026-08-22-недельная-стратсессия.md")
    assert not rituals.напоминать_ли(tmp_path, НЕДЕЛЬНЫЙ, date(2026, 8, 24))


def test_через_неделю_напоминаем_снова(tmp_path):
    _журнал(tmp_path, "2026-08-22-недельная-стратсессия.md")
    assert rituals.напоминать_ли(tmp_path, НЕДЕЛЬНЫЙ, date(2026, 8, 29))


def test_чужая_стратсессия_своей_не_мешает(tmp_path):
    """Месячная в журнале не отменяет недельного напоминания."""
    _журнал(tmp_path, "2026-08-22-месячная-стратсессия.md")
    assert rituals.напоминать_ли(tmp_path, НЕДЕЛЬНЫЙ, date(2026, 8, 24))


def test_берём_самую_свежую_запись(tmp_path):
    _журнал(
        tmp_path,
        "2026-08-01-недельная-стратсессия.md",
        "2026-08-22-недельная-стратсессия.md",
    )
    assert rituals.когда_проводили(tmp_path, НЕДЕЛЬНЫЙ) == date(2026, 8, 22)


def test_битое_имя_не_роняет_проверку(tmp_path):
    """Файл без даты и с несуществующим числом — просто мимо."""
    _журнал(
        tmp_path,
        "недельная-стратсессия.md",
        "2026-13-40-недельная-стратсессия.md",
    )
    assert rituals.когда_проводили(tmp_path, НЕДЕЛЬНЫЙ) is None


def test_у_каждого_повода_своё_окно():
    """Месячную не предлагают заново через неделю после проведённой."""
    assert МЕСЯЧНЫЙ.окно > НЕДЕЛЬНЫЙ.окно == 7
