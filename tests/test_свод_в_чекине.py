"""Свод обязан доехать до утреннего чек-ина — и не быть принят за реплику.

Куплено 12.08.2026, дважды за одно утро. Сначала `_with_brief` осталась
`@staticmethod`, а внутрь добавили `self.snapshot.db_path` — чек-ин упал
на `NameError`, и сообщения в 10:00 не было вовсе. Потом, когда падение
починили, в своде оказалась карточка «Провести недельную стратсессию» —
и ловушка фраз приняла НАЗВАНИЕ ЗАДАЧИ за просьбу человека: вместо главного
дела дня пришла подсказка «жми /week».

Общее у обоих: прогон был зелёный, потому что дорогу чек-ина не проходил
ни один тест. Тесты ниже идут ею.
"""

import asyncio
from pathlib import Path
from types import SimpleNamespace

from src import detectors, main


def _бот(db_path: Path):
    """Бот, урезанный до того, что нужно подкладке: путь к базе."""
    return SimpleNamespace(snapshot=SimpleNamespace(db_path=db_path))


def _свод(имя="Просрочено"):
    свод = detectors.Свод()
    свод.отклонения = [detectors.Отклонение("прибор", имя, f"{имя}: беда")]
    return свод


def test_свод_подкладывается_к_промпту(tmp_path):
    текст = main.CoachBot._with_brief(
        _бот(tmp_path / "coach.db"), "промпт утра", _свод()
    )
    assert текст.startswith("промпт утра")
    assert "Просрочено: беда" in текст


def test_пустой_свод_оставляет_промпт_нетронутым(tmp_path):
    prompt = "промпт утра"
    assert main.CoachBot._with_brief(
        _бот(tmp_path / "coach.db"), prompt, detectors.Свод()
    ) == prompt


# ── ловушка фраз не смотрит на служебный текст ───────────────────────────────

ЧЕКИН_СО_СВОДОМ = (
    "Наступило утро — время утреннего чек-ина.\n\n"
    "- Без метки сферы 2 шт.: «Провести недельную стратсессию», «Разобрать "
    "предложения памяти». [висит 4-е сутки]"
)


class ПоддельныйБот:
    """Телеграм, который только запоминает отправленное."""

    def __init__(self):
        self.sent = []

    async def send_message(self, chat_id, text, **_):
        self.sent.append(text)


def _бот_с_обрядами(телеграм):
    return SimpleNamespace(
        engine=SimpleNamespace(обряд=False),
        owner_id=1,
        _команда_обряда=main.CoachBot._команда_обряда,
    ), SimpleNamespace(bot=телеграм)


def test_название_задачи_в_своде_не_считается_просьбой():
    """Свод сочинил код, а не человек: подсказки быть не должно."""
    телеграм = ПоддельныйБот()
    бот, context = _бот_с_обрядами(телеграм)
    мостик = asyncio.run(main.CoachBot._переключить_обряд(
        бот, ЧЕКИН_СО_СВОДОМ, context, сочинил_код=True,
    ))
    assert мостик == ""
    assert телеграм.sent == [], "коуч влез с подсказкой в свой же чек-ин"


def test_те_же_слова_от_человека_подсказку_дают():
    """Обратная сторона: живая реплика по-прежнему получает подсказку."""
    телеграм = ПоддельныйБот()
    бот, context = _бот_с_обрядами(телеграм)
    мостик = asyncio.run(main.CoachBot._переключить_обряд(
        бот, "давай проведём недельную стратсессию", context,
    ))
    assert мостик == ""
    assert len(телеграм.sent) == 1
    assert "/week" in телеграм.sent[0]
